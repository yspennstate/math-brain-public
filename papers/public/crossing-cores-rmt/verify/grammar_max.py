"""Maximum volume over the grammar class, for r far beyond exhaustive reach.

Proposition (closed evaluation) makes p_T a polynomial integral for every
word generated by

    W ::= w_r | WW | aWa ,

so the maximum over the whole class at a given number of pairs can be
computed by enumerating trees, with no polytope work.  The class contains
the conjectured extremals at every size (the two-square chains omega_l),
so this is a direct test of the 4/9 bound well past r = 7.

Reducedness, carefully: read cyclically, the word aWa puts the two
endpoints of a at positions 0 and 2|W|+1, which are ADJACENT in a cyclic
word of length 2|W|+2 -- so a top-level nesting is an ear and the word
is NOT a reduced core (its volume equals p_T(W), exactly as ear deletion
says).  Nesting is legitimate only inside a concatenation, where the
other factor separates the two endpoints.  The maximum below is
therefore taken over words whose top level is a single cycle or a
concatenation of at least two factors; nesting may occur inside factors.

Run:  python -u grammar_max.py [rmax]
"""
import sys
from fractions import Fraction as Fr
from math import comb
from functools import lru_cache

def pmul(a, b):
    out = [Fr(0)] * (len(a) + len(b) - 1)
    for i, u in enumerate(a):
        if u:
            for j, v in enumerate(b):
                if v:
                    out[i + j] += u * v
    return out

def pint01(p):
    return sum(c / (i + 1) for i, c in enumerate(p))

@lru_cache(maxsize=None)
def cycle_poly(r):
    p = [Fr(0)] * (r + 1)
    p[0] += Fr(2, r)
    p[r] -= Fr(1, r)
    for k in range(r + 1):
        p[k] -= Fr(comb(r, k) * (-1) ** k, r)
    return tuple(p)

def profiles(r, memo):
    """All distinct profiles of grammar words with exactly r pairs."""
    if r in memo:
        return memo[r]
    out = set()
    if r >= 2:
        out.add(cycle_poly(r))
    for a in range(2, r - 1):
        b = r - a
        if b < 2:
            continue
        for pa in profiles(a, memo):
            for pb in profiles(b, memo):
                out.add(tuple(pmul(list(pa), list(pb))))
    if r >= 3:
        for pin in profiles(r - 1, memo):
            out.add((pint01(list(pin)),))
    memo[r] = out
    return out

def reduced_profiles(r, memo):
    """Top level is a single cycle, or a concatenation of >= 2 factors."""
    out = set()
    if r >= 2:
        out.add(cycle_poly(r))
    for a in range(2, r - 1):
        b = r - a
        if b < 2:
            continue
        for pa in profiles(a, memo):
            for pb in profiles(b, memo):
                out.add(tuple(pmul(list(pa), list(pb))))
    return out

def main():
    rmax = int(sys.argv[1]) if len(sys.argv) > 1 else 12
    memo = {}
    FOURNINTHS = Fr(4, 9)
    print(" r   distinct profiles   max p_T over reduced words   vs 4/9")
    for r in range(2, rmax + 1):
        ps = reduced_profiles(r, memo)
        if not ps:
            continue
        best = max(pint01(list(p)) for p in ps)
        flag = ("= 4/9" if best == FOURNINTHS else
                ("EXCEEDS 4/9 ***" if best > FOURNINTHS else "< 4/9"))
        print(f" {r:2d}   {len(ps):8d}            {str(best):<20} {flag}",
              flush=True)

if __name__ == "__main__":
    main()

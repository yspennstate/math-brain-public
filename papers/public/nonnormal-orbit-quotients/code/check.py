"""Exact checks for the finite-group facts used in the paper.

Python 3, standard library only.  Permutations of {0,...,m-1} are tuples p with
p[i] the image of i; (p*q)(i) = p[q[i]].

For F = S_3 (m = 3) and F = A_m (4 <= m <= 7), acting naturally on m letters:
  1. F has the expected order and acts transitively;
  2. the stabiliser H of the letter 0 has index m, is nontrivial and is not normal;
  3. every normal subgroup K of F with [F:K] dividing m has K = F, so every
     homomorphism from F to a group of order m is trivial;
  4. the right cosets H x are m in number and every one of them is represented
     by an element of F (so the orbit quotient of the paper is K_m).
Also checked: the number of reduced words of length j in the free product of two
groups with a nonidentity elements each is 2 a^j (j <= 4, a = 1, 2, 3), and the
degree bound 2t(t+14), t = 2(a + a^2 + a^3), equals 200880 for F = S_3.
"""
from itertools import permutations, product


def mul(p, q):
    return tuple(p[i] for i in q)


def inv(p):
    r = [0] * len(p)
    for i, pi in enumerate(p):
        r[pi] = i
    return tuple(r)


def parity(p):
    seen, sign = set(), 0
    for i in range(len(p)):
        if i in seen:
            continue
        j, length = i, 0
        while j not in seen:
            seen.add(j)
            j = p[j]
            length += 1
        sign ^= (length - 1) & 1
    return sign


def group(m, alternating):
    return [p for p in permutations(range(m)) if not alternating or parity(p) == 0]


def conj_classes(G):
    left, classes = set(G), []
    while left:
        g = next(iter(left))
        cl = {mul(mul(x, g), inv(x)) for x in G}
        classes.append(frozenset(cl))
        left -= cl
    return classes


def closure(gens, e):
    S = {e}
    frontier = [e]
    gens = list(gens)
    while frontier:
        new = []
        for s in frontier:
            for g in gens:
                t = mul(s, g)
                if t not in S:
                    S.add(t)
                    new.append(t)
        frontier = new
    return frozenset(S)


def normal_subgroups(G, e):
    """All normal subgroups: every one is generated by a union of classes."""
    classes = conj_classes(G)
    found = {frozenset([e])}
    frontier = [frozenset([e])]
    while frontier:
        new = []
        for N in frontier:
            for c in classes:
                if c <= N:
                    continue
                M = closure(set(N) | set(c), e)
                if M not in found:
                    found.add(M)
                    new.append(M)
        frontier = new
    return found


def check_template(m, alternating):
    e = tuple(range(m))
    G = group(m, alternating)
    order = len(G)
    expect = 1
    for k in range(2, m + 1):
        expect *= k
    if alternating:
        expect //= 2
    assert order == expect, (m, order)
    assert {g[0] for g in G} == set(range(m)), "not transitive"
    H = [g for g in G if g[0] == 0]
    assert order // len(H) == m and len(H) > 1
    Hs = set(H)
    nonnormal = any(mul(mul(x, h), inv(x)) not in Hs for x in G for h in H)
    assert nonnormal
    cosets = {frozenset(mul(h, x) for h in H) for x in G}
    assert len(cosets) == m
    assert sum(len(c) for c in cosets) == order
    Ns = normal_subgroups(G, e)
    bad = [N for N in Ns if len(N) < order and m % (order // len(N)) == 0]
    assert not bad, (m, [order // len(N) for N in bad])
    return order, len(H), sorted(order // len(N) for N in Ns)


def reduced_words(a, j):
    """Count words x1...xj, letters nonidentity elements of factor 0 or 1
    (a of each), consecutive letters from different factors."""
    count = 0
    for factors in product((0, 1), repeat=j):
        if all(factors[i] != factors[i + 1] for i in range(j - 1)):
            count += a ** j
    return count


def main():
    out = []
    for m, alt in [(3, False), (4, True), (5, True), (6, True), (7, True)]:
        name = ("A%d" if alt else "S%d") % m
        order, h, indices = check_template(m, alt)
        out.append(f"{name}: |F|={order}, |H|={h}, [F:H]={m}, H not normal, "
                   f"indices of normal subgroups {indices}: none divides {m} except 1  ok")
    for a in (1, 2, 3):
        for j in range(1, 5):
            assert reduced_words(a, j) == 2 * a ** j
    out.append("reduced words of length j in a free product of two factors with a "
               "nonidentity elements: 2 a^j for a<=3, j<=4  ok")
    a = 5
    t = 2 * (a + a * a + a ** 3)
    assert t == 310 and 2 * t * (t + 14) == 200880
    out.append(f"S3*S3: a=5, t={t}, degree bound 2t(t+14)={2 * t * (t + 14)}  ok")
    out.append("ALL CHECKS PASS")
    print("\n".join(out))


if __name__ == "__main__":
    main()

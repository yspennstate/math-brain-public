"""Propose the Condition-2varfn slab schedule for the kappa-interval
program: partition the certified strip into pilot-sized slabs, with
each slab's alpha and q windows hulled from the strip certificates it
covers (plus outward padding), and emit both the schedule CSV and a
queue script in the margins-queue conventions.

The widths are a PROPOSAL: uniform by default, halved in the two
neighborhoods the margin evidence marks as hard (the thin Region-I
band near kappa = 0.05, the approach to the +0.19 wall).  Each slab is
meant to be preceded by the pre-flight spot-check before its 3-4h
certified run; a slab whose pre-flight fails gets split, not forced.

Usage: python make_slab_schedule.py [width]      (default 0.028)
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, 'results')
PAD_A = 5e-7        # outward alpha padding beyond the hulled windows
PAD_Q = 2e-3        # outward q padding


def load_strip():
    rows = []
    for name in ('certified_intervals.csv', 'certified_intervals_nak.csv'):
        p = os.path.join(R, name)
        if not os.path.exists(p):
            continue
        with open(p, newline='') as fh:
            rows += list(csv.DictReader(fh))
    rows.sort(key=lambda r: float(r['kappa_lo']))
    return rows


def hard(k):
    """Half-width neighborhoods: thin Region-I margins near 0.05, and
    the weakening contraction toward the +0.19 wall."""
    return (0.02 <= k <= 0.08) or (k >= 0.10)


def main(width):
    strip = load_strip()
    lo = min(float(r['kappa_lo']) for r in strip)
    hi = max(float(r['kappa_hi']) for r in strip)
    slabs = []
    k = lo
    import slab_windows
    while k < hi - 1e-12:
        w = width / 2 if hard(k) else width
        k2 = min(k + w, hi)
        # windows() hulls alpha from the interval CSVs and (q, psi)
        # from the box records' located enclosures, refusing gaps; the
        # emitted queue then runs the pilot in direct-enclosure mode
        # (the locator fails at these widths - aggregation replaces it)
        win = slab_windows.windows(k, k2)
        win['kappa_lo'] = round(k, 6)
        win['kappa_hi'] = round(k2, 6)
        slabs.append(win)
        k = k2
    out = os.path.join(R, 'slab_schedule_2varfn.csv')
    with open(out, 'w', newline='') as fh:
        wtr = csv.DictWriter(fh, fieldnames=list(slabs[0].keys()))
        wtr.writeheader()
        wtr.writerows(slabs)
    qs = [
        '#!/bin/bash',
        '# Generated by make_slab_schedule.py: the 2varfn kappa-slab',
        '# queue.  Same conventions as queue_margins2.sh; run the',
        '# pre-flight spot-check on a slab before starting it.',
        'set -o pipefail',
        'cd "$(dirname "$0")"',
        'VENV=${VENV:-python}',
        'nw() { echo "${WORKERS:-4}"; }',
        'run() {  # klo khi alo ahi qlo qhi psilo psihi',
        '  echo "=== slab [$1, $2] (workers $(nw)) $(date -u +%H:%M:%S)"',
        '  nice -n 12 $VENV pilot_2varfn.py --kappa-lo "$1" --kappa-hi "$2" \\',
        '    --ktag "slab" --alpha-lo "$3" --alpha-hi "$4" \\',
        '    --q-lo "$5" --q-hi "$6" --psi-lo "$7" --psi-hi "$8" \\',
        '    --stages sweep,region1,supplement,starint,stage2,assemble \\',
        '    --workers "$(nw)"',
        '  echo "=== slab [$1, $2] exit $? $(date -u +%H:%M:%S)"',
        '}',
    ]
    for s in slabs:
        qs.append('run %s %s %s %s %s %s %s %s' % (
            s['kappa_lo'], s['kappa_hi'], s['alpha_lo'], s['alpha_hi'],
            s['q_lo'], s['q_hi'], s['psi_lo'], s['psi_hi']))
    qout = os.path.join(HERE, 'queue_slabs_2varfn.sh')
    with open(qout, 'w', newline='\n') as fh:
        fh.write('\n'.join(qs) + '\n')
    widths = [s['kappa_hi'] - s['kappa_lo'] for s in slabs]
    print('%d slabs over [%.3f, %.3f]; widths %.4f..%.4f; '
          'alpha windows %.2e..%.2e wide'
          % (len(slabs), lo, hi, min(widths), max(widths),
             min(float(s['alpha_hi']) - float(s['alpha_lo']) for s in slabs),
             max(float(s['alpha_hi']) - float(s['alpha_lo']) for s in slabs)))
    print('wrote %s and %s' % (out, qout))


if __name__ == '__main__':
    main(float(sys.argv[1]) if len(sys.argv) > 1 else 0.028)

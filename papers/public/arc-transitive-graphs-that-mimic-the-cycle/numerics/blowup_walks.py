"""Numerical companion to "Arc-transitive graphs that mimic the cycle" (Aldous-Fill Open Problem 7.27).

Exact (rational) mean hitting times, the parameters tau*, tau_0, tau_2 of Aldous and Fill, and an
arc-transitivity check, for the lexicographic products C_m[K_r-bar] and for blow-ups H[K_r-bar] of other
arc-transitive graphs H.  Everything is exact except the eigenvalues, which are compared to closed forms
in floating point.

Usage: python blowup_walks.py            (writes results.md and ../figures/ratio.pdf)
"""
from fractions import Fraction
import itertools, math, sys, os
import numpy as np

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))

# ---------------------------------------------------------------- graphs
def cycle(m):
    return [{(i - 1) % m, (i + 1) % m} for i in range(m)]

def blowup(adj, r):
    """H[K_r-bar]: vertex (u,a) ~ (v,b) iff u ~ v in H."""
    N = len(adj)
    idx = lambda u, a: u * r + a
    out = [set() for _ in range(N * r)]
    for u in range(N):
        for v in adj[u]:
            for a in range(r):
                for b in range(r):
                    out[idx(u, a)].add(idx(v, b))
    return out

def petersen():
    V = list(itertools.combinations(range(5), 2))
    return [{j for j, w in enumerate(V) if not set(v) & set(w)} for v in V]

def complete(N):
    return [set(range(N)) - {i} for i in range(N)]

def cube(d):
    return [{i ^ (1 << k) for k in range(d)} for i in range(2 ** d)]

def complete_bipartite(a, b):
    return [set(range(a, a + b)) for _ in range(a)] + [set(range(a)) for _ in range(b)]

# ---------------------------------------------------------------- exact hitting times
def hitting_times(adj):
    """h[v][w] = E_v T_w for simple random walk, exact rationals, by solving (I - P) h = 1 off the target."""
    n = len(adj)
    H = [[Fraction(0)] * n for _ in range(n)]
    for w in range(n):
        others = [v for v in range(n) if v != w]
        pos = {v: k for k, v in enumerate(others)}
        A = [[Fraction(0)] * (n - 1) for _ in range(n - 1)]
        b = [Fraction(1)] * (n - 1)
        for v in others:
            A[pos[v]][pos[v]] += 1
            for u in adj[v]:
                if u != w:
                    A[pos[v]][pos[u]] -= Fraction(1, len(adj[v]))
        x = solve(A, b)
        for v in others:
            H[v][w] = x[pos[v]]
    return H

def solve(A, b):
    n = len(A)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = next(r for r in range(c, n) if M[r][c] != 0)
        M[c], M[p] = M[p], M[c]
        piv = M[c][c]
        M[c] = [x / piv for x in M[c]]
        for r in range(n):
            if r != c and M[r][c] != 0:
                f = M[r][c]
                M[r] = [x - f * y for x, y in zip(M[r], M[c])]
    return [M[i][n] for i in range(n)]

def params(adj, H=None):
    """tau* = max commute time, tau_0 = sum_i sum_j pi_i pi_j E_i T_j (uniform pi for regular graphs)."""
    n = len(adj)
    if H is None:
        H = hitting_times(adj)
    tau_star = max(H[i][j] + H[j][i] for i in range(n) for j in range(n) if i != j)
    tau0 = sum(H[i][j] for i in range(n) for j in range(n)) / Fraction(n * n)
    return tau_star, tau0

def tau2(adj):
    """Relaxation time 1/(1 - lambda_2), lambda_2 the second largest eigenvalue of P (floating point)."""
    n = len(adj)
    P = np.zeros((n, n))
    for v in range(n):
        for u in adj[v]:
            P[v, u] = 1 / len(adj[v])
    ev = np.sort(np.linalg.eigvalsh((P + P.T) / 2))[::-1]
    return 1 / (1 - ev[1]), ev

# ---------------------------------------------------------------- arc-transitivity (orbit of one arc)
def arc_orbit_size(m, r):
    """Orbit of the arc ((0,0),(1,0)) under the group generated by the rotation, the reflection and the
    transposition of the first two vertices of every fibre, acting on C_m[K_r-bar]; the graph has 2 m r^2 arcs."""
    gens = []
    gens.append(lambda p: ((p[0] + 1) % m, p[1]))
    gens.append(lambda p: ((-p[0]) % m, p[1]))
    for i in range(m):
        gens.append(lambda p, i=i: (p[0], (1 - p[1]) if (p[0] == i and p[1] < 2) else p[1]))
    start = ((0, 0), (1, 0))
    seen = {start}; frontier = [start]
    while frontier:
        nxt = []
        for arc in frontier:
            for g in gens:
                img = (g(arc[0]), g(arc[1]))
                if img not in seen:
                    seen.add(img); nxt.append(img)
        frontier = nxt
    return len(seen)

def main():
    lines = ["# Results of blowup_walks.py", ""]
    # 1. C_m[K_2-bar]
    lines += ["## 1. The graphs C_m[K_2-bar]", "",
              "| m | n | tau* | formula 2 floor(m^2/4)+2m | tau_0 | formula (m^2-1)/6+m | tau*/(2 tau_0) | tau_2 | 1/(1-cos 2pi/m) | arc orbit / 8m |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    ratios = []
    for m in [5, 6, 7, 9, 11, 15, 21, 31]:
        adj = blowup(cycle(m), 2)
        H = hitting_times(adj)
        ts, t0 = params(adj, H)
        # check g(j) = j(m-j)+m and twin = 2m
        ok = all(H[2 * i + a][0] == (min(i, m - i) * (m - min(i, m - i)) + m if i else 2 * m) for i in range(m) for a in range(2) if (i, a) != (0, 0))
        f_ts = 2 * (m * m // 4) + 2 * m
        f_t0 = Fraction(m * m - 1, 6) + m
        t2, ev = tau2(adj)
        f_t2 = 1 / (1 - math.cos(2 * math.pi / m))
        orb = arc_orbit_size(m, 2) if m <= 15 else None
        ratios.append((m, float(ts / (2 * t0))))
        lines.append(f"| {m} | {2*m} | {ts} | {f_ts} {'ok' if ts == f_ts else 'MISMATCH'} | {t0} | {f_t0} {'ok' if t0 == f_t0 else 'MISMATCH'} | {float(ts/(2*t0)):.4f} | {t2:.4f} | {f_t2:.4f} | {orb if orb is not None else '-'}/{8*m} |")
        assert ok, f"hitting formula failed at m={m}"
        assert ts == f_ts and t0 == f_t0
        assert abs(t2 - f_t2) < 1e-9
        if orb is not None:
            assert orb == 8 * m
    lines.append("")
    lines.append("Every row: g(j) = j(m-j)+m and the twin value 2m reproduced exactly; the arc orbit is the whole arc set.")
    # 2. general r and the neighbour check n-1
    lines += ["", "## 2. C_m[K_r-bar]: neighbours hit in n-1 steps, tau* = 2 floor(m^2/4) + 2(r-1)m, tau_0 = (m^2-1)/6 + (r-1)m", "",
              "| m | r | n | E_v T_w for an edge | n-1 | tau* | formula | tau_0 | formula | tau_2 | tau_2(C_m) |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for m, r in [(5, 3), (7, 3), (7, 4), (9, 2), (9, 3), (11, 4)]:
        adj = blowup(cycle(m), r)
        H = hitting_times(adj)
        ts, t0 = params(adj, H)
        edge = H[0][r]  # (0,0) -> (1,0)
        f_ts = 2 * (m * m // 4) + 2 * (r - 1) * m
        f_t0 = Fraction(m * m - 1, 6) + (r - 1) * m
        t2, _ = tau2(adj); t2c, _ = tau2(cycle(m))
        lines.append(f"| {m} | {r} | {m*r} | {edge} | {m*r-1} | {ts} | {f_ts} | {t0} | {f_t0} | {t2:.4f} | {t2c:.4f} |")
        assert edge == m * r - 1 and ts == f_ts and t0 == f_t0 and abs(t2 - t2c) < 1e-9
    # 3. the blow-up identities on other regular graphs
    lines += ["", "## 3. Blow-ups H[K_r-bar] of other regular graphs: E T = h_H + (r-1)N off the fibre, r N on the fibre; tau_2 = max(tau_2(H), 1)", "",
              "| H | N | r | max |E T - (h_H + (r-1)N)| off fibre | twin value | rN | tau*(G) | max(tau*(H)+2(r-1)N, 2rN) | tau_0(G) | tau_0(H)+(r-1)N | tau_2(G) | max(tau_2(H),1) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    tests = [("K_4", complete(4)), ("K_2", complete(2)), ("Q_3", cube(3)), ("Petersen", petersen()), ("K_{3,3}", complete_bipartite(3, 3)), ("C_6", cycle(6))]
    for name, Hadj in tests:
        N = len(Hadj)
        hH = hitting_times(Hadj)
        tsH, t0H = params(Hadj, hH)
        t2H, _ = tau2(Hadj)
        for r in [2, 3]:
            G = blowup(Hadj, r)
            hG = hitting_times(G)
            tsG, t0G = params(G, hG)
            t2G, _ = tau2(G)
            dev = max(abs(hG[u * r + a][v * r + b] - (hH[u][v] + (r - 1) * N)) for u in range(N) for v in range(N) if u != v for a in range(r) for b in range(r))
            twin = {hG[u * r + a][u * r + b] for u in range(N) for a in range(r) for b in range(r) if a != b}
            lines.append(f"| {name} | {N} | {r} | {dev} | {sorted(twin)} | {r*N} | {tsG} | {max(tsH + 2*(r-1)*N, 2*r*N)} | {t0G} | {t0H + (r-1)*N} | {t2G:.4f} | {max(t2H,1):.4f} |")
            assert dev == 0 and twin == {r * N} and tsG == max(tsH + 2 * (r - 1) * N, 2 * r * N) and t0G == t0H + (r - 1) * N and abs(t2G - max(t2H, 1)) < 1e-9
    lines.append("")
    lines.append("All identities hold exactly (rational arithmetic) on every test graph; the relaxation times agree to 1e-9.")
    open(os.path.join(HERE, "results.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    # figure
    try:
        import matplotlib; matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        ms = list(range(5, 62, 2))
        rat = [(2 * (m * m // 4) + 2 * m) / (2 * ((m * m - 1) / 6 + m)) for m in ms]
        fig, ax = plt.subplots(figsize=(4.6, 3.0))
        ax.plot(ms, rat, "o-", ms=3, label=r"$C_m[\overline{K}_2]$")
        ax.axhline(1.5, color="gray", lw=0.8, ls="--")
        ax.axhline(1.0, color="gray", lw=0.8, ls=":")
        ax.set_xlabel(r"$m$"); ax.set_ylabel(r"$\tau^*/(2\tau_0)$")
        ax.set_ylim(0.9, 1.6); ax.legend(frameon=False)
        fig.tight_layout()
        os.makedirs(os.path.join(HERE, "..", "figures"), exist_ok=True)
        fig.savefig(os.path.join(HERE, "..", "figures", "ratio.pdf"))
        print("figure written")
    except Exception as e:
        print("figure skipped:", e)

if __name__ == "__main__":
    main()

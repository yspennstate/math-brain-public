"""Recompute, from records/ only, the quantities listed in DATA_ADDITIONS.md (2026-09-16).

DERIVED output, not raw records: every number here is a function of the JSON files in ../../records
and can be regenerated by running this script from the paper directory. Nothing is read from the box.

    python records_additions/derived/recompute_from_records.py

Writes one JSON per family into records_additions/derived/ and prints a short summary.
"""
import collections
import glob
import json
import math
import os
import statistics as st

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REC = os.path.normpath(os.path.join(HERE, "..", "..", "records"))
OUT = HERE


def load(pattern):
    out = []
    for f in sorted(glob.glob(os.path.join(REC, pattern))):
        out.append(json.load(open(f, encoding="utf-8")))
    return out


def mse(v):
    v = list(v)
    return (st.mean(v), (st.stdev(v) / math.sqrt(len(v))) if len(v) > 1 else 0.0, len(v))


def msd(v):
    v = list(v)
    return (st.mean(v), st.stdev(v) if len(v) > 1 else 0.0, len(v))


def dump(name, obj):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=1)
    print("wrote", name)


# ----------------------------------------------------------------------------- moments by row law
def moments():
    agg = collections.defaultdict(list)
    for j in load("p9m*.json") + load("p9r_*.json"):
        law = j.get("rowlaw") or "veronese"          # p9_moments.py default is veronese (line 36)
        for r in j["records"]:
            agg[(law, j["d"])].append(r)
    cat = {2: 2.0, 3: 5.0, 4: 14.0, 5: 42.0}
    key = {2: "m4", 3: "m6", 4: "m8", 5: "m10"}
    rows = []
    for (law, d), rs in sorted(agg.items(), key=lambda kv: (kv[0][0], kv[0][1])):
        row = {"rowlaw": law, "d": d, "n": len(rs)}
        for k in ("m4", "m6", "m8", "m10", "edge"):
            m, se, _ = mse(x[k] for x in rs)
            row[k] = m; row[k + "_se"] = se
        ks = [x["ks_semicircle"] for x in rs if "ks_semicircle" in x]
        if ks:
            row["ks_semicircle"], row["ks_semicircle_se"], row["ks_n"] = mse(ks)
        rows.append(row)
    # mixture check: what the paper's table_moments (no rowlaw filter) prints
    mix = collections.defaultdict(list)
    for (law, d), rs in agg.items():
        mix[d] += [x["m4"] for x in rs]
    mixture = {str(d): {"n": len(v), "m4_mixed": st.mean(v)} for d, v in sorted(mix.items())}
    # fits on the pure Veronese ladder
    ds = sorted(d for (law, d) in agg if law == "veronese")
    fits = {}
    for k in (2, 3, 4, 5):
        D = np.array(ds, float)
        Y = np.array([st.mean([x[key[k]] for x in agg[("veronese", int(d))]]) for d in D])
        S = np.array([st.stdev([x[key[k]] for x in agg[("veronese", int(d))]]) / math.sqrt(len(agg[("veronese", int(d))])) for d in D])
        N = np.array([len(agg[("veronese", int(d))]) for d in D], float)
        fk = {}
        for name, lo, hi, ncol, wmode in (("two_term_40_140_countw", 40, 140, 2, "count"),
                                          ("three_term_20_200_countw", 20, 200, 3, "count"),
                                          ("two_term_40_140_invvar", 40, 140, 2, "invvar"),
                                          ("two_term_20_200_invvar", 20, 200, 2, "invvar"),
                                          ("three_term_20_200_invvar", 20, 200, 3, "invvar"),
                                          ("two_term_60_200_invvar", 60, 200, 2, "invvar")):
            sel = (D >= lo) & (D <= hi)
            X = np.vstack([np.ones(sel.sum()), 1 / D[sel], 1 / D[sel] ** 2][:ncol]).T
            if wmode == "count":
                W = N[sel]
            else:
                W = 1 / S[sel] ** 2
            A = X * np.sqrt(W)[:, None]; b = Y[sel] * np.sqrt(W)
            beta = np.linalg.lstsq(A, b, rcond=None)[0]
            cov = np.linalg.inv(A.T @ A)
            resid = Y[sel] - X @ beta
            dof = max(1, sel.sum() - ncol)
            if wmode == "count":
                s2 = float((W * resid ** 2).sum() / dof)       # refresh_p9._wls convention
                se0 = math.sqrt(s2 * cov[0, 0])
                chi2 = None
            else:
                se0 = math.sqrt(cov[0, 0])
                chi2 = float((W * resid ** 2).sum())
            fk[name] = {"a": float(beta[0]), "a_se": se0, "a_minus_catalan_in_se": float((beta[0] - cat[k]) / se0),
                        "b": float(beta[1]), "e": (float(beta[2]) if ncol == 3 else None),
                        "chi2": chi2, "dof": int(dof), "points": int(sel.sum())}
        # d * excess ladder
        fk["d_times_excess"] = {str(int(d)): float(d * (y - cat[k])) for d, y in zip(D, Y)}
        fits[f"k{k}"] = fk
    dump("moments_by_rowlaw.json", {"rows": rows, "mixture_as_printed_by_table_moments": mixture,
                                     "pure_veronese_fits": fits,
                                     "note": "rows are per (rowlaw, d); refresh_p9.table_moments/table_momentfit aggregate by d only and so mix the gauss/rademacher controls into d=20,30,40,60"})
    return rows


# ----------------------------------------------------------------------------- hard edge ladder
def hardedge():
    F = lambda t: 1 - math.exp(-math.sqrt(max(t, 0.0)) - t / 2)

    def ks(v):
        v = sorted(v); n = len(v); m = 0.0
        for i, x in enumerate(v):
            c = F(x); m = max(m, abs(c - (i + 1) / n), abs(c - i / n))
        return m

    agg = collections.defaultdict(list)
    for j in load("p9h_*.json"):
        for r in j["records"]:
            agg[j["d"]].append(r)
    rows = []
    for d in sorted(agg):
        rs = agg[d]; n = len(rs)
        sr = sorted(r["smin_ratio"] for r in rs)
        q = lambda v, p: v[min(len(v) - 1, int(p * len(v)))]
        bh = sorted(r["stat_BH"] for r in rs)
        row = {"d": d, "p": rs[0]["p"], "n": n,
               "smin_ratio_mean": st.mean(sr), "smin_ratio_sd": st.stdev(sr), "smin_ratio_median": st.median(sr),
               "smin_ratio_p10": q(sr, 0.1), "smin_ratio_p90": q(sr, 0.9),
               "d_times_one_minus_ratio": d * (1 - st.mean(sr)),
               "ks_Z": ks([r["stat_Z"] for r in rs]), "ks_BH": ks(bh), "ks_H": ks([r["stat_H"] for r in rs]),
               "ks_crit95": 1.36 / math.sqrt(n),
               "b_mean": st.mean(r["b_mean"] for r in rs), "b_mean_pred": rs[0]["b_mean_pred"],
               "b_var": st.mean(r["b_var"] for r in rs), "b_var_pred": rs[0]["b_var_pred"],
               "alpha2_mean": st.mean(r["alpha2"] for r in rs),
               "d_tr_A4_mean": st.mean(r["d_tr_A4"] for r in rs),
               "d_tr_A4_se": st.stdev(r["d_tr_A4"] for r in rs) / math.sqrt(n),
               "sqrtd_op_A_mean": st.mean(r["sqrtd_op_A"] for r in rs),
               "op2_over_trA4": st.mean(r["op_A"] ** 2 / r["tr_A4"] for r in rs),
               "lower_tail_F_at_percentiles_2_5_10_20": [F(q(bh, p)) for p in (0.02, 0.05, 0.10, 0.20)]}
        ov = [x for r in rs for x in r["ones_overlap"][:3]]
        row["ones_overlap_mean"], row["ones_overlap_sd"], _ = msd(ov)
        row["ones_overlap_p90"] = q(sorted(ov), 0.9)
        # inverse first moment in disjoint blocks of 150, both statistics
        for nm, key in (("Z", "stat_Z"), ("BH", "stat_BH")):
            v = [1 / math.sqrt(r[key]) for r in rs]
            blocks = [v[i:i + 150] for i in range(0, len(v) - 149, 150)]
            if len(blocks) >= 2:
                means = [st.mean(b) for b in blocks]; meds = [st.median(b) for b in blocks]
                row[f"inv_block_means_{nm}"] = sorted(means)
                row[f"inv_block_means_cv_{nm}"] = st.stdev(means) / st.mean(means)
                row[f"inv_block_medians_range_{nm}"] = [min(meds), max(meds)]
                row[f"inv_block_medians_cv_{nm}"] = st.stdev(meds) / st.mean(meds)
        rows.append(row)
    dump("hardedge_ladder.json", rows)
    return rows


# ----------------------------------------------------------------------------- Target-3 records
def gap2():
    agg = collections.defaultdict(list); consts = collections.Counter()
    for j in load("p9t_*.json"):
        consts[json.dumps({"c_strong": j["c_strong"], "c_route": j.get("c_route"), "c_p04": j.get("c_p04"), "window": j["window"]})] += 1
        for r in j["records"]:
            agg[(j["d"], j["h"])].append(r)
    rows = []
    for (d, h), rs in sorted(agg.items()):
        wc = [r["window_certificates"][0] for r in rs if r.get("window_certificates")]
        row = {"d": d, "h": h, "n": len(rs),
               "window_certificate_mean": st.mean(wc), "window_certificate_sd": (st.stdev(wc) if len(wc) > 1 else 0.0),
               "window_delta_L": rs[0]["window_deltas"][0],
               "best_certificate_mean": st.mean(r["best_certificate"] for r in rs),
               "best_delta": rs[0]["best_delta"], "best_in_window": rs[0]["best_in_window"],
               "V_mc_mean": st.mean(r["V_over_sigma2"] for r in rs), "V_mc_sd": (st.stdev([r["V_over_sigma2"] for r in rs]) if len(rs) > 1 else 0.0),
               "V_exact_mean": st.mean(r["V_over_sigma2_exact"] for r in rs),
               "max_V_rel_gap": max(r["V_rel_gap"] for r in rs),
               "tau_sum": rs[0]["tau_sum"],
               "exact_form": collections.Counter(r.get("exact_form") for r in rs).most_common(1)[0][0],
               "kappa_range": [min(r["K_eig_max"] / r["K_eig_min"] for r in rs), max(r["K_eig_max"] / r["K_eig_min"] for r in rs)]}
        ec = [r["eps_cond2"] for r in rs if r.get("eps_cond2") is not None]
        if ec:
            row["eps_cond2_range"] = [min(ec), max(ec)]
        rows.append(row)
    # tab:t3 over every design at d=10, h=1 (the paper prints design 0 only)
    blocks = collections.defaultdict(list)
    for r in agg.get((10, 1.0), []):
        for b in r["blocks"]:
            if b["L"] > 0:
                blocks[b["L"]].append(b)
    t3 = []
    for L in sorted(blocks):
        bs = blocks[L]
        sr = [b["S_dev_ratio"] for b in bs if b["S_dev_ratio"] is not None]
        t3.append({"L": L, "D_L": bs[0]["D_L"], "delta_L": bs[0]["delta_L"], "designs": len(bs),
                   "T_L_over_n_mean": st.mean(b["T_L_over_n"] for b in bs), "T_L_over_n_sd": st.stdev(b["T_L_over_n"] for b in bs),
                   "certificate_mean": st.mean(b["certificate"] for b in bs), "certificate_sd": st.stdev(b["certificate"] for b in bs),
                   "S_dev_ratio_mean": st.mean(sr), "S_dev_ratio_sd": st.stdev(sr), "S_dev_ratio_design0": bs[0]["S_dev_ratio"],
                   "in_window": bs[0]["in_window"]})
    dump("gap2_certificates.json", {"per_d_h": rows, "constants_in_lane_files": dict(consts), "tab_t3_all_designs_d10_h1": t3})
    return rows


# ----------------------------------------------------------------------------- cGEC arms
def cgec():
    agg = collections.defaultdict(list); herm = {}
    for j in load("p9c_*.json"):
        for r in j["records"]:
            agg[(j["d"], j["delta"], j["normalize_F"])].append(r)
        herm[json.dumps([j["d"], j["delta"]])] = dict(j["hermite"], eps_d=j["eps_d"])
    rows = []
    for (d, de, nf), rs in sorted(agg.items()):
        row = {"d": d, "delta": de, "normalize_F": nf, "n": len(rs)}
        for k in ("d_q11_var", "L_rel_gap", "risk_end_to_end_gap", "risk_same_w_gap", "F_colnorm_dev", "q11_mean"):
            row[k + "_mean"], row[k + "_sd"], _ = msd(x[k] for x in rs)
        rows.append(row)
    dump("cgec_arms.json", {"per_d_delta_normF": rows, "hermite_by_d_delta": herm})
    return rows


# ----------------------------------------------------------------------------- correction lanes
def correction():
    lanes = []
    for j in load("p9e_*.json"):
        rows = sorted(j["rows"], key=lambda r: r["lam"])
        best = min(rows, key=lambda r: r["R1_con"])
        pm, pc = best.get("phys_mean"), best.get("phys_con")
        lanes.append({"tag": j["tag"], "corpus": j["corpus"], "comp": j["comp"] if j["corpus"] == "emit" else j["band"],
                      "seed": j["seed"], "R0": j["R0"], "lam_best": best["lam"], "R1_con_best": best["R1_con"],
                      "gain_pct": 100 * (j["R0"] - best["R1_con"]) / j["R0"],
                      "phys_mean": pm, "phys_con_best": pc, "phys_gain_pct": (100 * (pm - pc) / pm) if pm else None,
                      "helps_by_ridge": [r["helps"] for r in rows], "lams": [r["lam"] for r in rows],
                      "sign_margin_over_R0_by_ridge": [r["sign_margin"] / j["R0"] for r in rows],
                      "eta_best": best["eta"], "eta_bound_best": best["eta_bound"],
                      "max_identity_rel_err": max(abs(r["identity_rel_err"]) for r in rows),
                      "n": j["n"], "nfit": j["nfit"], "epochs": j["epochs"], "folds": j["folds"]})
    summ = collections.defaultdict(list)
    for l in lanes:
        summ[l["corpus"] + " " + l["comp"]].append(l)
    per = {}
    for k, v in summ.items():
        per[k] = {"lanes": len(v), "gain_pct_mean": st.mean(x["gain_pct"] for x in v),
                  "gain_pct_sd": (st.stdev([x["gain_pct"] for x in v]) if len(v) > 1 else 0.0),
                  "phys_gain_pct_mean": st.mean(x["phys_gain_pct"] for x in v if x["phys_gain_pct"] is not None),
                  "phys_mean_mean": st.mean(x["phys_mean"] for x in v), "phys_con_mean": st.mean(x["phys_con_best"] for x in v),
                  "hurt_pairs": sum(sum(1 for h in x["helps_by_ridge"] if not h) for x in v),
                  "max_identity_rel_err": max(x["max_identity_rel_err"] for x in v)}
    dump("correction_lanes.json", {"lanes": lanes, "per_corpus": per})
    return lanes


# ----------------------------------------------------------------------------- dimension-gap sweep
def gap():
    agg = collections.defaultdict(list)
    for j in load("p9g_*.json"):
        for r in j["records"]:
            agg[(j["d"], j["h"], r["k"])].append(r)
    rows = []
    for (d, h, k), rs in sorted(agg.items()):
        by = collections.defaultdict(list); bi = collections.defaultdict(list)
        for r in rs:
            by[round(r["delta"], 2)].append(r["risk_noise"]); bi[round(r["delta"], 2)].append(r["tail_isotropy"])
        ds = sorted(by)
        if len(ds) < 3:
            continue
        means = [st.mean(by[x]) for x in ds]; iso = [st.mean(bi[x]) for x in ds]
        inv = sum(1 for i in range(len(means)) for j2 in range(i + 1, len(means)) if means[i] < means[j2])
        inv_iso = sum(1 for i in range(len(iso)) for j2 in range(i + 1, len(iso)) if iso[i] < iso[j2])
        rows.append({"d": d, "h": h, "k": k, "N_k": rs[0]["N_k"], "deltas": ds, "risk_noise_mean": means,
                     "tail_isotropy_mean": iso, "designs_per_point": len(by[ds[0]]),
                     "inverted_pairs_risk": inv, "inverted_pairs_isotropy": inv_iso})
    dump("gap_blocks.json", rows)
    return rows


# ----------------------------------------------------------------------------- prune block shares
def prune():
    agg = collections.defaultdict(list)
    for j in load("p9p_bk_*.json") + load("p9q_*.json"):
        for r in j["records"]:
            agg[(r["law"], r["n"], r["r"], r.get("aspect", 0.5))].append(r)
    rows = []
    for (law, n, r_, asp), rs in sorted(agg.items()):
        m = lambda key: st.mean(x[key] for x in rs)
        s = m("beta_A") + m("beta_D") + m("beta_B")
        rows.append({"law": law, "n": n, "r": r_, "aspect": asp, "designs": len(rs), "beta": m("beta"),
                     "beta_A": m("beta_A"), "beta_D": m("beta_D"), "beta_B": m("beta_B"),
                     "share_A": m("beta_A") / s, "share_D": m("beta_D") / s, "share_B": m("beta_B") / s})
    dump("prune_blocks.json", rows)
    return rows



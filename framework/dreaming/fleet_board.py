#!/usr/bin/env python3
"""fleet_board.py - one inbox and one task list for every agent on every computer that shares a brain.

Design goal: when the user runs agents on several computers, a message meant for all of them reaches every agent
quickly, every agent posts what it is working on to one shared place, and there is no doubt where to look.

Where things live (one answer, no other place). The board is a private GitHub repository named by FLEET_BOARD_REPO
(owner/name); the brain mirror is optional (FLEET_BRAIN_REPO, path FLEET_BRAIN_MIRROR_PATH):
  user -> fleet messages    <board> FLEET_INBOX.md   (canonical, newest first)
  brain mirror              <brain repo> <mirror path> (byte copy, written by the same call; skipped when unset)
  who saw a message         <board> coordination/acks/<msg id>/<computer>__<agent>.json (create-only)
  each computer's tasks     <board> coordination/computers/<computer>/OPEN_TASKS.md (one writer per computer)
                            and DONE_TASKS.md (its recently finished tasks, same writer)
  one view of all of it     <board> DASHBOARD.md (generated by `dashboard`; sync-tasks rebuilds it)
  this computer's name      FLEET_COMPUTER, else the host name

Delivery: fleet_inbox_hook.py (SessionStart + UserPromptSubmit) reads FLEET_INBOX.md over the GitHub API at most once a
minute and puts every message a session has not seen in front of it, on every computer that has the hook. Codex fleet
supervisors call `fleet_board.py check --agent <their id>` each tick and relay. A local mesh broadcast goes out too.

    python3 fleet_board.py broadcast --agent <your id> "<the user's message>"    tell the whole fleet, all computers
    python3 fleet_board.py check --agent <id> [--all]                             print messages this agent has not seen
    python3 fleet_board.py ack <msg id> --agent <id>                              record that you got it
    python3 fleet_board.py sync-tasks                                             post this computer's open and finished tasks
    python3 fleet_board.py dashboard                                              rebuild DASHBOARD.md (all computers, acks)
    python3 fleet_board.py whoami                                                 this computer's board name

Writes go through the GitHub contents API with the file's sha (a lost race re-reads and retries), so no clone is needed
and no two machines can overwrite each other. The token comes from `gh auth token` and is never printed or logged.

The hook's inbox read is a conditional GET with the last ETag: an unchanged inbox answers 304, which GitHub does not
count against the REST budget the computers share, so polling once a minute everywhere costs nothing.
"""
import base64, json, os, re, socket, subprocess, sys, time, urllib.error, urllib.request

NOWIN = 0x08000000 if os.name == "nt" else 0          # CREATE_NO_WINDOW: never a console flash on Windows
PY = "python3" if os.name != "nt" else '"%s"' % sys.executable   # how the printed hints call Python here

BOARD = os.environ.get("FLEET_BOARD_REPO", "your-account/tasks-board")
BRAIN = os.environ.get("FLEET_BRAIN_REPO", "")
INBOX = "FLEET_INBOX.md"
MIRROR = os.environ.get("FLEET_BRAIN_MIRROR_PATH", "fleet_board/FLEET_INBOX.md")
HERE = os.path.dirname(os.path.abspath(__file__))
STATE = os.path.join(os.path.expanduser("~"), ".claude", "fleet_board")
CACHE_S = 60
HEAD = ("# Fleet inbox: messages for every agent on every computer\n\n"
        "Newest first. Every agent reads this; the fleet_inbox_hook shows new entries to Claude sessions on its own, "
        "Codex supervisors run `fleet_board.py check` each tick. After reading a message, ack it: "
        "`python3 fleet_board.py ack <id> --agent <your id>`. Post with "
        "`fleet_board.py broadcast`, never by hand-editing, so the brain mirror stays identical.\n\n")
_TOKEN = None


def computer():
    n = os.environ.get("FLEET_COMPUTER") or socket.gethostname().split(".")[0]
    return re.sub(r"[^a-z0-9-]+", "-", n.lower()).strip("-") or "unknown"


def token():
    global _TOKEN
    if _TOKEN is None:
        try:
            _TOKEN = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True, timeout=20,
                                    stdin=subprocess.DEVNULL, creationflags=NOWIN).stdout.strip()
        except Exception:
            _TOKEN = ""
        if not _TOKEN:   # gh not signed in: use the token git itself pushes with
            try:
                out = subprocess.run(["git", "credential", "fill"], input="protocol=https\nhost=github.com\n\n",
                                     capture_output=True, text=True, timeout=20, creationflags=NOWIN,
                                     env=dict(os.environ, GIT_TERMINAL_PROMPT="0", GCM_INTERACTIVE="never")).stdout
                _TOKEN = next((l[9:].strip() for l in out.splitlines() if l.startswith("password=")), "")
            except Exception:
                _TOKEN = ""
    return _TOKEN


def api(method, url, body=None, timeout=15, headers=None, with_headers=False):
    h = {"Authorization": "Bearer " + token(), "Accept": "application/vnd.github+json",
         "X-GitHub-Api-Version": "2022-11-28", "Content-Type": "application/json"}
    h.update(headers or {})
    req = urllib.request.Request("https://api.github.com" + url, method=method,
                                 data=json.dumps(body).encode() if body is not None else None, headers=h)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            st, data, hd = r.status, json.loads(r.read() or b"{}"), dict(r.headers)
    except urllib.error.HTTPError as e:
        try:
            data = json.loads(e.read() or b"{}")
        except Exception:
            data = {}
        st, hd = e.code, dict(e.headers or {})
    except Exception:          # no network or a timeout: status 0, and get_file tries GraphQL
        st, data, hd = 0, {}, {}
    return (st, data, hd) if with_headers else (st, data)


def gql(query, variables, timeout=15):
    """GraphQL has its own hourly budget. Once, the account's 5,000 REST calls an hour were all used by other agents
    while GraphQL still had 4,964 points, so every read and write here falls back to it."""
    req = urllib.request.Request("https://api.github.com/graphql", method="POST",
                                 data=json.dumps({"query": query, "variables": variables}).encode(),
                                 headers={"Authorization": "Bearer " + token(), "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            d = json.loads(r.read() or b"{}")
    except Exception:
        return None
    return None if d.get("errors") else d.get("data")


def _gql_file(repo, path, timeout):
    owner, name = repo.split("/")
    d = gql("query($o:String!,$n:String!,$e:String!){repository(owner:$o,name:$n){defaultBranchRef{name "
            "target{oid}} object(expression:$e){... on Blob{text oid}}}}",
            {"o": owner, "n": name, "e": "HEAD:" + path}, timeout)
    if not d or not d.get("repository"):
        raise IOError("graphql read failed")
    repo_d = d["repository"]
    blob = repo_d.get("object")
    head = repo_d["defaultBranchRef"]
    return (blob["text"] if blob else None), (blob["oid"] if blob else None), head["name"], head["target"]["oid"]


def get_file(repo, path, timeout=15):
    st, r = api("GET", "/repos/%s/contents/%s" % (repo, path), timeout=timeout)
    if st == 200 and "content" in r:
        return base64.b64decode(r["content"]).decode("utf-8"), r["sha"]
    if st == 404:
        return None, None
    try:   # rate limited or the API is down
        text, oid, _, _ = _gql_file(repo, path, timeout)
        return text, oid
    except Exception:
        return None, None


def _gql_put(repo, path, update, message):
    """One commit through createCommitOnBranch. expectedHeadOid makes a lost race fail, and the caller retries."""
    old, _, branch, head = _gql_file(repo, path, 15)
    new = update(old)
    if new is None or new == old:
        return True
    d = gql("mutation($i:CreateCommitOnBranchInput!){createCommitOnBranch(input:$i){commit{oid}}}",
            {"i": {"branch": {"repositoryNameWithOwner": repo, "branchName": branch},
                   "message": {"headline": message}, "expectedHeadOid": head,
                   "fileChanges": {"additions": [{"path": path,
                                                  "contents": base64.b64encode(new.encode("utf-8")).decode()}]}}})
    return bool(d and d.get("createCommitOnBranch"))


def put_file(repo, path, update, message, tries=8):
    """update(old_text_or_None) -> new text, or None to leave the file alone. Re-read and retry on a lost race."""
    for _ in range(tries):
        old, sha = get_file(repo, path)
        new = update(old)
        if new is None or new == old:
            return True
        body = {"message": message, "content": base64.b64encode(new.encode("utf-8")).decode()}
        if sha:
            body["sha"] = sha
        st, r = api("PUT", "/repos/%s/contents/%s" % (repo, path), body)
        if st in (200, 201):
            return True
        if st in (403, 429):   # REST budget spent: write the same change as one GraphQL commit
            try:
                if _gql_put(repo, path, update, message):
                    return True
            except Exception:
                pass
            time.sleep(2)
            continue
        if st not in (409, 422):
            print("write %s:%s failed: %s %s" % (repo, path, st, str(r.get("message", ""))[:120]), file=sys.stderr)
            if st not in (500, 502, 503, 504):
                return False
        time.sleep(2)
    return False


def parse(text):
    """FLEET_INBOX.md -> [{id, when, sender, text}], newest first."""
    out = []
    for block in re.split(r"(?m)^## ", text or "")[1:]:
        first, _, rest = block.partition("\n")
        parts = [p.strip() for p in first.split("|")]
        if not parts or not parts[0].startswith("FM-"):
            continue
        out.append({"id": parts[0], "when": parts[1] if len(parts) > 1 else "",
                    "sender": parts[2] if len(parts) > 2 else "", "text": rest.strip()})
    return out


def broadcast(agent, text):
    now = time.localtime()
    mid = "FM-%s-%s" % (time.strftime("%Y%m%d-%H%M%S", now), computer())
    when = time.strftime("%Y-%m-%d %H:%M ", now) + time.strftime("%z", now)
    entry = "## %s | %s | from the user via %s on %s\n\n%s\n\n" % (mid, when, agent, computer(), text.strip())

    def add(old):
        old = old or HEAD
        i = old.find("\n## ")
        return (old[:i + 1] + entry + old[i + 1:]) if i >= 0 else old.rstrip("\n") + "\n\n" + entry

    ok = put_file(BOARD, INBOX, add, "Fleet message %s [skip ci]" % mid)
    board_text, _ = get_file(BOARD, INBOX)
    mirrored = (not BRAIN) or (bool(board_text) and put_file(BRAIN, MIRROR, lambda old: board_text,
                                                          "Fleet inbox mirror %s [skip ci]" % mid))
    try:   # this computer's agents get it at once through the mesh as well
        mesh = os.environ.get("AGENT_MESH_PY") or os.path.join(os.path.dirname(HERE), "mesh", "agent_mesh.py")
        subprocess.run([sys.executable, mesh, "send",
                        "--agent", agent, "--to", "all", "--kind", "warning", "--topic", "FLEET MESSAGE " + mid,
                        "--body", text.strip()[:3000]], capture_output=True, timeout=60, creationflags=NOWIN)
    except Exception:
        pass
    landed = ok and board_text is not None and mid in board_text
    print("%s %s; board %s, brain mirror %s" % (mid, "POSTED" if landed else "NOT POSTED",
                                                "ok" if landed else "FAILED", "ok" if mirrored else "FAILED"))
    return 0 if landed else 1


def seen_path(agent):
    return os.path.join(STATE, "seen_%s.json" % re.sub(r"[^A-Za-z0-9_.-]", "_", agent))


def inbox_cached(max_age=CACHE_S, timeout=4):
    os.makedirs(STATE, exist_ok=True)
    cp = os.path.join(STATE, "inbox_cache.json")
    try:
        c = json.load(open(cp, encoding="utf-8"))
        if time.time() - c["t"] < max_age:
            return c["text"]
    except Exception:
        c = None
    etag = (c or {}).get("etag")
    st, r, hd = api("GET", "/repos/%s/contents/%s" % (BOARD, INBOX), timeout=timeout,
                    headers={"If-None-Match": etag} if etag and c.get("text") is not None else None, with_headers=True)
    if st == 304:                        # unchanged, and free: keep the copy, restart its minute
        text, etag = c["text"], etag
    elif st == 200 and "content" in r:
        text, etag = base64.b64decode(r["content"]).decode("utf-8"), hd.get("ETag") or hd.get("etag")
    else:
        text, _ = get_file(BOARD, INBOX, timeout=timeout)   # REST refused: GraphQL
        etag = None
    if text is None:
        return c["text"] if c else None   # offline: the last copy is better than nothing
    tmp = cp + ".%d" % os.getpid()
    json.dump({"t": time.time(), "text": text, "etag": etag}, open(tmp, "w", encoding="utf-8"))
    os.replace(tmp, cp)
    return text


def unseen(agent, show_all=False, first_window_h=48):
    msgs = parse(inbox_cached())
    sp = seen_path(agent)
    try:
        seen = set(json.load(open(sp, encoding="utf-8")))
        fresh = False
    except Exception:
        seen, fresh = set(), True
    if show_all:
        return msgs, sp, seen
    new = [m for m in msgs if m["id"] not in seen]
    if fresh:   # a new session sees the last two days, not the whole history
        cut = time.time() - first_window_h * 3600
        new = [m for m in new if _ts(m["id"]) >= cut]
    return new, sp, seen


def _ts(mid):
    m = re.match(r"FM-(\d{8})-(\d{6})", mid)
    try:
        return time.mktime(time.strptime(m.group(1) + m.group(2), "%Y%m%d%H%M%S"))
    except Exception:
        return 0


def mark_seen(sp, seen, msgs):
    seen |= {m["id"] for m in msgs}
    tmp = sp + ".%d" % os.getpid()
    json.dump(sorted(seen), open(tmp, "w", encoding="utf-8"))
    os.replace(tmp, sp)


def check(agent, show_all=False):
    msgs, sp, seen = unseen(agent, show_all)
    for m in msgs:
        print("[%s] %s (%s)\n%s\n" % (m["id"], m["when"], m["sender"], m["text"]))
    if not show_all:
        mark_seen(sp, seen, msgs)
    return 0


def ack(mid, agent):
    path = "coordination/acks/%s/%s__%s.json" % (mid, computer(), re.sub(r"[^A-Za-z0-9_.-]", "_", agent))
    rec = json.dumps({"message": mid, "agent": agent, "computer": computer(),
                      "acked_at": time.strftime("%Y-%m-%dT%H:%M:%S%z")}, indent=1) + "\n"
    ok = put_file(BOARD, path, lambda old: rec if old is None else None, "Ack %s by %s [skip ci]" % (mid, agent))
    print("ack %s %s" % (mid, "recorded" if ok else "FAILED"))
    return 0 if ok else 1


STAMP = re.compile(r"at \d{4}-\d\d-\d\d \d\d:\d\d [+-]\d{4}")


def checklist(*args):
    try:
        r = subprocess.run([sys.executable, os.path.join(HERE, "task_checklist_hook.py"), "list",
                            *args], capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120,
                           creationflags=NOWIN, env=dict(os.environ, PYTHONIOENCODING="utf-8"))
        return (r.stdout or "").strip()   # a cp1252 decode used to leave stdout None on Windows
    except Exception as e:
        return "checklist unreadable: %r" % e


def entries(body, status=None):
    """Checklist `list` output -> one string per task (its T- line plus the indented lines under it)."""
    out = []
    for ln in (body or "").splitlines():
        if re.match(r"T-\d{8}-\d+\s", ln):
            out.append(ln)
        elif out and ln.startswith(" "):
            out[-1] += "\n" + ln
    return [e for e in out if status is None or e.split()[1] == status]


def post_tasks(name, title, body):
    """Write one of this computer's task files; returns (ok, changed)."""
    text = ("# %s on %s\n\nWritten by `fleet_board.py sync-tasks` at %s from this computer's task checklist "
            "(every agent's asks, in the user's words). Do not edit by hand; it is rewritten each sync.\n\n```\n%s\n```\n"
            % (title, computer(), time.strftime("%Y-%m-%d %H:%M %z"), body[:200000]))
    path = "coordination/computers/%s/%s" % (computer(), name)
    scan = os.path.join(HERE, "scan_secrets.py")
    if os.path.exists(scan):   # it runs unattended, so nothing that looks like a credential leaves the machine
        tmp = os.path.join(STATE, "open_tasks_scan.md")
        os.makedirs(STATE, exist_ok=True)
        open(tmp, "w", encoding="utf-8").write(text)
        if subprocess.run([sys.executable, scan, tmp], capture_output=True, timeout=120,
                          creationflags=NOWIN).returncode != 0:
            print("%s NOT synced: the secret scan flagged it" % path)
            return False, False
    changed = []

    def update(old):
        if STAMP.sub("", old or "") == STAMP.sub("", text):
            return None
        changed.append(1)
        return text
    ok = put_file(BOARD, path, update, "%s on %s [skip ci]" % (title, computer()))
    print("%s %s" % (path, ("synced" if changed else "unchanged") if ok else "FAILED"))
    return ok, bool(changed)


def sync_tasks():
    """Post this computer's open task-checklist entries (every agent's asks, registered by task_checklist_hook) and the
    ones finished lately to the board, one folder per computer so machines never write the same file. When either
    file changed, rebuild DASHBOARD.md."""
    ok1, ch1 = post_tasks("OPEN_TASKS.md", "Open tasks", checklist("--open"))
    done = entries(checklist(), "done")[:DONE_KEEP]
    ok2, ch2 = post_tasks("DONE_TASKS.md", "Finished tasks", "\n".join(done) or "(none in the recent list)")
    if ch1 or ch2:
        dashboard()
    return 0 if ok1 and ok2 else 1


DONE_KEEP = 40
SHOW = 40   # open tasks per computer on the dashboard; the rest stay in that computer's file


def _block(text):
    m = re.search(r"```\n(.*?)\n```", text or "", re.S)
    return m.group(1) if m else ""


def dashboard():
    """DASHBOARD.md: one page with every computer's open and finished tasks and who has acked each fleet message.
    Anyone may rebuild it (sync-tasks does when its files change); it is generated, never edited by hand."""
    st, items = api("GET", "/repos/%s/contents/coordination/computers" % BOARD)
    if st != 200:
        print("dashboard: cannot list computers (%s)" % st)
        return 1
    rows, open_parts, done_parts = [], [], []
    for c in sorted(i["name"] for i in items if i.get("type") == "dir"):
        o, _ = get_file(BOARD, "coordination/computers/%s/OPEN_TASKS.md" % c)
        d, _ = get_file(BOARD, "coordination/computers/%s/DONE_TASKS.md" % c)
        ob, db = _block(o), _block(d)
        when = STAMP.search(o or "")
        rows.append("| %s | %d | %s | %s |" % (c, len(entries(ob)), len(entries(db)) if d else "not posted yet",
                                              when.group(0)[3:] if when else "?"))
        oe = entries(ob)
        more = "\n(and %d more in coordination/computers/%s/OPEN_TASKS.md)" % (len(oe) - SHOW, c) if len(oe) > SHOW else ""
        open_parts.append("### %s\n\n```\n%s%s\n```\n" % (c, "\n".join(oe[:SHOW]) or ob or "(none)", more))
        if d:
            done_parts.append("### %s\n\n```\n%s\n```\n" % (c, db or "(none)"))
    inbox, _ = get_file(BOARD, INBOX)
    msgs = []
    for m in parse(inbox)[:8]:
        st, acks = api("GET", "/repos/%s/contents/coordination/acks/%s" % (BOARD, m["id"]))
        by = {}
        for a in (acks if st == 200 and isinstance(acks, list) else []):
            by.setdefault(a["name"].split("__")[0], []).append(1)
        msgs.append("| %s | %s | %s |" % (m["id"], m["text"][:90].replace("|", "/").replace("\n", " "),
                                          ", ".join("%s %d" % (k, len(v)) for k, v in sorted(by.items())) or "none"))
    text = ("# Fleet dashboard\n\nRebuilt by `fleet_board.py dashboard` at %s on %s from coordination/computers/*/ and "
            "coordination/acks/. Generated; do not edit by hand. Each computer posts its own tasks with "
            "`fleet_board.py sync-tasks`, which also rebuilds this page when they change.\n\n"
            "## Computers\n\n| computer | open | finished (recent) | tasks posted |\n|---|---|---|---|\n%s\n\n"
            "## Fleet messages and acks\n\n| message | start | acks by computer |\n|---|---|---|\n%s\n\n"
            "## Open tasks\n\n%s\n## Recently finished\n\n%s"
            % (time.strftime("%Y-%m-%d %H:%M %z"), computer(), "\n".join(rows), "\n".join(msgs),
               "\n".join(open_parts), "\n".join(done_parts) or "No computer has posted DONE_TASKS.md yet.\n"))
    norm = lambda t: re.sub(r"Rebuilt by .*? from", "", t or "", count=1)
    ok = put_file(BOARD, "DASHBOARD.md", lambda old: None if norm(old) == norm(text) else text, "Dashboard [skip ci]")
    print("DASHBOARD.md %s" % ("written" if ok else "FAILED"))
    return 0 if ok else 1


def main(a):
    def opt(name, default=None):
        if name in a:
            i = a.index(name)
            v = a[i + 1]
            del a[i:i + 2]
            return v
        return default
    agent = opt("--agent", os.environ.get("AGENT_MESH_ID", "unknown-agent"))
    show_all = "--all" in a
    a = [x for x in a if x != "--all"]
    cmd = a[0] if a else "check"
    if cmd == "broadcast":
        return broadcast(agent, " ".join(a[1:]))
    if cmd == "check":
        return check(agent, show_all)
    if cmd == "ack":
        return ack(a[1], agent)
    if cmd == "sync-tasks":
        return sync_tasks()
    if cmd == "dashboard":
        return dashboard()
    if cmd == "whoami":
        print(computer())
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

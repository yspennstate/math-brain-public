#!/usr/bin/env python3
"""build_prompt_views.py - regenerate the human-readable strata over the prompt ledger.

The perpetual ledger (memory/prompts/PROMPTS.jsonl, written by prompt_archive.py + backfill) is the
substrate. These views are the conscious handles:

  PROMPTS_INDEX.md      counts per class (owner vs automation), classification coverage, latest prompts
  PROMPTS_<class>.md    every owner prompt of that class, chronological, with date/session/count

Origin routing takes precedence over class_model. Missing origin remains unknown.
For recorded-owner rows, class_model overrides class_provisional; neither authenticates a human.
Views are regenerated wholesale on every run (they are views, not ledgers); the nightly dream persist
refreshes them. Usage: python build_prompt_views.py
"""
import os, io, json, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import prompt_archive as pa
from correction_ingestion_status import recorded_origin, routed_class

CLASSES = pa.TAXONOMY + ["automation", "unknown"]


def load():
    recs = []
    if not os.path.exists(pa.LEDGER):
        return recs
    for ln in io.open(pa.LEDGER, encoding="utf-8", errors="replace"):
        try:
            r = json.loads(ln)
            if r.get("text"):
                recs.append(r)
        except Exception:
            continue
    recs.sort(key=lambda r: r.get("ts") or "9999")
    return recs


def _write(path, body):
    """Temp + os.replace. A bare open(...,'w') truncates at open and fills at close, so a timeout
    in between destroys the file with clean intent - that is how PREDICTIONS.md lost 254 lines of
    calibration history mid-dream on 07-21."""
    tmp = path + ".tmp"
    with io.open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    os.replace(tmp, path)


def build():
    recs = load()
    for r in recs:
        r["_class"] = routed_class(r, pa.TAXONOMY)
        r["_prov"] = not r.get("class_model")
    by = {c: [r for r in recs if r["_class"] == c] for c in CLASSES}
    owner_n = sum(1 for r in recs if recorded_origin(r) == "owner")
    automation_n = sum(recorded_origin(r) == "automation" for r in recs)
    unknown_n = len(recs) - owner_n - automation_n
    modeled = sum(1 for r in recs if r.get("class_model"))
    # A /loop cron job re-enqueues the owner's words verbatim every tick, so a record is not an
    # ask. `repeat_of` (prompt_origin.py) marks the echoes; the first sighting is the real ask.
    asks = [r for r in recs if recorded_origin(r) == "owner" and not r.get("repeat_of")]
    echoes = owner_n - len(asks)

    ix = ["# Prompt archive - recorded prompts; origin labels are not human authentication", "",
          "Substrate: `PROMPTS.jsonl` (append-only, hook-fed live since 2026-07-09, backfilled to the",
          "beginning). `class_model` = model judgment; `~` marks keyword-provisional entries the dream",
          "still owes a proper read. Regenerated by `build_prompt_views.py`.", "",
          "%d prompts total (%d recorded owner, %d automation, %d origin unknown) - %d model-classified, %d provisional" %
          (len(recs), owner_n, automation_n, unknown_n, modeled, len(recs) - modeled), "",
          "**%d of the %d owner records are distinct asks; %d are /loop re-fires of an earlier one.**"
          % (len(asks), owner_n, echoes),
          "For \"read my last N prompts\", read [PROMPTS_ASKS.md](PROMPTS_ASKS.md) - reading the raw",
          "tail gives roughly a third machine echoes (2026-08 ran 66.2% distinct, 2026-04..06 ran 100%).",
          "", "| class | count | view |", "|---|---|---|"]
    for c in CLASSES:
        if by[c]:
            ix.append("| %s | %d | [PROMPTS_%s.md](PROMPTS_%s.md) |" % (c, len(by[c]), c, c))
    ix += ["", "## Latest", ""]
    for r in recs[-10:][::-1]:
        ix.append("- %s [%s]%s %s" % ((r.get("ts") or "?")[:16], r["_class"],
                                      "~" if r["_prov"] else "", r["text"][:150].replace("\n", " ")))
    _write(os.path.join(pa.ARCHIVE_DIR, "PROMPTS_INDEX.md"), "\n".join(ix) + "\n")

    for c in CLASSES:
        if not by[c]:
            continue
        out = ["# Prompts: %s (%d)" % (c, len(by[c])), "",
               "Chronological. `(xN)` = the same prompt given N times; `~` = provisional class.", ""]
        for r in by[c]:
            n = " (x%d)" % r["count"] if r.get("count", 1) > 1 else ""
            out.append("- %s [%s]%s %s%s" % ((r.get("ts") or "?")[:16], r.get("session", "?"),
                                             "~" if r["_prov"] else "", r["text"][:400].replace("\n", " "), n))
        _write(os.path.join(pa.ARCHIVE_DIR, "PROMPTS_%s.md" % c), "\n".join(out) + "\n")

    # The view every "read my last N prompts" instruction should point at: his asks, echoes folded
    # in, newest first. Reading the raw ledger tail instead means reading cron re-fires as asks.
    asks_desc = sorted(asks, key=lambda r: r.get("ts") or "", reverse=True)
    reps = {}
    for r in recs:
        if r.get("repeat_of"):
            reps[r["repeat_of"]] = max(reps.get(r["repeat_of"], 1), r.get("repeat_n", 2))
    av = ["# Recorded owner asks - re-fires folded in; native origin review still required", "",
          "%d distinct asks out of %d owner records. `(re-fired xN)` means a /loop cron job put the"
          % (len(asks), owner_n),
          "same words back on the queue N times; those are not N asks. Built by `build_prompt_views.py`",
          "from `origin`/`repeat_of` (see `prompt_origin.py`).", ""]
    for r in asks_desc:
        n = reps.get(r.get("ts"))
        av.append("- %s [%s]%s %s%s" % ((r.get("ts") or "?")[:16], r["_class"],
                                        "~" if r["_prov"] else "",
                                        r["text"][:400].replace("\n", " "),
                                        " (re-fired x%d)" % n if n else ""))
    _write(os.path.join(pa.ARCHIVE_DIR, "PROMPTS_ASKS.md"), "\n".join(av) + "\n")

    print("views: %d prompts (%d asks, %d re-fires) -> PROMPTS_INDEX.md + PROMPTS_ASKS.md + %d class "
          "files (%d model-classified, %d provisional)"
          % (len(recs), len(asks), echoes, sum(1 for c in CLASSES if by[c]), modeled,
             len(recs) - modeled))


if __name__ == "__main__":
    # --help must not DO anything. Without this, an unrecognised flag falls
    # through and build() regenerates every view - so `--help`, run to find out
    # what the script does, silently rewrites the whole prompt-view stratum.
    # That has now happened five times across different scripts here; the scar
    # is script_help_flag_can_execute_work_2026_07_14. Discovery is not
    # execution.
    if any(a in ("-h", "--help") for a in sys.argv[1:]):
        print(__doc__)
        raise SystemExit(0)
    build()

"""The recall command can show retrieve()'s decision, and it never creates a store.

Scheduled audit account04/B01 r3 (29 Sep 2026), B01-R1-CLI-DECISION-TRACE-PROJECTION-20260929-01:
`math-brain recall` called search(), which forces the support threshold to 0 and returns hits
only, so no abstention, reason, exclusion or trace ever reached its output; and it opened the
store writable, so a mistyped path became a new empty store.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from math_brain.cli import main
from math_brain.models import GraphNode, NodeKind
from math_brain.store import ResearchStore

Cap = pytest.CaptureFixture[str]

BODY = ("Every finite group of prime order is cyclic, generated by any element other than "
        "the identity.")


def _store(path: Path, nodes: list[GraphNode]) -> Path:
    with ResearchStore(path) as store:
        for n in nodes:
            store.add_node(n)
        store.connection.commit()
    return path


def _tie(tmp_path: Path) -> Path:
    return _store(tmp_path / "brain.sqlite3", [
        GraphNode("left", NodeKind.CLAIM, "finite group", BODY),
        GraphNode("right", NodeKind.CLAIM, "finite group", BODY),
    ])


def test_decision_shows_an_ambiguous_top(tmp_path: Path, capsys: Cap) -> None:
    db = _tie(tmp_path)
    assert main(["recall", str(db), "finite group", "--decision", "--limit", "1",
                 "--min-margin", "0.2"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["abstained"] is True and out["reason"] == "ambiguous_top_match"
    assert len(out["hits"]) == 1 and out["hits"][0]["trace"]


def test_decision_shows_weak_support(tmp_path: Path, capsys: Cap) -> None:
    db = _tie(tmp_path)
    assert main(["recall", str(db), "finite group", "--decision", "--min-support", "1e6"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["abstained"] is True and out["reason"] == "below_support_threshold"


def test_plain_recall_output_is_unchanged(
    tmp_path: Path, capsys: Cap, monkeypatch: pytest.MonkeyPatch
) -> None:
    import math_brain.cli as cli

    off = tmp_path / "BACKGROUND_OFF"
    off.touch()
    monkeypatch.setattr(cli, "BACKGROUND_OFF", off)
    db = _tie(tmp_path)
    assert main(["recall", str(db), "finite group"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert isinstance(out, list) and {h["id"] for h in out} == {"left", "right"}
    assert set(out[0]) == {"id", "kind", "title", "score", "warning_score"}


def test_recall_output_with_background(
    tmp_path: Path, capsys: Cap, monkeypatch: pytest.MonkeyPatch
) -> None:
    import math_brain.cli as cli

    monkeypatch.setattr(cli, "BACKGROUND_OFF", tmp_path / "absent")
    db = _tie(tmp_path)
    assert main(["recall", str(db), "finite group"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert {h["id"] for h in out["hits"]} == {"left", "right"}
    assert set(out["hits"][0]) == {"id", "kind", "title", "score", "warning_score"}
    assert isinstance(out["background"], list)


def test_recall_on_a_missing_path_creates_nothing(tmp_path: Path) -> None:
    path = tmp_path / "no_such_dir" / "brain.sqlite3"
    with pytest.raises(FileNotFoundError):
        main(["recall", str(path), "finite group"])
    assert not path.exists() and not path.parent.exists()

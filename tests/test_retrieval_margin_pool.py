"""The ambiguity verdict does not depend on how many hits were asked for.

Interactive audit IA-20260929-MB-01 (29 Sep 2026): retrieve() cut the ranked list to ``limit`` and
then compared the two best-supported hits of what was left, so a request for one hit had no
runner-up to compare against and two equally supported, unlinked claims came back as a confident
answer. The verdict is now the one an unlimited request gets; everything else is unchanged.
"""

from __future__ import annotations

import pytest

from math_brain.models import EdgeKind, GraphEdge, GraphNode, NodeKind
from math_brain.retrieval import AbstentionReason, retrieve

BODY = ("Every finite group of prime order is cyclic, generated by any element other than "
        "the identity.")


def _tie() -> list[GraphNode]:
    return [
        GraphNode("left", NodeKind.CLAIM, "finite group", BODY),
        GraphNode("right", NodeKind.CLAIM, "finite group", BODY),
    ]


@pytest.mark.parametrize("limit", [1, 2, 10])
def test_a_tie_abstains_at_every_limit(limit: int) -> None:
    result = retrieve("finite group", nodes=_tie(), edges=[], limit=limit, min_margin=0.2)
    assert result.abstained
    assert result.reason is AbstentionReason.AMBIGUOUS_TOP_MATCH
    assert len(result.hits) == min(limit, 2)


def test_a_clear_winner_is_served_at_limit_one() -> None:
    nodes = [
        GraphNode("strong", NodeKind.CLAIM, "finite group", BODY),
        GraphNode("weak", NodeKind.CLAIM, "commutative ring",
                  "A commutative ring with unity whose group of units is finite has a maximal "
                  "ideal."),
    ]
    everything = retrieve("finite group", nodes=nodes, edges=[], limit=10)
    supports = sorted((h.support_score for h in everything.hits), reverse=True)
    assert len(supports) == 2 and supports[0] - supports[1] >= 0.2  # the fixture's premise
    result = retrieve("finite group", nodes=nodes, edges=[], limit=1, min_margin=0.2)
    assert not result.abstained
    assert [h.node.id for h in result.hits] == ["strong"]


def test_one_candidate_is_not_ambiguous() -> None:
    nodes = [GraphNode("only", NodeKind.CLAIM, "finite group", BODY)]
    result = retrieve("finite group", nodes=nodes, edges=[], limit=1, min_margin=0.2)
    assert not result.abstained


def test_weak_support_still_abstains_below_the_threshold() -> None:
    result = retrieve("finite group", nodes=_tie(), edges=[], limit=1, min_support_score=1e6)
    assert result.abstained
    assert result.reason is AbstentionReason.BELOW_SUPPORT_THRESHOLD


def test_a_linked_pair_is_served_at_limit_one() -> None:
    linked = GraphEdge("left", "right", EdgeKind.CITES, "the one cites the other")
    result = retrieve("finite group", nodes=_tie(), edges=[linked], limit=1, min_margin=0.2)
    assert not result.abstained
    # the link resolves the subject only when both are shown, so both are served (interactive audit B100-01)
    assert {hit.node.id for hit in result.hits} == {"left", "right"}


def test_the_default_margin_never_abstains_for_ambiguity() -> None:
    for limit in (1, 2, 10):
        result = retrieve("finite group", nodes=_tie(), edges=[], limit=limit)
        assert not result.abstained
        assert len(result.hits) == min(limit, 2)


# A claim with no statement in it (a stub) is ranked below every claim that says something, yet
# its title alone can carry the highest support in the pool. account03/B03 r88,
# B03-R72-DEGENERATE-CONTENDER-BREAKS-MARGIN-SEMANTICS-001: the ambiguity test and the support
# floor compared it in anyway.
A_BODY = ("Every finite group of prime order is cyclic, generated by any element other than "
          "the identity.")
B_BODY = ("A finite group of prime order p is cyclic, and every non-identity element generates "
          "the whole group.")
RING = GraphNode("ring", NodeKind.CLAIM, "commutative ring",
                 "A commutative ring with unity whose group of units is finite has a maximal "
                 "ideal.")


def _supports(nodes: list[GraphNode]) -> dict[str, float]:
    return {h.node.id: h.support_score
            for h in retrieve("finite group", nodes=nodes, edges=[], limit=10).hits}


def test_a_stub_does_not_hide_a_tie_between_two_statements() -> None:
    nodes = [GraphNode("a", NodeKind.CLAIM, "finite group", A_BODY),
             GraphNode("b", NodeKind.CLAIM, "finite group", B_BODY),
             GraphNode("stub", NodeKind.CLAIM, "finite group", "Finite group."), RING]
    s = _supports(nodes)
    assert s["stub"] - max(s["a"], s["b"]) >= 0.2 and abs(s["a"] - s["b"]) < 0.2  # the premise
    result = retrieve("finite group", nodes=nodes, edges=[], limit=10, min_margin=0.2)
    assert result.abstained and result.reason is AbstentionReason.AMBIGUOUS_TOP_MATCH


def test_a_linked_stub_does_not_hide_the_tie_either() -> None:
    nodes = [GraphNode("a", NodeKind.CLAIM, "finite group", A_BODY),
             GraphNode("b", NodeKind.CLAIM, "finite group", B_BODY),
             GraphNode("stub", NodeKind.CLAIM, "finite group", "Groups of prime order are cyclic.")]
    edges = [GraphEdge("stub", "a", EdgeKind.SPECIALIZES, "the stub names the theorem")]
    result = retrieve("finite group", nodes=nodes, edges=edges, limit=10, min_margin=0.2)
    assert result.abstained and result.reason is AbstentionReason.AMBIGUOUS_TOP_MATCH


def test_a_stub_close_to_the_answer_does_not_force_an_abstention() -> None:
    nodes = [GraphNode("a", NodeKind.CLAIM, "finite group", A_BODY),
             GraphNode("stub", NodeKind.CLAIM, "finite group", "Groups of prime order are cyclic."),
             RING]
    s = _supports(nodes)
    assert abs(s["stub"] - s["a"]) < 0.2 and s["a"] - s["ring"] >= 0.2  # the premise
    result = retrieve("finite group", nodes=nodes, edges=[], limit=10, min_margin=0.2)
    assert not result.abstained
    assert result.hits[0].node.id == "a"


def test_a_stub_does_not_carry_weak_statements_past_the_support_floor() -> None:
    nodes = [GraphNode("a", NodeKind.CLAIM, "finite group", A_BODY),
             GraphNode("stub", NodeKind.CLAIM, "finite group", "Finite group."), RING]
    s = _supports(nodes)
    floor = (s["a"] + s["stub"]) / 2
    assert s["a"] < floor < s["stub"]  # the premise
    result = retrieve("finite group", nodes=nodes, edges=[], limit=10, min_support_score=floor)
    assert result.abstained and result.reason is AbstentionReason.BELOW_SUPPORT_THRESHOLD


def test_stubs_alone_are_still_compared() -> None:
    nodes = [GraphNode("s1", NodeKind.CLAIM, "finite group", "Finite group."),
             GraphNode("s2", NodeKind.CLAIM, "finite group", "Finite group.")]
    result = retrieve("finite group", nodes=nodes, edges=[], limit=10, min_margin=0.2)
    assert result.abstained and result.reason is AbstentionReason.AMBIGUOUS_TOP_MATCH

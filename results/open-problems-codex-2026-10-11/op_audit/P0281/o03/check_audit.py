ROOT=Path(__file__).resolve().parent
def partitions(n,cap):
 return (tuple(reversed(x)) for x in combinations_with_replacement(range(cap+1),n))
def below(top):
 if len(top)==1:
  yield (top,)
 else:
  for row in product(*(range(top[i+1],top[i]+1) for i in range(len(top)-1))):
   for a in below(row): yield a+(top,)
def arrays(n,cap):
 return [a for top in partitions(n,cap) for a in below(top)]
def flat(a): return sum(a,())
def unflat(x,n):
 a=[]; p=0
 for m in range(1,n+1): a.append(tuple(x[p:p+m])); p+=m
 return tuple(a)
def weight(a,t=F(1)):
 top=a[-1]; n=len(top); ell=[v+n-1-i for i,v in enumerate(top)]
 return t**sum(top)*F(prod(ell[i]-ell[j] for i in range(n) for j in range(i+1,n)),prod(factorial(v) for v in ell))
def events(a):
 # Independent implementation using BF raw ascending coordinates and clocks.
 z=[list(reversed([v-1-i for i,v in enumerate(row)])) for row in a]
 for m,row in enumerate(z):
  for k,v in enumerate(row):
   if m and k<m and v==z[m-1][k]-1: continue
   b=[r[:] for r in z]; mm=m; kk=k
   while True:
    b[mm][kk]+=1
    if mm+1>=len(z) or z[mm+1][kk+1]!=v: break
    mm+=1; kk+=1
   yield tuple(tuple(v+i+1 for i,v in enumerate(reversed(r))) for r in b)
report={}
for n,cap in [(1,12),(2,7),(3,4),(4,2)]:
 aa=arrays(n,cap); ww={flat(a):weight(a) for a in aa}; count=0
 for ii,a in enumerate(aa):
  x=flat(a)
  for b in aa[ii:]:
   y=flat(b); r=tuple((u+v)//2 for u,v in zip(x,y)); s=tuple((u+v+1)//2 for u,v in zip(x,y))
   assert r in ww and s in ww
   assert ww[x]*ww[y]<=ww[r]*ww[s]
   count+=1
 # Master equation at three exact rational times, including outgoing transitions beyond cap.
 for t in [F(1,2),F(1),F(2)]:
  weights={a:weight(a,t) for a in aa}; rhs=defaultdict(F)
  for a in aa:
   for b in events(a):
    rhs[a]-=weights[a]
    if b in weights: rhs[b]+=weights[a]
  for a in aa:
   assert rhs[a]==(F(sum(a[-1]),1)/t-n)*weights[a],(n,t,a,rhs[a])
 marginal=defaultdict(F)
 for a in aa: marginal[tuple(row[-1] for row in a)]+=weight(a)
 edges=list(marginal); marginal_checks=0
 for ii,d in enumerate(edges):
  for e in edges[ii:]:
   r=tuple((u+v)//2 for u,v in zip(d,e)); s=tuple((u+v+1)//2 for u,v in zip(d,e))
   assert marginal[d]*marginal[e]<=marginal[r]*marginal[s]
   marginal_checks+=1
 report[f'arrays_n{n}']={'cap':cap,'states':len(aa),'midpoint_pairs':count,'master_equation_times':['1/2','1','2'],'truncated_edge_midpoint_pairs':marginal_checks}

# Finite coefficient test: e^(nt) times the TASEP law is generated by Q+nI.
# Sum of top row = coefficient degree, so degrees <=K need no tail estimate.
for n,K in [(1,12),(2,10),(3,8),(4,6)]:
 coeff=defaultdict(F); norm=defaultdict(F); total=0
 for top in partitions(n,K):
  k=sum(top)
  if k>K: continue
  for a in below(top):
   c=weight(a); edge=tuple(row[-1] for row in a)
   coeff[k,edge]+=c; norm[k]+=c; total+=1
 for k in range(K+1): assert norm[k]==F(n**k,factorial(k))
 v={tuple([0]*n):1}; comparisons=0
 for k in range(K+1):
  states={e for kk,e in coeff if kk==k}|set(v)
  for e in states:
   assert coeff[k,e]==F(v.get(e,0),factorial(k)),(n,k,e)
   comparisons+=1
  nxt=defaultdict(int)
  for e,c in v.items():
   movable=[i for i in range(n) if i==0 or e[i]<e[i-1]]
   nxt[e]+=(n-len(movable))*c
   for i in movable:
    b=list(e); b[i]+=1; nxt[tuple(b)]+=c
  v=dict(nxt)
 report[f'edge_coefficients_n{n}']={'degree':K,'arrays':total,'coefficient_comparisons':comparisons,'normalization':'n^k/k!'}

# Determinant identity (5), stripped of the common exponential, exact rational t.
det_checks=0
for n in range(1,5):
 for top in partitions(n,5):
  L=list(reversed([v+n-1-i for i,v in enumerate(top)]))
  for t in [F(1,2),F(1),F(3,2)]:
   mat=sp.Matrix([[sp.Rational(t.numerator,t.denominator)**(v-i)/factorial(v-i) if v>=i else 0 for v in L] for i in range(n)])
   target=weight((top,),t)
   assert mat.det()==sp.Rational(target.numerator,target.denominator)
   det_checks+=1
report['determinant_checks']=det_checks
# Equal-alpha link normalization, using shifted descending ell in adjacent rows.
links=0
for n in range(2,6):
 for top in partitions(n,4):
  ell=[v+n-1-i for i,v in enumerate(top)]
  V=prod(ell[i]-ell[j] for i in range(n) for j in range(i+1,n)); total=F(0)
  for row in product(*(range(top[i+1],top[i]+1) for i in range(n-1))):
   small=[v+n-2-i for i,v in enumerate(row)]
   total+=F(factorial(n-1)*prod(small[i]-small[j] for i in range(n-1) for j in range(i+1,n-1)),V)
  assert total==1
  links+=1
report['normalized_links']=links
(ROOT/'independent_checks.json').write_text(json.dumps(report,indent=2),encoding='utf-8')

from fractions import Fraction as F
T = {0: F(1), 2: F(1), 4: F(8, 3), 6: F(11), 8: F(908, 15), 10: F(415),
     12: F(23840, 7), 14: F(325719, 10), 16: F(112135066, 315), 18: F(3065263961, 700),
     20: F(69174280444, 1155), 22: F(5680684105259, 6300),
     24: F(1112571762134554, 75075), 26: F(2032842751996209, 7700),
     28: F(1141293103886559392, 225225), 30: F(41741563830607349103, 400400)}
th30 = F(20400080756487813407473535015531475707321094536519875734216596825611281168384900829349,
         195694496922376637414127809726999995423516487096364318258954222739680000)
rat = [T[2 * k + 2] / T[2 * k] for k in range(1, 15)]
print("ratios:", ", ".join(f"{float(r):.4f}" for r in rat))
print("diffs:", ", ".join(f"{float(rat[i+1]-rat[i]):.4f}" for i in range(len(rat) - 1)))
print("passing diff at 30:", f"{float(th30 / T[28] - T[28] / T[26]):.4f}")
mg = T[30] - th30
print("margin", f"{float(mg):.4e}", "relative", f"{float(mg / th30):.3e}")

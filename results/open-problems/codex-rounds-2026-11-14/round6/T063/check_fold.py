"""Exact deterministic audit of the all-level fold. Standard library only.

Finite wired sets are generated by component reachability, independently of
the two decoders. Integer heights and residuals are never sampled from a
truncated geometric law. Residual values here are deterministic test inputs.
"""
from collections import Counter, deque
from fractions import Fraction
from itertools import product
from math import fsum, log
import os
import random
import resource
import signal
import sys
import time


def geometry(w, h):
    xy = [(x, y) for y in range(h) for x in range(w)]
    nn = [(i, j) for i, (x, y) in enumerate(xy)
          for j in (i+1, i+w) if j < w*h
          and abs(x-xy[j][0])+abs(y-xy[j][1]) == 1]
    ds = []
    for y in range(h-1):
        for x in range(w-1):
            i = y*w+x
            ds.extend(((i, i+w+1, i+1, i+w), (i+1, i+w, i, i+w+1)))
    boundary = [i for i, (x, y) in enumerate(xy)
                if x in (0, w-1) or y in (0, h-1)]
    return xy, nn, ds, boundary


def heights(w, h, nn):
    """All graph homomorphisms anchored at zero; row-order backtracking."""
    out, a = [], [None]*(w*h)
    a[0] = 0

    def visit(i):
        if i == len(a):
            out.append(tuple(a))
            return
        previous = [a[u] for u, j in nn if j == i]
        for value in (previous[0]-1, previous[0]+1):
            if all(abs(value-z) == 1 for z in previous):
                a[i] = value
                visit(i+1)
    visit(1)
    return out


def graph(D, residual, level, nn, ds, plus=False):
    valid = {i for i, d in enumerate(D) if (d > level if plus else d < level)}
    edges = [(u, v) for u, v in nn if u in valid and v in valid]
    endpoint = level+1 if plus else level-1
    for (u, v, z, t), n in zip(ds, residual):
        if n == 0 and D[u] == D[v] == endpoint and D[z] == D[t] == level:
            edges.append((u, v))
    adj = {i: [] for i in valid}
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    return adj


def reachable(adj, seeds, allowed=None):
    allowed = set(adj) if allowed is None else set(allowed) & set(adj)
    reached = set(seeds) & allowed
    queue = deque(reached)
    while queue:
        u = queue.popleft()
        for v in adj[u]:
            if v in allowed and v not in reached:
                reached.add(v)
                queue.append(v)
    return reached


def wired_bands(D, residual, M, thresholds, nn, ds, boundary):
    """Define nested wired sets first, then extract k. No fold formulas."""
    lo = min(D)//M-2
    hi = max(max(D)//M+2, max(thresholds)+2)
    k, previous = [None]*len(D), set()
    for j in range(lo, hi+1):
        adj = graph(D, residual, j*M, nn, ds)
        seeds = [b for b, r in zip(boundary, thresholds) if r < j]
        assert all(b in adj for b in seeds)
        T = reachable(adj, seeds)
        assert previous <= T
        for i in T-previous:
            k[i] = j-1
        previous = T
    assert all(z is not None for z in k)
    return tuple(k)


def equality_sums(h1, h2, ds):
    return tuple(int(h1[u] == h1[v])+int(h2[u] == h2[v]) for u, v, _, _ in ds)


def fold(h1, h2, residual, k, M, ds):
    out1, out2 = [], []
    for a, b, band in zip(h1, h2, k):
        if band % 2 == 0:
            out1.append(a+band*M)
            out2.append(b-band*M)
        else:
            out1.append(b-(band+1)*M)
            out2.append(a+(band+1)*M)
    old = equality_sums(h1, h2, ds)
    new = equality_sums(out1, out2, ds)
    assert all((v-u) % 2 == 0 for u, v in zip(old, new))
    res = tuple(n+(v-u)//2 for n, u, v in zip(residual, old, new))
    assert min(res, default=0) >= 0
    return tuple(out1), tuple(out2), res


def gradient(h):
    return tuple(z-h[0] for z in h)


def clip(z, lo, hi):
    return max(lo, min(hi, z))


def data(h1, h2, res, k, M, ds, boundary, diameter):
    f1, f2, newres = fold(h1, h2, res, k, M, ds)
    D = tuple((b-a)//2 for a, b in zip(h1, h2))
    E = tuple((b-a)//2 for a, b in zip(f1, f2))
    L = M+diameter+1
    B = (tuple(k[b]-k[boundary[0]] for b in boundary),
         k[boundary[0]] % 2, clip(E[boundary[0]], -L, L))
    X = (gradient(h1), gradient(h2), D[0] % (2*M), tuple(res))
    Y = (gradient(f1), gradient(f2), E[0] % (2*M),
         tuple(clip(z, -1, M+1) for z in E), tuple(newres))
    return X, Y, B


def boundary_labels(B):
    relative, parity, _ = B
    return tuple(z+parity for z in relative)


def forward_decode(X, B, M, nn, ds, boundary, diameter):
    a, b, dmod, residual = X
    relative, parity, clipped = B
    L = M+diameter+1
    if abs(clipped) == L:
        f1, f2 = (a, b) if parity == 0 else (b, a)
        return (f1, f2, (dmod if parity == 0 else -dmod) % (2*M),
                (-1 if clipped < 0 else M+1,)*len(a), residual)
    d0 = clipped+parity*M if parity == 0 else (parity+1)*M-clipped
    D = tuple(d0+(v-u)//2 for u, v in zip(a, b))
    kb = boundary_labels(B)
    lower, upper = min(kb), max(max(kb), max(D)//M)
    k = [upper]*len(a)
    # Recover each T_j from boundary seeds, not from wired_bands().
    for j in range(lower+1, upper+1):
        T = reachable(graph(D, residual, j*M, nn, ds),
                      [bb for bb, value in zip(boundary, kb) if value < j])
        for i in T:
            k[i] = min(k[i], j-1)
    _, Y, _ = data(a, tuple(z+2*d0 for z in b), residual, k, M, ds, boundary, diameter)
    return Y


def reverse_decode(Y, B, M, nn, ds, boundary, diameter):
    a, b, emod, truncated, residual = Y
    relative, parity, clipped = B
    L = M+diameter+1
    if abs(clipped) == L:
        h1, h2 = (a, b) if parity == 0 else (b, a)
        return h1, h2, (emod if parity == 0 else -emod) % (2*M), residual
    E = tuple(clipped+(v-u)//2 for u, v in zip(a, b))
    kb = boundary_labels(B)
    lower, upper = min(kb), max(kb)+diameter
    T, k = set(), [None]*len(a)
    for band in range(lower, upper+1):
        adj = graph(E, residual, 0 if band % 2 else M, nn, ds, plus=bool(band % 2))
        seeds = {bb for bb, value in zip(boundary, kb) if value == band}
        for u, v in nn:
            if u in T and v not in T:
                seeds.add(v)
            if v in T and u not in T:
                seeds.add(u)
        layer = reachable(adj, seeds, set(range(len(a)))-T)
        for i in layer:
            k[i] = band
        T.update(layer)
    assert len(T) == len(a)
    # Invert the height fold pointwise with the recovered band labels.
    h1, h2 = [], []
    for u, v, band in zip(a, (z+2*clipped for z in b), k):
        if band % 2 == 0:
            h1.append(u-band*M)
            h2.append(v+band*M)
        else:
            h1.append(v-(band+1)*M)
            h2.append(u+(band+1)*M)
    old = equality_sums(h1, h2, ds)
    new = equality_sums(a, tuple(z+2*clipped for z in b), ds)
    res = tuple(n-(v-u)//2 for n, u, v in zip(residual, old, new))
    D0 = (h2[0]-h1[0])//2
    return gradient(h1), gradient(h2), D0 % (2*M), res


def check_case(h1, h2, res, thresholds, M, geom, diameter, counts):
    xy, nn, ds, boundary = geom
    D = tuple((b-a)//2 for a, b in zip(h1, h2))
    k = wired_bands(D, res, M, thresholds, nn, ds, boundary)
    f1, f2, rr = fold(h1, h2, res, k, M, ds)
    assert all(abs(f[u]-f[v]) == 1 for f in (f1, f2) for u, v in nn)
    assert all(a+b == u+v for a, b, u, v in zip(h1, h2, f1, f2))
    old, new = equality_sums(h1, h2, ds), equality_sums(f1, f2, ds)
    # Twice the invariant exponent tau; covers arbitrary c_v>1 exactly.
    assert tuple(2*n-a for n, a in zip(res, old)) == tuple(2*n-a for n, a in zip(rr, new))
    for delta in (b-a for a, b in zip(res, rr)):
        counts['residual_delta_%d' % delta] += 1
    X, Y, B = data(h1, h2, res, k, M, ds, boundary, diameter)
    assert forward_decode(X, B, M, nn, ds, boundary, diameter) == Y
    assert reverse_decode(Y, B, M, nn, ds, boundary, diameter) == X
    counts['cases'] += 1
    counts['constant' if len(set(k)) == 1 else 'nonconstant'] += 1
    if max(k) > max(k[i] for i in boundary):
        counts['interior_above_boundary'] += 1
    if abs(B[2]) == M+diameter+1:
        counts['saturated_%s' % ('plus' if B[2] > 0 else 'minus')] += 1
    if min(res, default=0) > 1:
        counts['large_residual'] += 1
    return X, Y, B


def entropy_audit(records, ds, M, diameter, boundary):
    """Direct finite FE calculation and independent joint-count chain rule."""
    cx, cy, cxb, cyb = Counter(), Counter(), Counter(), Counter()
    forward, backward = {}, {}
    for X, Y, B in records:
        assert forward.setdefault((X, B), Y) == Y
        assert backward.setdefault((Y, B), X) == X
        cx[X] += 1
        cy[Y] += 1
        cxb[X, B] += 1
        cyb[Y, B] += 1
        a = equality_sums(X[0], X[1], ds)
        b = equality_sums(Y[0], Y[1], ds)
        ex = sum(a)-2*sum(X[3])
        ey = sum(b)-2*sum(Y[4])
        assert Fraction(3, 2)**ex == Fraction(3, 2)**ey
    N = len(records)
    H = lambda counter: -fsum((n/N)*log(n/N) for n in counter.values())
    def FE(counter, index):
        return fsum((n/N)*(log(n/N)-(sum(equality_sums(z[0], z[1], ds))
                                     -2*sum(z[index]))*log(1.5))
                    for z, n in counter.items())
    delta = FE(cy, 4)-FE(cx, 3)
    chain = (H(cyb)-H(cy))-(H(cxb)-H(cx))
    K = 2*3**(len(boundary)-1)*(2*(M+diameter+1)+1)
    assert sorted(cxb.values()) == sorted(cyb.values())
    assert abs(delta-chain) < 1e-11 and abs(delta) <= log(K)+1e-11
    print('entropy: records=%d X=%d Y=%d XB=%d YB=%d FE_difference=%.12f chain_difference=%.12f bound=log(%d) PASS'
          % (N, len(cx), len(cy), len(cxb), len(cyb), delta, chain, K))


def fixtures(counts):
    geom = geometry(3, 3)
    xy, nn, ds, boundary = geom
    a = (0, -1, 0, -1, -2, -1, 0, -1, 0)
    b = tuple(-v for v in a)
    D = tuple((v-u)//2 for u, v in zip(a, b))
    residual = (7,)*len(ds)
    k = wired_bands(D, residual, 2, (0,)*len(boundary), nn, ds, boundary)
    assert k == (0, 0, 0, 0, 1, 0, 0, 0, 0)
    check_case(a, b, residual, (0,)*len(boundary), 2, geom, 4, counts)
    print('regression: boundary bands all 0, centre band 1, both decoders PASS')
    geom = geometry(5, 5)
    xy, nn, ds, boundary = geom
    for M, offset in product((2, 3, 4), (-5, 0, 5)):
        a = tuple(-x+y for x, y in xy)
        b = tuple(x+y+2*offset for x, y in xy)
        D = tuple(x+offset for x, y in xy)
        thresholds = tuple(D[i]//M for i in boundary)
        residual = tuple(i % 3 for i in range(len(ds)))
        k = wired_bands(D, residual, M, thresholds, nn, ds, boundary)
        assert k == tuple(d//M for d in D)
        check_case(a, b, residual, thresholds, M, geom, 8, counts)
    print('infinite affine-height restrictions: 9 half-plane-band fixtures PASS')


def main():
    signal.alarm(180)
    start = time.monotonic()
    assert os.environ.get('OMP_NUM_THREADS') == '1'
    priority = os.getpriority(os.PRIO_PROCESS, 0)
    assert priority >= 15
    print('OMP_NUM_THREADS=1; effective_nice=%d' % priority)
    counts = Counter()
    geom = geometry(2, 2)
    hs = heights(2, 2, geom[1])
    assert len(hs) == 6
    records = []
    # Exhaust all pair profiles, offsets, boundary bits and zero/one residuals.
    for M in (2, 3):
        xy, nn, ds, boundary = geom
        for a, base, shift in product(hs, hs, range(-4, 5)):
            b = tuple(z+2*shift for z in base)
            D = tuple((v-u)//2 for u, v in zip(a, b))
            for bits in product((0, 1), repeat=len(boundary)):
                thresholds = tuple(D[i]//M+bit for i, bit in zip(boundary, bits))
                for res in product((0, 1), repeat=len(ds)):
                    result = check_case(a, b, res, thresholds, M, geom, 2, counts)
                    if M == 2 and -2 <= shift <= 2:
                        records.append(result)
    print('exhaustive 2x2 cases=%d PASS' % counts['cases'])
    entropy_audit(records, geom[2], 2, 2, geom[3])
    del records
    rng = random.Random(63006)
    for w, h in ((3, 3), (4, 3), (3, 4)):
        geom = geometry(w, h)
        xy, nn, ds, boundary = geom
        hs = heights(w, h, nn)
        # Independent brute assignment count for the 3x3 profile library.
        if (w, h) == (3, 3):
            direct = []
            for values in product(*[range(-x-y, x+y+1, 2) for x, y in xy[1:]]):
                a = (0,)+values
                if all(abs(a[u]-a[v]) == 1 for u, v in nn):
                    direct.append(a)
            assert set(direct) == set(hs)
        before = counts['cases']
        for z in range(1800):
            a, base = rng.choice(hs), rng.choice(hs)
            shift = rng.randrange(-12, 13)
            b = tuple(v+2*shift for v in base)
            M = (2, 3, 4, 7)[z % 4]
            D = tuple((v-u)//2 for u, v in zip(a, b))
            if z % 6 == 0:
                threshold = max(D)//M+20+(z % 2)
                thresholds = (threshold,)*len(boundary)
            else:
                thresholds = tuple(D[i]//M+rng.randrange(4) for i in boundary)
            res = tuple(rng.choice((0, 1, 2, 7)) for _ in ds)
            X, Y, B = check_case(a, b, res, thresholds, M, geom, w+h-2, counts)
            # A quotient shift by V_{2M} must leave all encoded data unchanged.
            kk = wired_bands(D, res, M, thresholds, nn, ds, boundary)
            shifted = data(a, tuple(v+4*M for v in b), res,
                           tuple(v+2 for v in kk), M, ds, boundary, w+h-2)
            assert shifted == (X, Y, B)
            counts['quotient_shift'] += 1
        print('wired %dx%d: profiles=%d cases=%d PASS' % (w, h, len(hs), counts['cases']-before))
    fixtures(counts)
    assert counts['residual_delta_-1'] and counts['residual_delta_1']
    assert counts['saturated_plus'] and counts['saturated_minus']
    assert counts['nonconstant'] and counts['large_residual']
    assert counts['interior_above_boundary']
    print('counts=%s' % dict(sorted(counts.items())))
    rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    if sys.platform != 'darwin':
        rss *= 1024
    assert rss < 1_000_000_000
    print('peak_RSS_bytes=%d; elapsed_seconds=%.3f' % (rss, time.monotonic()-start))


if __name__ == '__main__':
    main()

# Symmetry group generated by transpose and order reversal.
def tr(r):
    d={p:r[k] for k,p in enumerate(PAIRS)}
    return tuple(d[(j,i)] for i,j in PAIRS)
def rev(r):
    d={p:r[k] for k,p in enumerate(PAIRS)}
    return tuple(d[(3-i,3-j)] for i,j in PAIRS)
def orb(r):
    return {r,tr(r),rev(r),tr(rev(r))}
rem=set(RAYS); orbits=[]
while rem:
    r=min(rem); o=orb(r)&set(RAYS); orbits.append(sorted(o)); rem-=o

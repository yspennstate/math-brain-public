def qcoeff(i,j):
    v=[0]*12
    if i==j:
        for k in range(4):
            if k!=i: v[IDX[(i,k)]]-=1
    else:
        v[IDX[(i,j)]]=1
    return sp.Matrix([v])

def mono_rows(transpose=False):
    rows=[]
    def coeff(i,j):
        return qcoeff(j,i) if transpose else qcoeff(i,j)
    for i in range(4):
        for ip in range(i+1,4):
            for k in range(4):
                U=list(range(k,4))
                if U and i not in U and ip not in U:
                    r=sp.zeros(1,12)
                    for j in U: r += coeff(i,j)-coeff(ip,j)
                    if any(r): rows.append(r)
            for k in range(4):
                D=list(range(0,k+1))
                if D and i not in D and ip not in D:
                    r=sp.zeros(1,12)
                    for j in D: r += coeff(ip,j)-coeff(i,j) # <=0
                    if any(r): rows.append(r)
    out=[]
    for r in rows:
        t=tuple(int(x) for x in r)
        if t not in [tuple(int(x) for x in z) for z in out]: out.append(r)
    return out

# Uniform stationarity equalities. Four column-sum equations have rank 3.
E=[]

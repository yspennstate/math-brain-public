assert sorted(len(o) for o in orbits)==sorted([2,1,2,4,1,4,2,2,1,4,2,2,4,2,4])


def sccs_of_ray(r):
    adj=[[] for _ in range(4)]; radj=[[] for _ in range(4)]
    for z,(i,j) in zip(r,PAIRS):
        if z>0:
            adj[i].append(j); radj[j].append(i)
    seen=[False]*4; order=[]
    def dfs(v):
        seen[v]=True
        for w in adj[v]:
            if not seen[w]: dfs(w)
        order.append(v)
    for v in range(4):
        if not seen[v]: dfs(v)
    seen=[False]*4; comps=[]
    def rdfs(v,c):
        seen[v]=True; c.append(v)
        for w in radj[v]:
            if not seen[w]: rdfs(w,c)
    for v in reversed(order):
        if not seen[v]:
            c=[]; rdfs(v,c); comps.append(tuple(sorted(c)))
    return sorted(comps)

def is_reversible_uniform(r):
    d={p:r[k] for k,p in enumerate(PAIRS)}
    return all(d[(i,j)]==d[(j,i)] for i,j in PAIRS)

irr_rev=irr_nonrev=red_rev=red_nonrev=0
red_partitions=[]
for r in RAYS:
    comps=sccs_of_ray(r)
    irr=(len(comps)==1)
    rev=is_reversible_uniform(r)
    if irr and rev: irr_rev+=1
    elif irr: irr_nonrev+=1
    elif rev: red_rev+=1
    else: red_nonrev+=1
    if not irr:
        # With positive uniform stationarity every SCC is closed; in these exact rays all are contiguous blocks.
        assert all(list(c)==list(range(min(c),max(c)+1)) for c in comps)
        assert len(comps)<=3
        red_partitions.append(comps)

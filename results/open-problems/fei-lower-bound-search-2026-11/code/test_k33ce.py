# the three index-2 subgroups of the k33c group, as sets of permutations of the 9 points (identity labelling):
# k33cs, ap_9ck, k33ce.  Checks: each has order 36 and lies in the k33c group (order 72); the three are different;
# the k33c group has exactly three subgroups of index 2 (counted from its homomorphisms onto a group of order 2:
# a subgroup of index 2 is the set of elements on which a sign rule, multiplicative on generators, is +1);
# every k33ce class lies inside one k33c class.   usage: python3 test_k33ce.py CODEDIR
import sys
import itertools
sys.path.insert(0, sys.argv[1])
import sym_search as S


def closure(gens, n):
    idt = tuple(range(n)); seen = {idt}; stack = [idt]
    while stack:
        x = stack.pop()
        for g in gens:
            y = tuple(g[x[i]] for i in range(n))
            if y not in seen:
                seen.add(y); stack.append(y)
    return seen


def points(name):
    m, gens, e = S.struct(name)
    assert m == 18 and all(all(g[9 + i] == 9 + g[i] for i in range(9)) for g in gens)
    return [tuple(g[:9]) for g in gens], e


K = closure(points("k33c")[0], 9)
grp = {}
for nm in ("k33cs", "ap_9ck", "k33ce"):
    pg, e = points(nm)
    grp[nm] = closure(pg, 9)
    print(nm, "order", len(grp[nm]), "inside k33c group", grp[nm] <= K, "edges", e == points("k33c")[1])
print("pairwise different:", all(grp[a] != grp[b] for a, b in itertools.combinations(grp, 2)))
# all subgroups of index 2: H of size 36 with H closed; found as kernels: for h outside H, K = H + hH.  Enumerate by
# the elements' images: a subgroup of index 2 contains every square and every commutator; quotient by those.
sq = set()
for a in K:
    sq.add(tuple(a[a[i]] for i in range(9)))
core = closure(list(sq), 9)                      # generated by the squares: its index is 2^r, index-2 subgroups 2^r - 1
print("subgroup generated by squares has order", len(core), "-> index-2 subgroups:", 72 // len(core) - 1)
m, g, _ = S.struct("k33ce"); mk, gk, _ = S.struct("k33c")
r1, c1, s1 = S.orbits(m, g); r2, c2, s2 = S.orbits(mk, gk)
img = {}; ok = True
for x in range(1 << m):
    a, b = int(c1[x]), int(c2[x])
    if img.setdefault(a, b) != b:
        ok = False; break
print("k33ce classes %d; every one inside one k33c class: %s; sizes sum %s" % (len(r1), ok, int(s1.sum()) == 1 << m))

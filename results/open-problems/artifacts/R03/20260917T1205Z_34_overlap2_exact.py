#!/usr/bin/env python3
"""
R03 run34 exact checker: previously uncredited overlap-two sign-relation planes.

Finite scope:
- m=10 binary reduction, p=11.
- Enumerate projective +/-1 relation lines of support 3 or 4.
- Form 2-planes generated by two such lines whose supports overlap in exactly 2 coordinates.
- Conservatively discard every plane containing ANY pair of projective +/-1 relation lines
  whose supports overlap in <=1 coordinate. This excludes every plane that could have appeared
  in the retained disjoint-support or overlap-one M2 catalogs.
- Discard every plane containing a projective vector of support <=2 (would force row collisions).
- For the remaining planes, compute the Boolean orthogonal slice exactly, the exact largest
  hyperplane fiber in its local factor, and a greedy lower bound on ordered Boolean bases.
- This certifies exact left modular nullity 2 for a matrix-disjoint plane family and reclaims
  the uniform conservative p-c slack in the retained C253-based majorant, lowering r(11).

All arithmetic affecting the certificate is integer / Fraction exact.
"""

from itertools import combinations, product
from collections import Counter
from fractions import Fraction
from decimal import Decimal, getcontext
from math import prod

getcontext().prec = 70
M = 10
P = 11


def sign_lines_support(s):
    out = []
    for supp in combinations(range(M), s):
        mask = sum(1 << i for i in supp)
        # projective +/-1 line: normalize first nonzero coefficient to +1
        for tail in product((1, -1), repeat=s-1):
            v = [0] * M
            v[supp[0]] = 1
            for i,sgn in zip(supp[1:], tail):
                v[i] = sgn % P
            out.append((tuple(v), mask))
    return out


def rref_two(v, w, n=M):
    A = [list(v), list(w)]
    r = 0
    for c in range(n):
        pivot = None
        for rr in range(r, 2):
            if A[rr][c] % P:
                pivot = rr
                break
        if pivot is None:
            continue
        A[r], A[pivot] = A[pivot], A[r]
        inv = pow(A[r][c] % P, -1, P)
        A[r] = [(x * inv) % P for x in A[r]]
        for rr in range(2):
            if rr != r and A[rr][c] % P:
                f = A[rr][c] % P
                A[rr] = [(A[rr][j] - f*A[r][j]) % P for j in range(n)]
        r += 1
        if r == 2:
            break
    assert r == 2
    return tuple(A[0] + A[1])


def plane_projective_lines(key):
    v = key[:M]
    w = key[M:]
    # projective P^1(F_p): [1:t], t in F_p, plus [0:1]
    out = []
    for t in range(P):
        out.append(tuple((v[i] + t*w[i]) % P for i in range(M)))
    out.append(tuple(w))
    assert len(out) == P + 1
    return out


def support_mask(u):
    return sum(1 << i for i,x in enumerate(u) if x % P)


def is_sign_relation(u):
    nz = [x % P for x in u if x % P]
    if not nz:
        return False
    inv = pow(nz[0], -1, P)
    return all((x * inv) % P in (1, P-1) for x in nz)


def admissible_new_plane(key):
    """Conservative new-family test against all old overlap 0/1 sign-line planes."""
    pls = plane_projective_lines(key)
    masks = [support_mask(u) for u in pls]
    if min(mask.bit_count() for mask in masks) <= 2:
        return False
    sign_masks = [support_mask(u) for u in pls if is_sign_relation(u)]
    for i in range(len(sign_masks)):
        for j in range(i+1, len(sign_masks)):
            if (sign_masks[i] & sign_masks[j]).bit_count() <= 1:
                return False
    return True


def rank_mod(rows, ncols):
    A = [list(map(lambda x: x % P, row)) for row in rows]
    r = 0
    for c in range(ncols):
        pivot = next((i for i in range(r, len(A)) if A[i][c] % P), None)
        if pivot is None:
            continue
        A[r], A[pivot] = A[pivot], A[r]
        inv = pow(A[r][c] % P, -1, P)
        A[r] = [(x * inv) % P for x in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c] % P:
                f = A[i][c] % P
                A[i] = [(A[i][j] - f*A[r][j]) % P for j in range(ncols)]
        r += 1
        if r == len(A):
            break
    return r


def projective_forms(r):
    for first in range(r):
        for tail in product(range(P), repeat=r-first-1):
            yield (0,)*first + (1,) + tail


def local_stats(u, local_key):
    row1 = local_key[:u]
    row2 = local_key[u:]
    rows = (row1, row2)
    pivots = [next(i for i,x in enumerate(row) if x % P) for row in rows]
    free = [i for i in range(u) if i not in pivots]
    r = len(free)
    assert r == u-2

    pts = []
    coords = []
    for bits in product((0,1), repeat=u):
        if (sum(row1[i]*bits[i] for i in range(u)) % P == 0 and
            sum(row2[i]*bits[i] for i in range(u)) % P == 0):
            pts.append(bits)
            coords.append(tuple(bits[i] for i in free))

    if rank_mod(coords, r) < r:
        return len(pts), None, r

    q = 0
    for a in projective_forms(r):
        counts = Counter(sum(ai*xi for ai,xi in zip(a,x)) % P for x in coords)
        q = max(q, max(counts.values()))
    return len(pts), q, r


L3 = sign_lines_support(3)
L4 = sign_lines_support(4)
assert len(L3) == 480
assert len(L4) == 1680

# Candidate unique planes generated by support-3/4 sign lines with overlap exactly 2.
candidates = {}

def add_pairs(A, B, same=False):
    if same:
        for i,j in combinations(range(len(A)), 2):
            v,mv = A[i]
            w,mw = A[j]
            if (mv & mw).bit_count() != 2:
                continue
            k = rref_two(v,w)
            candidates.setdefault(k, (mv,mw))
    else:
        for v,mv in A:
            for w,mw in B:
                if (mv & mw).bit_count() != 2:
                    continue
                k = rref_two(v,w)
                candidates.setdefault(k, (mv,mw))

add_pairs(L3, L3, same=True)
add_pairs(L3, L4, same=False)
add_pairs(L4, L4, same=True)
assert len(candidates) == 604800

keepers = []
for key,(mv,mw) in candidates.items():
    if admissible_new_plane(key):
        keepers.append(key)
assert len(keepers) == 534240

# Compress to exact local rowspaces. The original candidate support union still contains
# the whole plane, and has size 4,5,or6. Outside it the Boolean coordinates are free.
local_counts = Counter()
for key in keepers:
    mv,mw = candidates[key]
    union = [i for i in range(M) if ((mv|mw) >> i) & 1]
    u = len(union)
    assert u in (4,5,6)
    v = [key[i] for i in union]
    w = [key[M+i] for i in union]
    lk = rref_two(v,w,n=u)
    local_counts[(u,lk)] += 1
assert len(local_counts) == 2448

summary = Counter()
total_E = 0
positive_planes = 0
nospan_planes = 0

for (u,lk), multiplicity in local_counts.items():
    hloc,q,rdim = local_stats(u,lk)
    if q is None:
        nospan_planes += multiplicity
        summary[(u,"nospan")] += multiplicity
        continue

    free = M-u
    h = hloc * (2**free)
    # A proper hyperplane either has a nonzero local restriction (q*2^free)
    # or, if its local restriction vanishes, cuts the free cube in at most half.
    Q = q * (2**free)
    if free:
        Q = max(Q, h//2)

    factors = [h - min(2**j, Q) for j in range(M-2)]
    if min(factors) <= 0 or h <= M:
        summary[(u,"zero",hloc,q,h,Q)] += multiplicity
        continue

    basis = prod(factors)
    tail = (h-M+1)*(h-M)
    per_plane = basis*tail
    total_E += multiplicity*per_plane
    positive_planes += multiplicity
    summary[(u,"positive",hloc,q,h,Q)] += multiplicity

assert positive_planes == 253890
assert nospan_planes == 280350
assert positive_planes + nospan_planes == len(keepers)

# Exact class regression.

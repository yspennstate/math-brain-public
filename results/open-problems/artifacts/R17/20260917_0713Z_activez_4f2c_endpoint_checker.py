print('fixed_z_machine_lower_upper_decimal =',dec(B_lower_hi))
print('fixed_z_machine_upper_lower_decimal =',dec(B_upper_lo))
print('fixed_z_machine_upper_decimal =',dec(B_upper_hi))
print('fixed_z_machine_bracket_width_decimal =',dec(B_upper_hi-B_lower_lo))

from fractions import Fraction
from decimal import Decimal, getcontext
getcontext().prec = 120

z = Fraction(320896250000000001555829, 10**24)
a = 2*z
lam_hi = Fraction(
    2843189737668456825766410880179840192382738891786753771961640989,
    8317735052872827843750000000000000000000000000000000000000000000,
)
lam_lo = Fraction(
    701902846068534238006565436831971247585866790965032360131712223,
    2053412696699963600000000000000000000000000000000000000000000000,
)

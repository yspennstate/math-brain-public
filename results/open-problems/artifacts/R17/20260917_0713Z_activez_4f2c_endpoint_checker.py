U_new = Fraction(82627917854239782538084052, 10**26)
assert 0 < a < 1 and 0 < lam_lo <= lam_hi < 1
assert U_new < U_prev

def neglog_bounds(x, terms):
    u = (1-x)/(1+x)
    assert 0 < u < 1
    s = Fraction(0)
    p = u
    for k in range(terms):
        s += p/(2*k+1)
        p *= u*u
    lo = 2*s
    hi = lo + 2*p/((2*terms+1)*(1-u*u))
    return lo, hi

Alo,Ahi = neglog_bounds(a,140)
Hlo,Hhi = neglog_bounds(lam_hi,280)
Llo,Lhi = neglog_bounds(lam_lo,280)
# B(lambda)=2*(-log(2z))/(-log lambda) increases in lambda on (0,1).
B_upper_lo = 2*Alo/Hhi
B_upper_hi = 2*Ahi/Hlo
B_lower_lo = 2*Alo/Lhi
B_lower_hi = 2*Ahi/Llo
assert B_lower_lo < B_lower_hi <= B_upper_lo < B_upper_hi < U_new
assert L < U_new

def dec(q): return Decimal(q.numerator)/Decimal(q.denominator)
print('R17-C025 exact endpoint/Collatz compiler')
print('z =',z)
print('lambda_lo =',lam_lo)
print('lambda_hi =',lam_hi)
print('EXACT_DUAL_COLLATZ_ORDER=PASS')

#!/usr/bin/env python3
"""
R08 self-check for I0082 first-variation strict-free-stable exclusion,
plus an independent exact finite audit of the R09 Tang Q4.11 candidate.

This is a SELF-CHECK / finite audit aid, not a proof of the universal analytic theorem.
"""
from fractions import Fraction
import sympy as sp
import mpmath as mp

print("R08 I0082 strict-stable first-variation SELF-CHECK")
x,r=sp.symbols("x r", positive=True)
A = r/x + (1-r)*sp.log(x/(1-x))
Aprime=sp.simplify(sp.diff(A,x))
target=(x-r)/(x**2*(1-x))
assert sp.simplify(Aprime-target)==0
assert sp.simplify(Aprime.subs(x,r))==0
assert sp.simplify(Aprime.subs(x,2*r)-1/(4*r*(1-2*r)))==0
assert sp.simplify(A.subs(x,sp.Rational(1,2))-2*r)==0
assert sp.simplify(Aprime.subs(x,sp.Rational(1,2))-(4-8*r))==0
print("exact_boundary_derivative_identity = PASS")
print("A'(r)=0; A'(2r)=1/[4r(1-2r)]; A(1/2)=2r; A'(1/2)=4-8r")

# Phase interval algebra is proved on the report page. Here we exact-check
# representative rational parameters from all relevant parameter faces.
samples=[
    (sp.Rational(1,4),sp.Rational(0,1),sp.Rational(1,3)),
    (sp.Rational(1,4),sp.Rational(1,1),sp.Rational(2,3)),
    (sp.Rational(3,4),sp.Rational(1,2),sp.Rational(4,5)),
    (sp.Rational(3,2),sp.Rational(1,3),sp.Rational(2,3)),
    (sp.Rational(3,2),sp.Rational(1,2),sp.Rational(2,3)),
    (sp.Rational(19,10),sp.Rational(9,19),sp.Rational(9,10)),
    (sp.Rational(19,10),sp.Rational(10,19),sp.Rational(9,10)),
]
for alpha,rho,theta_over_pi in samples:
    psi_over_pi=sp.simplify(alpha*rho+(1-alpha)*theta_over_pi)
    assert 0 < psi_over_pi < 1
print("representative_phase_first_quadrant_checks = PASS")

# Numerical adversarial stress of the full boundary fixed-point equation.
# Floating only; not theorem evidence.
mp.mp.dps=60
def Gnu(z, rr):
    return rr/z + (1-rr)*mp.log(z/(z-1))
def Fnu(z, rr):
    return 1/Gnu(z,rr)
def solve_w(xx, eps, alpha, rho, rr):
    aa=mp.e**(1j*mp.pi*alpha*rho)
    guess=Fnu(xx+mp.mpf("1e-20")*1j,rr)
    fun=lambda w: w-Fnu(xx+eps*aa*w**(1-alpha),rr)
    return mp.findroot(fun,guess,tol=mp.mpf("1e-45"),maxsteps=100)
def dens(xx,eps,alpha,rho,rr):
    w=solve_w(xx,eps,alpha,rho,rr)
    return -mp.im(1/w)/mp.pi

rr=mp.mpf("1e-4"); eps=mp.mpf("1e-7")
stress=[
    (mp.mpf("0.25"),mp.mpf("1")),
    (mp.mpf("0.25"),mp.mpf("0")),
    (mp.mpf("0.75"),mp.mpf("0.5")),
    (mp.mpf("1.5"),mp.mpf(1)/3),
    (mp.mpf("1.5"),mp.mpf(2)/3),
    (mp.mpf("1.9"),mp.mpf(9)/19),
    (mp.mpf("1.9"),mp.mpf(10)/19),
]
for alpha,rho in stress:
    vals=[dens(xx,eps,alpha,rho,rr) for xx in (rr,2*rr,mp.mpf("0.5"))]
    assert vals[1] < vals[0] and vals[1] < vals[2]
    print("NUMERICAL_STRESS_ONLY alpha",mp.nstr(alpha,8),"rho",mp.nstr(rho,8),
          "densities",*[mp.nstr(v,18) for v in vals],"VALLEY_PASS")
print("full_fixed_point_numerical_stress = PASS")

# Alpha=1 canonical free-stable family: after removing the real translation
# generated by scaling, the subordination direction is
# S_rho(w)=2 rho i - [2(2rho-1)/pi] log w.
# Its imaginary part for arg(w)=pi*t, 0<t<1, is
# 2[t + rho(1-2t)], positive because it is linear in rho and positive
# at rho=0 and rho=1.
rho,t=sp.symbols("rho t", real=True)
ImS=2*(t+rho*(1-2*t))
assert sp.simplify(ImS.subs(rho,0)-2*t)==0
assert sp.simplify(ImS.subs(rho,1)-2*(1-t))==0
print("alpha1_phase_endpoint_identity = PASS")

def solve_w_alpha1(xx, eps, rho, rr):
    aa=2*(2*rho-1)/mp.pi
    S=lambda w: 2*rho*1j-aa*mp.log(w)
    guess=Fnu(xx+mp.mpf("1e-20")*1j,rr)
    fun=lambda w: w-Fnu(xx+eps*S(w),rr)
    return mp.findroot(fun,guess,tol=mp.mpf("1e-45"),maxsteps=100)
def dens_alpha1(xx,eps,rho,rr):
    w=solve_w_alpha1(xx,eps,rho,rr)
    return -mp.im(1/w)/mp.pi
for rho1 in (mp.mpf("0"),mp.mpf("0.5"),mp.mpf("1")):
    vals=[dens_alpha1(xx,eps,rho1,rr) for xx in (rr,2*rr,mp.mpf("0.5"))]
    assert vals[1] < vals[0] and vals[1] < vals[2]
    print("NUMERICAL_STRESS_ONLY alpha 1 rho",mp.nstr(rho1,8),
          "densities",*[mp.nstr(v,18) for v in vals],"VALLEY_PASS")

# Independent R09 Tang-Q4.11 finite core audit at p=3/4.
p=Fraction(3,4)
beta=Fraction(8,9)
assert beta == 1-(1-p*beta)**2
vec=(Fraction(3,8),Fraction(1,2),Fraction(2,3),Fraction(8,9))
assert vec[0]==p*vec[1]
assert vec[1]==p*vec[2]
assert vec[2]==p*vec[3]
assert vec[3]==1-(1-p*vec[3])**2
assert p**3*beta == Fraction(3,8)
P=sp.symbols("P")
theta3=2*P**2-P
assert sp.diff(theta3,P,2)==4
q=sp.symbols("q")
poly=sp.factor(q-(1-sp.Rational(3,4)+sp.Rational(3,4)*q)**2)
assert sp.simplify(poly + sp.Rational(1,16)*(q-1)*(9*q-1)) == 0
print("R08_AUDIT_R09_TANG_Q411 finite algebra = PASS")
print("physical_vector_p_3_4 =",vec)
print("theta3_second_derivative = 4")
print("ALL_CHECKS_PASS")

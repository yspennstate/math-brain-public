from itertools import product, combinations
from collections import defaultdict

# Exact-arithmetic self-check for the graph-intrinsic p^2 reconstruction lemma.
# This validates one finite clean Cayley instance; it is not a proof of the
# asymptotic high-probability theorem in the accompanying run report.

p = 3
m = p * p
d = 2
Z = [(2, 4), (8, 2), (7, 6)]
V = list(product(range(m), repeat=d))
zero = (0, 0)


def add(a, b):
    return tuple((a[i] + b[i]) % m for i in range(d))


def neg(a):
    return tuple((-x) % m for x in a)


def mul(c, a):
    return tuple((c * x) % m for x in a)


def edge(a, b):
    return tuple(sorted((a, b)))


def order(a):
    x = zero
    for n in range(1, m + 1):
        x = add(x, a)
        if x == zero:
            return n
    raise AssertionError("order not found")


# Clean-instance conditions.
assert all(order(z) == m for z in Z)
assert len({z for z in Z} | {neg(z) for z in Z}) == 2 * len(Z)
det = (Z[0][0] * Z[1][1] - Z[0][1] * Z[1][0]) % p
assert det != 0
short_relations = []
for c in product(range(-4, 5), repeat=len(Z)):
    if all(x == 0 for x in c) or sum(abs(x) for x in c) > 4:
        continue
    s = zero
    for a, z in zip(c, Z):
        s = add(s, mul(a, z))
    if s == zero:
        short_relations.append(c)
assert short_relations == []

# Cayley graph. Hidden direction labels are used only to check that the
# graph-defined equivalence classes recover the planted directions.
steps = []
for i, z in enumerate(Z):
    steps.append((i, z))
    steps.append((i, neg(z)))
adj = {x: set() for x in V}
hidden = {}
for x in V:
    for i, s in steps:
        y = add(x, s)
        adj[x].add(y)
        hidden.setdefault(edge(x, y), set()).add(i)
assert all(len(adj[x]) == 2 * len(Z) for x in V)
assert all(len(v) == 1 for v in hidden.values())


def co4(x, y, z):
    """Whether incident edges xy,xz lie in a simple 4-cycle."""
    return any(w != x for w in (adj[y] & adj[z]))


# Unique non-co-4-cyclic edge at each incidence = straight continuation.
partner = {}
for x in V:
    for y in adj[x]:
        non = [z for z in adj[x] if z != y and not co4(x, y, z)]
        assert len(non) == 1
        partner[(x, y)] = non[0]

# Global direction classes generated by local straight pairs and opposite
# sides of simple 4-cycles.
edges = sorted(hidden)
eid = {e: i for i, e in enumerate(edges)}
parent = list(range(len(edges)))


def find(a):
    while parent[a] != a:
        parent[a] = parent[parent[a]]
        a = parent[a]
    return a


def union(a, b):
    a, b = find(a), find(b)
    if a != b:
        parent[b] = a


for x in V:
    for y in adj[x]:
        z = partner[(x, y)]
        union(eid[edge(x, y)], eid[edge(x, z)])

cycles = set()
for x in V:
    for y, z in combinations(sorted(adj[x]), 2):
        for w in sorted(adj[y] & adj[z]):
            if w == x or len({x, y, z, w}) < 4:
                continue
            cyc = tuple(sorted((edge(x, y), edge(y, w), edge(w, z), edge(z, x))))
            cycles.add(cyc)
for cyc in cycles:
    for a, b in combinations(cyc, 2):
        if set(a).isdisjoint(set(b)):
            union(eid[a], eid[b])

classes = defaultdict(list)
for e in edges:
    classes[find(eid[e])].append(e)
assert len(classes) == len(Z)
assert sorted(len(c) for c in classes.values()) == [len(V)] * len(Z)
hidden_class_labels = []
for c in classes.values():
    lab = set()
    for e in c:
        lab |= hidden[e]
    assert len(lab) == 1
    hidden_class_labels.append(next(iter(lab)))
assert sorted(hidden_class_labels) == list(range(len(Z)))


def straight_endpoint(x, y, steps):
    prev, cur = x, y
    for _ in range(steps - 1):
        nxt = partner[(cur, prev)]
        prev, cur = cur, nxt
    return cur


# Every graph-defined straight cycle has length p^2.
for x in V:
    for y in adj[x]:
        seen = {x}
        prev, cur = x, y
        for _ in range(1, m):
            assert cur not in seen
            seen.add(cur)
            nxt = partner[(cur, prev)]
            prev, cur = cur, nxt
        assert cur == x

# Connect x to the result of p straight steps in every recovered direction.
# Components must be the cosets of pG, i.e. residue classes modulo p.
J = {x: set() for x in V}
for x in V:
    for y in adj[x]:
        q = straight_endpoint(x, y, p)
        J[x].add(q)
        J[q].add(x)

seen = set()
components = []
for x in V:
    if x in seen:
        continue
    stack = [x]
    seen.add(x)
    comp = []
    while stack:
        u = stack.pop()
        comp.append(u)
        for v in J[u]:
            if v not in seen:
                seen.add(v)
                stack.append(v)
    components.append(comp)

assert len(components) == p ** d
assert sorted(len(c) for c in components) == [p ** d] * (p ** d)
for comp in components:
    residue = tuple(comp[0][j] % p for j in range(d))
    assert all(tuple(x[j] % p for j in range(d)) == residue for x in comp)

print("R19 I0110 p^2 reconstruction exact self-check")
print("p", p, "d", d, "k", len(Z), "|G|", len(V))
print("generators", Z)
print("short_relations_l1_le_4", len(short_relations))
print("degree", 2 * len(Z))
print("simple_4cycles", len(cycles))
print("global_direction_classes", len(classes))
print("direction_class_sizes", sorted(len(c) for c in classes.values()))
print("straight_cycle_length", m)
print("p_step_components", len(components))
print("p_step_component_sizes", sorted(set(len(c) for c in components)))
print("quotient_size", len(components))
print("ALL_EXACT_CHECKS_PASS")

#!/usr/bin/env python3
"""Exact finite self-check for R19 mixed p-primary reconstruction.

Checks the clean graph-theoretic reconstruction on
    G = Z/9Z x Z/3Z,
with generators (1,0), (1,1), (4,2).
All calculations are integer/modular and exhaustive.
"""
from itertools import combinations, product
from collections import defaultdict

P = 3
MODS = (9, 3)
GENS = ((1, 0), (1, 1), (4, 2))
V = [(a, b) for a in range(MODS[0]) for b in range(MODS[1])]
ZERO = (0, 0)


def add(x, y):
    return tuple((x[i] + y[i]) % MODS[i] for i in range(2))


def neg(x):
    return tuple((-x[i]) % MODS[i] for i in range(2))


def smul(c, x):
    return tuple((c * x[i]) % MODS[i] for i in range(2))


def edge(a, b):
    return tuple(sorted((a, b)))


def order(x):
    cur = ZERO
    for n in range(1, 100):
        cur = add(cur, x)
        if cur == ZERO:
            return n
    raise AssertionError("order search failed")


def generated(gs):
    seen = {ZERO}
    changed = True
    while changed:
        changed = False
        for x in list(seen):
            for g in gs:
                for h in (g, neg(g)):
                    y = add(x, h)
                    if y not in seen:
                        seen.add(y)
                        changed = True
    return seen


assert all(order(g) == 9 for g in GENS)
assert len(generated(GENS)) == len(V) == 27

short_relations = []
for cs in product(range(-4, 5), repeat=len(GENS)):
    if all(c == 0 for c in cs) or sum(abs(c) for c in cs) > 4:
        continue
    s = ZERO
    for c, g in zip(cs, GENS):
        s = add(s, smul(c, g))
    if s == ZERO:
        short_relations.append(cs)
assert short_relations == []

SIGNED = GENS + tuple(neg(g) for g in GENS)
E = set()
adj = {x: set() for x in V}
for x in V:
    for a in SIGNED:
        y = add(x, a)
        E.add(edge(x, y))
        adj[x].add(y)
assert len(E) == 81
assert {len(adj[x]) for x in V} == {6}


def shares_simple4(x, y, z):
    for w in adj[y].intersection(adj[z]):
        if w not in (x, y, z):
            return True
    return False


# Unique graph-only straight pairing: the only other edge at x that does not
# share a simple 4-cycle with x--y is the inverse edge in the same direction.
pair = {}
for x in V:
    for y in adj[x]:
        non = [z for z in adj[x] if z != y and not shares_simple4(x, y, z)]
        assert len(non) == 1
        pair[(x, y)] = non[0]

hidden_dir = {}
for i, g in enumerate(GENS):
    for x in V:
        hidden_dir[edge(x, add(x, g))] = i
for (x, y), z in pair.items():
    assert hidden_dir[edge(x, y)] == hidden_dir[edge(x, z)]

# Edge-direction equivalence generated by straight pairs and opposite sides
# of graph-theoretic simple 4-cycles.
edges = list(E)
idx = {e: i for i, e in enumerate(edges)}
parent = list(range(len(edges)))


def find(a):
    while parent[a] != a:
        parent[a] = parent[parent[a]]
        a = parent[a]
    return a


def union(a, b):
    ra, rb = find(a), find(b)
    if ra != rb:
        parent[rb] = ra


for (x, y), z in pair.items():
    union(idx[edge(x, y)], idx[edge(x, z)])

cycles = set()
for x in V:
    nbs = list(adj[x])
    for y, z in combinations(nbs, 2):
        for w in adj[y].intersection(adj[z]):
            if w not in (x, y, z):
                cyc = frozenset((edge(x, y), edge(y, w), edge(w, z), edge(z, x)))
                if len(cyc) == 4:
                    cycles.add(cyc)
for cyc in cycles:
    es = list(cyc)
    for a, b in combinations(es, 2):
        if set(a).isdisjoint(set(b)):
            union(idx[a], idx[b])

components = defaultdict(list)
for e in edges:
    components[find(idx[e])].append(e)
component_sizes = sorted(len(c) for c in components.values())
assert len(components) == 3
assert component_sizes == [27, 27, 27]
assert all(len({hidden_dir[e] for e in c}) == 1 for c in components.values())


def straight_next(prev, cur):
    return pair[(cur, prev)]


straight_lengths = set()
for e in edges:
    start = e
    state = start
    n = 0
    while True:
        prev, cur = state
        state = (cur, straight_next(prev, cur))
        n += 1
        if state == start:
            break
        assert n <= 100
    straight_lengths.add(n)
assert straight_lengths == {9}

# J_p: connect endpoints of exactly p graph-reconstructed straight steps.
J = {x: set() for x in V}
for x in V:
    for y in adj[x]:
        prev, cur = x, y
        for _ in range(P - 1):
            prev, cur = cur, straight_next(prev, cur)
        J[x].add(cur)
        J[cur].add(x)

seen = set()
j_sizes = []
for x in V:
    if x in seen:
        continue
    stack = [x]
    seen.add(x)
    cc = []
    while stack:
        u = stack.pop()
        cc.append(u)
        for v in J[u]:
            if v not in seen:
                seen.add(v)
                stack.append(v)
    j_sizes.append(len(cc))
j_sizes.sort()
assert j_sizes == [3] * 9

# Recover mixed invariants from the unlabeled graph data in this example.
recovered_k = len(components)
recovered_p = int(next(iter(straight_lengths)) ** 0.5)
assert recovered_p * recovered_p == next(iter(straight_lengths))
component_size = j_sizes[0]
component_count = len(j_sizes)
# Here component_size=p^d, component_count=p^(d+e).
def exact_log_p(n):
    r = 0
    while n > 1:
        assert n % P == 0
        n //= P
        r += 1
    return r
recovered_d = exact_log_p(component_size)
recovered_d_plus_e = exact_log_p(component_count)
recovered_e = recovered_d_plus_e - recovered_d
assert (recovered_p, recovered_d, recovered_e, recovered_k) == (3, 1, 1, 3)

print("group_size=27")
print("graph_edges=81 degree=6")
print("short_relations_l1_le_4=0")
print("simple_4cycles=%d" % len(cycles))
print("direction_classes=%d sizes=%s" % (len(components), component_sizes))
print("straight_cycle_lengths=%s" % sorted(straight_lengths))
print("J_p_components=%d sizes=%s" % (len(j_sizes), j_sizes))
print("recovered=(p,d,e,k)=(%d,%d,%d,%d)" % (recovered_p, recovered_d, recovered_e, recovered_k))
print("ALL_EXACT_CHECKS_PASS")

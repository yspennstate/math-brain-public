template<int M, int N>
int discrepancy(const int (&A)[M][N], uint64_t *arg=nullptr) {
    int best=999;
    uint64_t besta=0;
    uint64_t total=1ULL<<(N-1); // fix last sign +1, quotient global negation
    for(uint64_t mask=0; mask<total; ++mask){
        int mx=0;
        for(int i=0;i<M;i++){
            int s=A[i][N-1];
            for(int j=0;j<N-1;j++) s += ((mask>>j)&1 ? -A[i][j] : A[i][j]);
            mx=max(mx,abs(s));
        }
        if(mx<best){best=mx;besta=mask;}
    }
    if(arg) *arg=besta;
    return best;
}

int uncovered(int n,int R,const vector<int>& centers){
    int D=n-1, N=1<<D, u=0;
    for(int x=0;x<N;x++){
        bool ok=false;
        for(int c:centers){
            int w=__builtin_popcount((unsigned)(x^c));
            if(min(w,n-w)<=R){ok=true;break;}
        }
        if(!ok)u++;
    }
    return u;
}


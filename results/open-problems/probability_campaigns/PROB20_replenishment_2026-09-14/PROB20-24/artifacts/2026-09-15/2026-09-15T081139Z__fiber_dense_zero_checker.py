from itertools import product
from fractions import Fraction
from math import ceil, floor

# Corroborative finite checker for the fiber-dense zero-coefficient extension
# of the 3D signed small-ball block argument.  This is not the proof.


def fiber_dense_coeffs(n, delta_num=1, delta_den=2):
    """Build a deterministic {-1,0,1} coefficient array.

    Index is (r1,r2,r3,i,j,k), where r1+r2+r3=n and i,j,k identify
    dyadic intervals at those levels.  For every shape and first-coordinate
    interval i, activate at least delta of the yz fibers.
    """
    coeff = {}
    for r1 in range(n // 2 + 1):
        for r2 in range(n - r1 + 1):
            r3 = n - r1 - r2
            yz_count = 2 ** (r2 + r3)
            active = ceil(delta_num * yz_count / delta_den)
            for i in range(2 ** r1):
                for flat in range(yz_count):
                    j = flat // (2 ** r3)
                    k = flat % (2 ** r3)
                    coeff[(r1, r2, r3, i, j, k)] = 1 if flat < active else 0
    return coeff


def conditional_diagonal_values(n, q, t, coeff):
    """Exact E(D_t | F_t) on every first-coordinate F_t atom.

    D_t is the diagonal square-function term sum_{r in I_t} f_r^2.
    F_t is generated by x1 intervals of level floor(t*n/q).
    """
    L = floor(t * n / q)
    lo = (t - 1) * n / q
    hi = t * n / q
    shapes = []
    for r1 in range(n // 2 + 1):
        if lo <= r1 < hi:
            for r2 in range(n - r1 + 1):
                r3 = n - r1 - r2
                shapes.append((r1, r2, r3))

    values = []
    for atom in range(2 ** L):
        total = Fraction(0)
        for r1, r2, r3 in shapes:
            if r1 > L:
                raise RuntimeError(("unexpected scale ordering", L, r1))
            first_interval = atom // (2 ** (L - r1))
            yz_count = 2 ** (r2 + r3)
            active = 0
            for j in range(2 ** r2):
                for k in range(2 ** r3):
                    active += coeff[(r1, r2, r3, first_interval, j, k)] != 0
            total += Fraction(active, yz_count)
        values.append(total)
    return shapes, values


def main():
    n = 8
    q = 4
    delta = Fraction(1, 2)
    coeff = fiber_dense_coeffs(n, delta.numerator, delta.denominator)
    for t in range(1, q // 2 + 1):
        shapes, values = conditional_diagonal_values(n, q, t, coeff)
        target = delta * len(shapes)
        print(
            "block", t,
            "shape_count", len(shapes),
            "min_conditional_diagonal", min(values),
            "fiber_lower_bound", target,
            "verified", min(values) >= target,
        )

    # Scaling check used in the proof. If N_t ~ n^2/q and
    # ||Pi_t||_{exp(L^{2/3})} <= C n^{3/2}/sqrt(q), then the good-event
    # threshold delta*N_t is larger than the coincidence scale by
    # order delta*sqrt(n/q), yielding a tail exponent order
    # delta^(2/3)*(n/q)^(1/3).
    for n in (256, 1024, 4096):
        q = round(n ** 0.25)
        ratio = float(delta) * (n / q) ** 0.5
        tail_exponent = ratio ** (2 / 3)
        print("n", n, "q", q, "threshold_over_scale", ratio,
              "tail_exponent_proxy", tail_exponent)


if __name__ == "__main__":
    main()

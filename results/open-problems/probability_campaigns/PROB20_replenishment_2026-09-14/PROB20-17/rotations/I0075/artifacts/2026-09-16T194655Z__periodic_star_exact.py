#!/usr/bin/env python3
"""
Exact certificate for the 3x3-periodic star replacement network used in I0075.

Network N:
- cities are Z^2;
- begin with every horizontal/vertical unit grid segment;
- for each (a,b) in (3Z)^2 delete the four boundary segments of
  [a,a+1] x [b,b+1];
- add its center (a+1/2,b+1/2) and the four center-to-corner spokes.

For city-to-city routing, each selected square may be replaced metrically by
a K4 on its corners with edge-weight sqrt(2), since every pair of distinct
corners can travel corner -> center -> corner in length sqrt(2).
Thus every path cost is A + B*sqrt(2), A,B nonnegative integers.

This script uses ONLY integer arithmetic for algebraic comparisons.
It certifies every source phase mod 3 and every nonzero integer displacement
with Euclidean norm < 49.  The analytic report handles norm >= 49.
"""
from heapq import heappush, heappop
from functools import total_ordering

LO, HI = -75, 78
MAX_CUTOFF = (72, 0)  # 72 exactly in Z[sqrt(2)]

def sign_qsqrt2(p, q):
    """Exact sign of p + q*sqrt(2), p,q integers."""
    if p == 0:
        return (q > 0) - (q < 0)
    if q == 0:
        return (p > 0) - (p < 0)
    if p > 0 and q > 0:
        return 1
    if p < 0 and q < 0:
        return -1
    if p > 0 and q < 0:
        c = p*p - 2*q*q
        return (c > 0) - (c < 0)
    # p < 0 < q
    c = 2*q*q - p*p
    return (c > 0) - (c < 0)

def alg_lt(x, y):
    return sign_qsqrt2(x[0]-y[0], x[1]-y[1]) < 0

def alg_leq(x, y):
    return sign_qsqrt2(x[0]-y[0], x[1]-y[1]) <= 0

@total_ordering
class HeapItem:
    __slots__ = ("a","b","v")
    def __init__(self, a, b, v):
        self.a, self.b, self.v = a, b, v
    def __lt__(self, other):
        s = sign_qsqrt2(self.a-other.a, self.b-other.b)
        return (s < 0) if s else (self.v < other.v)
    def __eq__(self, other):
        return (self.a,self.b,self.v) == (other.a,other.b,other.v)

def deleted_unit_edge(x1,y1,x2,y2):
    assert abs(x1-x2) + abs(y1-y2) == 1
    if y1 == y2:
        x, y = min(x1,x2), y1
        # bottom/top boundary of selected square
        return x % 3 == 0 and y % 3 in (0,1)
    x, y = x1, min(y1,y2)
    # left/right boundary of selected square
    return y % 3 == 0 and x % 3 in (0,1)

def incident_selected_squares(x,y):
    # selected BL corners (a,b) with a,b divisible by 3
    # for which (x,y) is one of the four corners.
    for a in (x, x-1):
        if a % 3:
            continue
        for b in (y, y-1):
            if b % 3 == 0:
                yield a,b

def neighbors(v):
    x,y = v
    # Surviving unit grid edges: cost 1.
    for dx,dy in ((1,0),(-1,0),(0,1),(0,-1)):
        nx,ny = x+dx,y+dy
        if LO <= nx <= HI and LO <= ny <= HI:
            if not deleted_unit_edge(x,y,nx,ny):
                yield (nx,ny),(1,0)
    # Metric closure through one Steiner center: every distinct pair of
    # corners of one selected square has a valid two-spoke route of cost sqrt(2).
    for a,b in incident_selected_squares(x,y):
        for w in ((a,b),(a+1,b),(a,b+1),(a+1,b+1)):
            if w != v and LO <= w[0] <= HI and LO <= w[1] <= HI:
                yield w,(0,1)

def dijkstra_exact(src):
    """Exact Dijkstra in the finite induced routing graph.

    We also retain a predecessor witness.  The final checks reconstruct every
    certified route, so correctness only uses existence of the produced path;
    it does not rely on an unverified optimality claim.
    """
    dist = {src:(0,0)}
    pred = {src:None}
    pq = [HeapItem(0,0,src)]
    while pq:
        item = heappop(pq)
        v = item.v
        cur = dist.get(v)
        if cur != (item.a,item.b):
            continue
        if not alg_leq(cur, MAX_CUTOFF):
            break
        A,B = cur
        for w,(da,db) in neighbors(v):
            nd = (A+da, B+db)
            if w not in dist or alg_lt(nd, dist[w]):
                dist[w] = nd
                pred[w] = (v,(da,db))
                heappush(pq, HeapItem(nd[0],nd[1],w))
    return dist,pred

def reconstruct_cost(src,target,pred):
    """Return exact (A,B) cost of the explicit predecessor route."""
    v = target
    A = B = 0
    seen = set()
    while v != src:
        assert v not in seen, ("predecessor cycle",src,target,v)
        seen.add(v)
        assert v in pred and pred[v] is not None
        u,(da,db) = pred[v]
        # Check that this exact directed step is genuinely generated by N.
        ok = False
        for w,cost in neighbors(u):
            if w == v and cost == (da,db):
                ok = True
                break
        assert ok, ("invalid predecessor edge",u,v,(da,db))
        A += da
        B += db
        v = u
    return A,B

def route_leq_source_bound(A,B,dx,dy):
    """
    Exact check:
       A+B sqrt(2) <= sqrt(2)*sqrt(dx^2+dy^2).
    Square both nonnegative sides:
       A^2+2B^2+2AB sqrt(2) <= 2R^2.
    """
    R2 = dx*dx + dy*dy
    C = 2*R2 - (A*A + 2*B*B)
    if C < 0:
        return False
    # Need 2AB sqrt(2) <= C; both sides are nonnegative.
    return C*C >= 8*A*A*B*B

def route_eq_source_bound(A,B,dx,dy):
    R2 = dx*dx + dy*dy
    # sign of cost^2 - 2R^2
    p = A*A + 2*B*B - 2*R2
    q = 2*A*B
    return sign_qsqrt2(p,q) == 0

# Exact algebraic scalar checks used by the analytic proof.
# Candidate length density: (14+2 sqrt(2))/9 < 2.
assert sign_qsqrt2(14-18, 2) < 0
# Macro Cauchy coefficient:
# (2+sqrt2)^2 + 2^2 = 10+4sqrt2 < 16.
assert sign_qsqrt2(10-16, 4) < 0
# Large-radius threshold check at R=49:
# sqrt2*49 - (4/3)(49+sqrt2) - 2
# = (143 sqrt2 - 202)/3 > 0.
assert sign_qsqrt2(-202, 143) > 0

checked = 0
equalities = 0
phase_counts = []
for sx in range(3):
    for sy in range(3):
        src = (sx,sy)
        dist,pred = dijkstra_exact(src)
        local = 0
        for dx in range(-48,49):
            for dy in range(-48,49):
                if dx == 0 and dy == 0:
                    continue
                if dx*dx + dy*dy >= 49*49:
                    continue
                target = (sx+dx, sy+dy)
                assert target in dist, ("missing target",src,(dx,dy))
                A,B = dist[target]
                assert reconstruct_cost(src,target,pred) == (A,B)
                assert route_leq_source_bound(A,B,dx,dy), (
                    "stretch failure",src,(dx,dy),(A,B)
                )
                if route_eq_source_bound(A,B,dx,dy):
                    equalities += 1
                checked += 1
                local += 1
        phase_counts.append((src,local))

assert checked == 9*7520
assert all(c == 7520 for _,c in phase_counts)

print("I0075_PERIODIC_STAR_EXACT_CERTIFICATE")
print("length_density=(14+2*sqrt(2))/9 < 2 : PASS")
print("macro_bound sqrt(10+4*sqrt(2)) < 4 : PASS")
print("radius_49 inequality 143*sqrt(2) > 202 : PASS")
print("phases=9")
print("finite_nonzero_displacements_per_phase=7520")
print("finite_cases_checked=%d" % checked)
print("finite_stretch_equalities=%d" % equalities)
print("finite_stretch_failures=0")
print("ALL_ASSERTIONS_PASSED")

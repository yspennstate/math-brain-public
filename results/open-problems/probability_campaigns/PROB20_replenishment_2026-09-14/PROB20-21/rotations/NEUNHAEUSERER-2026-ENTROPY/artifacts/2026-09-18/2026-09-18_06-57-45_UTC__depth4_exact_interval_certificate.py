#!/usr/bin/env python3
"""Exact finite/interval certificate for the depth-4 frontier of NEUNHAEUSERER-2026-ENTROPY.

Certifies exactly (no floating-point PASS decisions):
1. all realizable four-weight subset-sum collision flats reduce to 23 entropy signatures;
2. H''(p)<0 for every signature on p in [1e-5,1/2] by exact rational Bernstein
   bounds and rigorous rational atanh-series bounds for logarithms.
The report supplies the analytic tail proof on (0,1e-5] and uses H(p)=H(1-p).
"""
from fractions import Fraction as F
from math import comb, gcd
from itertools import product

M=4

def rref_key(rows):
    A=[[F(x) for x in row] for row in rows if any(F(x)!=0 for x in row)]
    if not A: return ()
    r=c=0
    while r<len(A) and c<M:
        piv=next((i for i in range(r,len(A)) if A[i][c]!=0),None)
        if piv is None:
            c+=1; continue
        A[r],A[piv]=A[piv],A[r]
        z=A[r][c]; A[r]=[x/z for x in A[r]]
        for i in range(len(A)):
            if i!=r and A[i][c]!=0:
                z=A[i][c]
                A[i]=[A[i][j]-z*A[r][j] for j in range(M)]
        r+=1; c+=1
    nz=[tuple(row) for row in A if any(x!=0 for x in row)]
    nz.sort(key=lambda row: next(i for i,x in enumerate(row) if x!=0))
    return tuple(nz)

def integerize(v):
    den=1
    for x in v: den=den*x.denominator//gcd(den,x.denominator)
    z=[int(x*den) for x in v]; g=0
    for x in z: g=gcd(g,abs(x))
    return tuple(x//g for x in z) if g else tuple(z)

def nullspace_basis(key):
    piv=[next(i for i,x in enumerate(row) if x!=0) for row in key]
    free=[j for j in range(M) if j not in piv]
    out=[]
    for f in free:
        v=[F(0)]*M; v[f]=F(1)
        for row,p in reversed(list(zip(key,piv))):
            v[p]=-sum(row[j]*v[j] for j in free)
        out.append(integerize(v))
    return out

def row_basis(key): return [integerize(row) for row in key]

# Equality of two subset sums, after cancelling common coordinates, has normal
# epsilon in {-1,0,1}^4 containing both signs. Quotient epsilon ~ -epsilon.
RELS=[]
for v in product((-1,0,1),repeat=M):
    if 1 not in v or -1 not in v: continue
    if next(x for x in v if x)<0: v=tuple(-x for x in v)
    if v not in RELS: RELS.append(v)
assert len(RELS)==25

# Exhaust every rank <=3 span generated by subsets of the 25 normals.
spans={()}; stack=[()]
while stack:
    key=stack.pop()
    for rel in RELS:
        nk=rref_key(list(key)+[rel])
        if len(nk)>=M: continue
        if nk not in spans:
            spans.add(nk); stack.append(nk)
assert len(spans)==522

def closure_relations(key):
    return tuple(i for i,r in enumerate(RELS) if rref_key(list(key)+[r])==key)

def zero_relations(w):
    return tuple(i for i,r in enumerate(RELS) if sum(r[j]*w[j] for j in range(M))==0)

def positive_generic_witness(key,B=8):
    basis=nullspace_basis(key); target=closure_relations(key)
    for coeff in product(range(-B,B+1),repeat=len(basis)):
        if all(c==0 for c in coeff): continue
        w=[sum(coeff[t]*basis[t][j] for t in range(len(basis))) for j in range(M)]
        if min(w)<=0: continue
        if zero_relations(w)==target:
            g=0
            for x in w: g=gcd(g,abs(x))
            return tuple(x//g for x in w)
    return None

def nonnegative_rowspace_certificate(key,B=8):
    rows=row_basis(key)
    if not rows: return None
    for coeff in product(range(-B,B+1),repeat=len(rows)):
        if all(c==0 for c in coeff): continue
        y=[sum(coeff[i]*rows[i][j] for i in range(len(rows))) for j in range(M)]
        if all(v>=0 for v in y) and any(v>0 for v in y):
            g=0
            for v in y: g=gcd(g,abs(v))
            return tuple(v//g for v in y)
        if all(v<=0 for v in y) and any(v<0 for v in y):
            y=[-v for v in y]; g=0
            for v in y: g=gcd(g,abs(v))
            return tuple(v//g for v in y)
    return None

# Exact Gordan-style dichotomy certificate for every candidate span.
feasible={}; infeasible={}
for key in spans:
    w=positive_generic_witness(key)
    y=nonnegative_rowspace_certificate(key)
    assert not (w is not None and y is not None)
    assert (w is not None) or (y is not None)
    if w is not None:
        assert all(sum(row[j]*w[j] for j in range(M))==0 for row in key)
        assert zero_relations(w)==closure_relations(key)
        feasible[key]=w
    else:
        assert all(v>=0 for v in y) and any(v>0 for v in y)
        infeasible[key]=y
assert len(feasible)==216 and len(infeasible)==306

def collision_signature(w):
    classes={}
    for mask in range(1<<M):
        s=sum(w[i] for i in range(M) if (mask>>i)&1)
        k=mask.bit_count()
        classes.setdefault(s,[0]*(M+1))[k]+=1
    return tuple(sorted(tuple(v) for v in classes.values()))

sig_rep={}
for w in feasible.values(): sig_rep.setdefault(collision_signature(w),w)
assert len(sig_rep)==23

def q_poly(c):
    out=[F(0)]*(M+1)
    for k,ck in enumerate(c):
        if not ck: continue
        for j in range(M-k+1): out[k+j]+=F(ck*comb(M-k,j)*((-1)**j))
    while len(out)>1 and out[-1]==0: out.pop()
    return tuple(out)

def deriv(a): return (F(0),) if len(a)==1 else tuple(F(i)*a[i] for i in range(1,len(a)))

POLY={}
for c in sorted({c for sig in sig_rep for c in sig}):
    q0=q_poly(c); q1=deriv(q0); q2=deriv(q1); POLY[c]=(q0,q1,q2)

def bernstein_bounds(coeff,a,b):
    d=len(coeff)-1
    if d==0: return coeff[0],coeff[0]
    h=b-a; power=[F(0)]*(d+1)
    for j,cj in enumerate(coeff):
        for r in range(j+1): power[r]+=cj*comb(j,r)*(a**(j-r))*(h**r)
    beta=[]
    for k in range(d+1):
        beta.append(sum((power[j]*F(comb(k,j),comb(d,j)) for j in range(k+1)),F(0)))
    return min(beta),max(beta)

def iadd(I,J): return I[0]+J[0],I[1]+J[1]
def imul(I,J):
    v=(I[0]*J[0],I[0]*J[1],I[1]*J[0],I[1]*J[1]); return min(v),max(v)
def isquare(I):
    a,b=I
    if a<=0<=b: return F(0),max(a*a,b*b)
    return min(a*a,b*b),max(a*a,b*b)
def idiv_pos(I,J):
    assert J[0]>0
    return imul(I,(1/J[1],1/J[0]))
def iscale(I,k): return (I[0]*k,I[1]*k) if k>=0 else (I[1]*k,I[0]*k)

def floor_log2(x):
    n,d=x.numerator,x.denominator; k=n.bit_length()-d.bit_length()
    while F(2)**k>x: k-=1
    while F(2)**(k+1)<=x: k+=1
    return k

def atanh_log_unit(y,N=8):
    # log y=2 sum z^(2j+1)/(2j+1), z=(y-1)/(y+1), 0<=z<1/3.
    assert F(1)<=y<F(2)
    z=(y-1)/(y+1); zz=z*z; term=z; s=F(0)
    for j in range(N): s+=term/F(2*j+1); term*=zz
    lo=2*s; tail=2*term/(F(2*N+1)*(1-zz))
    return lo,lo+tail

def log2_bounds(N=10):
    z=F(1,3); zz=z*z; term=z; s=F(0)
    for j in range(N): s+=term/F(2*j+1); term*=zz
    lo=2*s; tail=2*term/(F(2*N+1)*(1-zz)); return lo,lo+tail
LOG2=log2_bounds()

def log_bounds(x):
    k=floor_log2(x); y=x/(F(2)**k)
    return iadd(iscale(LOG2,k),atanh_log_unit(y))

def S_interval(sig,a,b):
    # H''=-S, S=sum_C[Q_C'' log Q_C + (Q_C')^2/Q_C].
    S=(F(0),F(0))
    for c in sig:
        q0,q1,q2=POLY[c]
        Q=bernstein_bounds(q0,a,b); Q1=bernstein_bounds(q1,a,b); Q2=bernstein_bounds(q2,a,b)
        assert Q[0]>0
        L=(log_bounds(Q[0])[0],log_bounds(Q[1])[1])
        S=iadd(S,iadd(imul(Q2,L),idiv_pos(isquare(Q1),Q)))
    return S

def certify(sig,a,b,depth=0,maxdepth=20,records=None):
    if records is None: records=[]
    S=S_interval(sig,a,b)
    if S[0]>0:
        records.append((a,b,S[0],S[1],depth)); return True,records
    if depth>=maxdepth:
        records.append((a,b,S[0],S[1],depth)); return False,records
    mid=(a+b)/2
    ok,records=certify(sig,a,mid,depth+1,maxdepth,records)
    if not ok: return False,records
    return certify(sig,mid,b,depth+1,maxdepth,records)

LO,HI=F(1,100000),F(1,2)
summary=[]
for sig,w in sorted(sig_rep.items(),key=lambda kv:tuple(sorted(kv[1]))):
    ok,recs=certify(sig,LO,HI); assert ok
    summary.append((tuple(sorted(w)),len(recs),max(r[4] for r in recs),min(r[2] for r in recs)))
assert len(summary)==23
assert sum(x[1] for x in summary)==338
assert max(x[2] for x in summary)==5
global_min=min(x[3] for x in summary); assert global_min>0

print('PASS')
print('relation_normals =',len(RELS))
print('relation_spans_rank_le_3 =',len(spans))
print('positive_exact_flats =',len(feasible))
print('infeasible_flats_with_nonnegative_rowspace_certificate =',len(infeasible))
print('entropy_signatures =',len(sig_rep))
print('certified_interval = [1/100000,1/2]')
print('terminal_rational_intervals =',sum(x[1] for x in summary))
print('max_bisection_depth =',max(x[2] for x in summary))
print('minimum_exact_lower_bound_positive =',global_min>0)
print('minimum_lower_bound_float_diagnostic =',float(global_min))
print('per_signature:')
for w,n,d,lb in summary:
    print(w,'intervals=',n,'depth=',d,'lower~',float(lb))

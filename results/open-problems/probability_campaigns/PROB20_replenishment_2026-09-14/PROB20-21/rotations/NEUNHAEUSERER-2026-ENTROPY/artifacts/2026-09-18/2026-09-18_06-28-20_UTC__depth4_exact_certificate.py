#!/usr/bin/env python3
"""
Exact finite core for NEUNHAEUSERER-2026-ENTROPY, depth m=4.

What is certified:
(1) Every collision pattern of four positive real weights is one of 23
    entropy signatures.  This is an exact hyperplane-arrangement enumeration
    over Q; it is not a bounded weight scan.
(2) For every one of the 23 signatures, H''(p)<0 for all 0<p<1.
    The central interval [1/1000,1/2] is certified by rational interval
    arithmetic with rigorous rational enclosures for log.  The endpoint
    (0,1/1000] is handled by a uniform analytic bound checked below.
    Symmetry H(p)=H(1-p) covers [1/2,1).
(3) The all-equal pattern is curvature-extremal in the following rigorous
    sense: every non-all-equal depth-4 signature has H''(p)<-11/2 for every
    0<p<1, while the all-equal signature has
    H''(1/2)=-16+log(46656)>-21/4.

Only the Python standard library is used. All finite linear algebra and
interval endpoints are exact fractions.Fraction objects.  Transcendental
logarithms are enclosed by the positive atanh series with an explicit
geometric tail bound.
"""
from fractions import Fraction
from collections import deque, defaultdict
from itertools import product, combinations, combinations_with_replacement
from math import comb

M = 4

def rref_basis(rows, n=M):
    A = [[Fraction(x) for x in row] for row in rows if any(x != 0 for x in row)]
    if not A:
        return tuple()
    m = len(A)
    r = 0
    for c in range(n):
        piv = next((i for i in range(r, m) if A[i][c]), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        pv = A[r][c]
        A[r] = [x / pv for x in A[r]]
        for i in range(m):
            if i != r and A[i][c]:
                fac = A[i][c]
                A[i] = [A[i][j] - fac * A[r][j] for j in range(n)]
        r += 1
        if r == m:
            break
    return tuple(tuple(row) for row in A[:r])

def in_span(v, basis):
    # basis is already in RREF. Reduce v by its pivot rows directly.
    x = [Fraction(z) for z in v]
    for row in basis:
        piv = next(i for i,z in enumerate(row) if z)
        fac = x[piv]
        if fac:
            x = [x[j] - fac*row[j] for j in range(M)]
    return all(z == 0 for z in x)

def solve_square(A, b):
    n = len(A)
    X = [[Fraction(A[i][j]) for j in range(n)] + [Fraction(b[i])] for i in range(n)]
    for c in range(n):
        piv = next((i for i in range(c, n) if X[i][c]), None)
        if piv is None:
            return None
        X[c], X[piv] = X[piv], X[c]
        pv = X[c][c]
        X[c] = [z / pv for z in X[c]]
        for i in range(n):
            if i != c and X[i][c]:
                fac = X[i][c]
                X[i] = [X[i][j] - fac * X[c][j] for j in range(n + 1)]
    return tuple(X[i][-1] for i in range(n))

def positive_feasible_vertex(basis):
    """
    Exact feasibility for ker(basis) intersect {w_i>0}.

    By homogeneity this is equivalent to P={Bw=0,w_i>=1} nonempty.
    A nonempty P is pointed, hence has a vertex.  If rank(B)=r, at a
    vertex at least 4-r independent coordinate lower bounds are active.
    We enumerate all choices of 4-r active bounds exactly.
    """
    r = len(basis)
    if r >= M:
        return None
    need = M - r
    for active in combinations(range(M), need):
        A = [list(row) for row in basis]
        b = [0] * r
        for i in active:
            row = [0] * M
            row[i] = 1
            A.append(row)
            b.append(1)
        sol = solve_square(A, b)
        if sol is not None and all(x >= 1 for x in sol):
            return sol
    return None

# Every collision of two distinct subsets, after cancelling their common
# part, is r.w=0 for a nonzero r in {-1,0,1}^4 with both signs.
REL = []
for r in product((-1, 0, 1), repeat=M):
    if not (1 in r and -1 in r):
        continue
    # quotient by r ~ -r using first nonzero sign
    if next(x for x in r if x) < 0:
        continue
    REL.append(tuple(r))
assert len(REL) == 25

# Enumerate every row space generated by collision hyperplanes, rank <=3.
ZERO = tuple()
spaces = {ZERO}
q = deque([ZERO])
while q:
    B = q.popleft()
    if len(B) >= M - 1:
        continue
    for r in REL:
        NB = rref_basis(list(B) + [r])
        if len(NB) <= M - 1 and NB not in spaces:
            spaces.add(NB)
            q.append(NB)
assert len(spaces) == 522

def diff_masks(a, b):
    return tuple(((a >> i) & 1) - ((b >> i) & 1) for i in range(M))

def signature_from_basis(B):
    """Entropy signature = multiset of level-count vectors of collision fibers."""
    parent = list(range(1 << M))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra
    for a in range(1 << M):
        for b in range(a + 1, 1 << M):
            if in_span(diff_masks(a, b), B):
                union(a, b)
    groups = defaultdict(list)
    for a in range(1 << M):
        groups[find(a)].append(a)
    cls = []
    for g in groups.values():
        cnt = [0] * (M + 1)
        for mask in g:
            cnt[mask.bit_count()] += 1
        cls.append(tuple(cnt))
    return tuple(sorted(cls))

feasible = []
for B in spaces:
    w = positive_feasible_vertex(B)
    if w is not None:
        feasible.append((B, w, signature_from_basis(B)))
assert len(feasible) == 216
SIGNATURES = sorted({sig for _, _, sig in feasible}, key=lambda s: (len(s), s))
assert len(SIGNATURES) == 23

def signature_from_weights(w):
    sums = defaultdict(list)
    for mask in range(1 << M):
        s = sum(w[i] for i in range(M) if (mask >> i) & 1)
        sums[s].append(mask)
    cls = []
    for g in sums.values():
        cnt = [0] * (M + 1)
        for mask in g:
            cnt[mask.bit_count()] += 1
        cls.append(tuple(cnt))
    return tuple(sorted(cls))

# Small labels only, not used for completeness.  Every exact arrangement
# signature happens to have a representative with weights <=8.
reps = {}
for w in combinations_with_replacement(range(1, 9), M):
    sig = signature_from_weights(w)
    if sig in SIGNATURES and sig not in reps:
        reps[sig] = w
assert len(reps) == 23

# ---------------- exact rational interval arithmetic ----------------

def iadd(X, Y):
    return (X[0] + Y[0], X[1] + Y[1])

def ineg(X):
    return (-X[1], -X[0])

def imul(X, Y):
    vals = (X[0]*Y[0], X[0]*Y[1], X[1]*Y[0], X[1]*Y[1])
    return (min(vals), max(vals))

def poly_interval(coeff, I):
    out = (Fraction(0), Fraction(0))
    for a in reversed(coeff):
        out = iadd(imul(out, I), (a, a))
    return out

def exact_poly_coeff(cnt):
    # ascending coefficients in p of sum_k cnt[k] p^k (1-p)^(4-k)
    c = [Fraction(0) for _ in range(M + 1)]
    for k, mult in enumerate(cnt):
        if not mult:
            continue
        for j in range(M - k + 1):
            c[k + j] += Fraction(mult * comb(M-k, j) * ((-1) ** j))
    return c

def dcoeff(c):
    return [Fraction(i) * c[i] for i in range(1, len(c))]

LOG2_CACHE = {}
LOG_CACHE = {}
def log2_bounds(N=14):
    if N in LOG2_CACHE:
        return LOG2_CACHE[N]
    z = Fraction(1, 3)                 # log 2 = 2 atanh(1/3)
    s = Fraction(0)
    zp = z
    for j in range(N):
        s += zp / Fraction(2*j + 1)
        zp *= z*z
    lo = 2*s
    # positive omitted terms; denominator >=2N+1
    rem = Fraction(2) * zp / (Fraction(2*N + 1) * (1 - z*z))
    out = (lo, lo + rem)
    LOG2_CACHE[N] = out
    return out

def log_pos_bounds(x, N=14):
    """Rigorous rational lower/upper bounds for log(x), x>0 rational."""
    x = Fraction(x)
    assert x > 0
    key = (x, N)
    if key in LOG_CACHE:
        return LOG_CACHE[key]
    y = x
    k = 0
    while y >= 2:
        y /= 2
        k += 1
    while y < 1:
        y *= 2
        k -= 1
    z = (y - 1) / (y + 1)             # 0 <= z < 1/3
    s = Fraction(0)
    zp = z
    for j in range(N):
        s += zp / Fraction(2*j + 1)
        zp *= z*z
    lo_y = 2*s
    rem_y = Fraction(0) if z == 0 else Fraction(2)*zp / (
        Fraction(2*N + 1) * (1-z*z)
    )
    hi_y = lo_y + rem_y
    lo2, hi2 = log2_bounds(N)
    if k >= 0:
        out = (k*lo2 + lo_y, k*hi2 + hi_y)
    else:
        out = (k*hi2 + lo_y, k*lo2 + hi_y)
    LOG_CACHE[key] = out
    return out

def log_interval(X, N=14):
    assert X[0] > 0
    return (log_pos_bounds(X[0], N)[0], log_pos_bounds(X[1], N)[1])

def q_positive_interval(cnt, I):
    """
    Safe range for Q=sum cnt[k] p^k(1-p)^(4-k).
    We intentionally relax p and 1-p independently.
    """
    a, b = I
    qlo, qhi = 1-b, 1-a
    lo = Fraction(0)
    hi = Fraction(0)
    for k, mult in enumerate(cnt):
        if mult:
            lo += mult * (a**k) * (qlo**(M-k))
            hi += mult * (b**k) * (qhi**(M-k))
    return (lo, hi)

DATA = []
for sig in SIGNATURES:
    P = [exact_poly_coeff(cnt) for cnt in sig]
    P1 = [dcoeff(c) for c in P]
    P2 = [dcoeff(dcoeff(c)) for c in P]
    DATA.append((sig, P, P1, P2))

def hpp_upper_interval(data, I, Nlog=14):
    """
    Certified upper bound for
      H'' = -sum_C [Q_C'' log Q_C + (Q_C')^2/Q_C].
    """
    sig, P, P1, P2 = data
    ub = Fraction(0)
    for cnt, c1, c2 in zip(sig, P1, P2):
        Q = q_positive_interval(cnt, I)
        L = log_interval(Q, Nlog)
        Q1 = poly_interval(c1, I)
        Q2 = poly_interval(c2, I)

        # exact interval for -Q'' log Q
        t1 = ineg(imul(Q2, L))

        # lower bound for (Q')^2/Q, sufficient because it is subtracted
        if Q1[0] <= 0 <= Q1[1]:
            sqlo = Fraction(0)
        else:
            sqlo = min(Q1[0]*Q1[0], Q1[1]*Q1[1])
        fisher_lo = sqlo / Q[1]
        ub += t1[1] - fisher_lo
    return ub

# Coarse but rigorous central proof: 23 patterns x 50 intervals.
START = Fraction(1, 1000)
END = Fraction(1, 2)
WIDTH = Fraction(1, 100)
worst = None
checks = 0
a = START
while a < END:
    b = min(a + WIDTH, END)
    for i, data in enumerate(DATA):
        ub = hpp_upper_interval(data, (a, b))
        checks += 1
        rec = (ub, i, a, b)
        if worst is None or ub > worst[0]:
            worst = rec
        assert ub < 0
    a = b
assert checks == 1150

# Uniform analytic endpoint p in (0,1/1000].
#
# Let U be the output classes containing the four singleton subsets.
# For p<=1/1000, derivatives of level-2 and level-3 atom masses are >=0, so
#   Q_U' >= 4(1-p)^2(1-4p)
# and
#   Q_U <= 4p+6p^2+4p^3.
# Cauchy gives Fisher >= c/p with
#   c >= 16*(999/1000)^4*(996/1000)^2/(4+6/1000+4/10^6) > 197/50.
eps = Fraction(1, 1000)
c_fisher = (
    16 * (Fraction(999,1000)**4) * (Fraction(996,1000)**2)
    / (4 + 6*eps + 4*eps*eps)
)
assert c_fisher > Fraction(197, 50)

# Also sum_C |Q_C''| <= sum_A |x_A''| <49 on this interval:
# level counts 1,4,6,4,1 give <=12 + 24 + 12 + .024 + .000012 <49.
second_abs_bound = (
    Fraction(12)
    + Fraction(24)
    + Fraction(12)
    + Fraction(24,1000)
    + Fraction(12,1000000)
)
assert second_abs_bound < 49

# Each nonempty output-class probability Q_C is in [p^4,1], hence
# |log Q_C|<=4 log(1/p). For t=1/p>=1000,
# log t < t/50: g(t)=t/50-log t is increasing for t>=1000, and
# g(1000)>20-10>0 because e>2 => e^10>2^10>1000.
# Thus the log term is <49*4/(50p)=98/(25p)=3.92/p,
# while the Fisher term is >197/(50p)=3.94/p.
assert Fraction(197,50) - Fraction(98,25) == Fraction(1,50)

# B24 extremal certificate.  Tighten only the 22 non-all-equal patterns
# on [1/1000,1/2]; endpoint bound is already <= -20 there.
all_equal_sig = signature_from_weights((1,1,1,1))
all_equal_index = SIGNATURES.index(all_equal_sig)
non_equal_worst = None
a = START
tight_checks = 0
while a < END:
    b = min(a + Fraction(1,1000), END)
    for i, data in enumerate(DATA):
        if i == all_equal_index:
            continue
        ub = hpp_upper_interval(data, (a,b))
        tight_checks += 1
        rec = (ub, i, a, b)
        if non_equal_worst is None or ub > non_equal_worst[0]:
            non_equal_worst = rec
        assert ub < Fraction(-11, 2)
    a = b
assert tight_checks == 10978

# All-equal midpoint: H''(1/2) = -16 + log(46656) = -16+6log6.
lo46656, hi46656 = log_pos_bounds(Fraction(46656), 14)
equal_mid_lo = -16 + lo46656
equal_mid_hi = -16 + hi46656
assert equal_mid_lo > Fraction(-21,4)   # > -5.25
assert Fraction(-21,4) > Fraction(-11,2)

print("DEPTH4_EXACT_CERTIFICATE=PASS")
print(f"relation_hyperplanes={len(REL)}")
print(f"generated_row_spaces={len(spaces)}")
print(f"positive_feasible_row_spaces={len(feasible)}")
print(f"distinct_entropy_signatures={len(SIGNATURES)}")
print(f"central_interval_checks={checks}")
print("central_worst_upper_bound="
      f"{worst[0]} ~= {float(worst[0]):.12f}, "
      f"interval=[{worst[2]},{worst[3]}], "
      f"representative={reps[SIGNATURES[worst[1]]]}")
print("endpoint_fisher_constant_lower="
      f"{c_fisher} ~= {float(c_fisher):.12f} > 197/50")
print("endpoint_abs_second_derivative_sum_bound="
      f"{second_abs_bound} ~= {float(second_abs_bound):.12f} < 49")
print("endpoint_final_bound: H''(p) < -1/(50 p) for 0<p<=1/1000")
print(f"non_equal_tight_checks={tight_checks}")
print("non_equal_worst_upper_bound="
      f"{non_equal_worst[0]} ~= {float(non_equal_worst[0]):.12f}, "
      f"interval=[{non_equal_worst[2]},{non_equal_worst[3]}], "
      f"representative={reps[SIGNATURES[non_equal_worst[1]]]}")
print("all_equal_midpoint_Hpp_interval="
      f"[{equal_mid_lo},{equal_mid_hi}] ~= "
      f"[{float(equal_mid_lo):.12f},{float(equal_mid_hi):.12f}]")
print("all_equal_midpoint_formula=-16+log(46656)=-16+6log(6)")
print("extremal_separation: non-all-equal H''<-11/2 globally; "
      "all-equal H''(1/2)>-21/4")

print("patterns_by_support:")
for i, sig in enumerate(SIGNATURES, 1):
    print(f"{i:02d} support={len(sig):2d} rep={reps[sig]} signature={sig}")


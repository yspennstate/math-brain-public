r"""Check of: for the (weighted) uniform spanning tree, if A = [K] is a PRINCIPAL
increasing event and B is ANY increasing event, then P(A box B) <= P(A) P(B).

Proof (three lines, from Feder-Mihail negative association):
  A box B = {K subset of T} intersect B_K, where B_K is the up-set generated by those
  minimal witnesses of B that avoid K.  B_K depends only on coordinates in E \ K and is
  increasing, and {K subset of T} is increasing in the coordinates K, so the two are
  increasing functions of DISJOINT coordinate sets; negative association gives
  P(A box B) <= P(K subset of T) P(B_K) = P(A) P(B_K) <= P(A) P(B).

This script tests the conclusion by brute force with random edge weights, and separately
tests the negative-association step it rests on.
"""
import itertools, random, sys
from fractions import Fraction as Fr
from bk_ust import spanning_trees, forests
from graphs_iso import connected_iso

def run(nmax=5, mmax=7, trials=2, seed=3):
    rng=random.Random(seed)
    tested=0; viol=0; natested=0; naviol=0
    for n in range(3,nmax+1):
        for edges in connected_iso(n, mmax=mmax, min_edges=n-1):
            m=len(edges); ST=spanning_trees(n,edges)
            if len(ST)<2: continue
            F=[f for f in forests(n,edges)]
            for _ in range(trials):
                w=[Fr(rng.randint(1,6)) for _ in range(m)]
                wt=[]
                for t in ST:
                    p=Fr(1)
                    for b in range(m):
                        if t>>b&1: p*=w[b]
                    wt.append(p)
                W=sum(wt)
                def P(pred): return sum(wt[i] for i,t in enumerate(ST) if pred(t))/W
                # all principal A and all antichains B of size <= 2
                for K in F:
                    PA=P(lambda t,K=K: (t&K)==K)
                    if PA==0: continue
                    cands=[g for g in F]
                    for B in itertools.chain(((g,) for g in cands),
                                             ((g,h) for g,h in itertools.combinations(cands,2)
                                              if (g&h)!=g and (g&h)!=h)):
                        PB=P(lambda t,B=B: any((t&g)==g for g in B))
                        Pbox=P(lambda t,K=K,B=B: (t&K)==K and any((t&g)==g and (g&K)==0 for g in B))
                        tested+=1
                        if Pbox>PA*PB:
                            viol+=1
                            print("PRINCIPAL-A VIOLATION", n, edges, K, B, Pbox, PA*PB)
                # negative-association control: K and a fixed disjoint H
                for K in F:
                    for H in F:
                        if K&H: continue
                        PK=P(lambda t,K=K:(t&K)==K); PH=P(lambda t,H=H:(t&H)==H)
                        PKH=P(lambda t,K=K,H=H:(t&(K|H))==(K|H))
                        natested+=1
                        if PKH>PK*PH: naviol+=1; print("NA FAILS", n, edges, K, H)
    print("principal-A tests %d, violations %d"%(tested,viol))
    print("negative-association (two disjoint fixed sets) tests %d, violations %d"%(natested,naviol))

if __name__=="__main__":
    run(nmax=int(sys.argv[1]) if len(sys.argv)>1 else 5,
        mmax=int(sys.argv[2]) if len(sys.argv)>2 else 6)

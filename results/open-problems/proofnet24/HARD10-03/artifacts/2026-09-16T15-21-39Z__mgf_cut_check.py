# Rigorous log bounds using ln x = 2 sum_{k>=0} z^(2k+1)/(2k+1), z=(x-1)/(x+1).
def ln_bounds(x: Fraction, N: int = 140):
    assert x > 0
    if x < 1:
        lo, hi = ln_bounds(1/x, N)
        return -hi, -lo
    z = (x-1)/(x+1)
    zz = z*z
    p = z
    s = Fraction(0,1)
    for k in range(N):
        if k:
            p *= zz
        s += p/Fraction(2*k+1,1)
    lo = 2*s
    # Positive tail bounded by geometric domination since 1/(2j+1) <= 1/(2N+1) for j>=N.
    tail = 2*p*zz/(Fraction(2*N+1,1)*(1-zz))
    return lo, lo+tail

# e > sum_{j=0}^{M} 1/j!, hence 1/e < reciprocal of that partial sum.
def inv_e_upper(M: int = 70):
    s = Fraction(0,1)
    fact = 1
    for j in range(M+1):
        if j:
            fact *= j
        s += Fraction(1,fact)
    return 1/s

x = (1+u)/2

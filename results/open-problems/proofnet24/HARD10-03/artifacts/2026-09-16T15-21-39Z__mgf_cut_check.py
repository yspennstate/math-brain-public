# Bound e between partial sum and partial sum plus a rigorous factorial tail.
def e_bounds(M: int = 30):
    s = Fraction(0,1)
    fact = 1
    for j in range(M+1):
        if j:
            fact *= j
        s += Fraction(1,fact)
    # Tail sum_{j=M+1}^inf 1/j! <= 1/(M+1)! * 1/(1-1/(M+2)).
    fact_next = fact*(M+1)
    tail = Fraction(1,fact_next) * Fraction(M+2,M+1)
    return s, s+tail


assert {tau for tau,rp in uncovered}==SWAP

for key,terms in CERT.items():
    tau,rp=key
    lhs=external_coeff(tau,rp)
    rhs={s:F(0) for s in S4}
    for s,c in terms:
        rhs[s]+=c
        if s not in FACE:
            assert c>=0
    for I,J in generators:
        lv=sum(lhs[s]*indicator(I,J,s) for s in S4)
        rv=sum(rhs[s]*indicator(I,J,s) for s in S4)
        assert lv==rv, (key,I,J,lv,rv)


def indicator(I,J,sig):
    return F(int({sig[i] for i in I}==set(J)))

generators=[]
for k in (0,1,2):
    for I in combinations(range(4),k):
        for J in combinations(range(4),k):
            generators.append((I,J))
assert len(generators)==53

labels=[]
for tau in S4:
    rt=rho(tau)
    ders=[rp for rp in fibers if all(rp[i]!=rt[i] for i in range(3))]
    assert len(ders)==2
    labels.extend((tau,rp) for rp in ders)
assert len(labels)==48
assert len(CERT)==40


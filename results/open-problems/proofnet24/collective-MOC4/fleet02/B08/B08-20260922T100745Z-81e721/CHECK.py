matchings=[
    frozenset((frozenset((0,1)),frozenset((2,3)))),
    frozenset((frozenset((0,2)),frozenset((1,3)))),
    frozenset((frozenset((0,3)),frozenset((1,2)))),
]
def rho(sig):
    out=[]
    for m in matchings:
        image=frozenset(frozenset(sig[i] for i in pair) for pair in m)
        out.append(matchings.index(image))
    return tuple(out)

fibers={}
for s in S4: fibers.setdefault(rho(s),[]).append(s)
assert sorted(map(len,fibers.values())) == [4]*6

def external_coeff(tau,rp):
    c={s:F(0) for s in S4}
    for s in fibers[rho(tau)]: c[s]+=F(1,6)
    for s in fibers[rp]: c[s]+=F(1,6)
    c[tau]-=F(1,3)
    return c


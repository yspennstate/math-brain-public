def indicator(I,J,sig):
    return F(int({sig[i] for i in I}==set(J)))

generators=[]
for k in (0,1,2):
    for I in combinations(range(4),k):
        for J in combinations(range(4),k):
            generators.append((I,J))
assert len(generators)==53
assert len(FACE)==6

labels=[]
for tau in S4:
    rt=rho(tau)
    ders=[rp for rp in fibers if all(rp[i]!=rt[i] for i in range(3))]
    assert len(ders)==2
    labels.extend((tau,rp) for rp in ders)
assert len(labels)==48
assert set(CERT)==set(labels)

strict_outside_support=True
for key,terms in CERT.items():
    tau,rp=key
    lhs=external_coeff(tau,rp)
    rhs={s:F(0) for s in S4}
    outside_mass=F(0)
    for s,c in terms:
        rhs[s]+=c
        if s not in FACE:
            assert c>=0
            outside_mass+=c
    assert outside_mass>0
    for I,J in generators:
        lv=sum(lhs[s]*indicator(I,J,s) for s in S4)
        rv=sum(rhs[s]*indicator(I,J,s) for s in S4)
        assert lv==rv, (key,I,J,lv,rv)


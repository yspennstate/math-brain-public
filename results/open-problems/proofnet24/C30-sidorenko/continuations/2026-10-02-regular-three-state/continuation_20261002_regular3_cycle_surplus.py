"""Exact final cycle-surplus certificate on all regular three-state hosts.

The input density was regenerated by full ten-vertex enumeration in the
separate full_enumeration script. A distinct nine-state transfer audit
regenerates its entire polynomial without any vertex-assignment loop.
"""
import json
import math
from collections import Counter
from fractions import Fraction
from pathlib import Path
from continuation_20261002_regular3_full_enumeration import (
    multiply, power, linear, encode)


def main():
    original=json.loads(Path(__file__).with_name(
        'continuation_20261002_regular3_full_enumeration.json').read_text())
    D=linear([0,0,0,1])
    rbase={(0,2,0,0):1,(0,1,1,0):1,(0,0,2,0):1}
    results={}
    for cone in['I','T']:
        density={tuple(map(int,k.split(','))):v
                 for k,v in original['results'][cone]['density'].items()}
        s=linear([3,2,1,1] if cone=='I' else[6,4,2,2])
        r2={a:(v if cone=='I' else 4*v) for a,v in rbase.items()}
        C4=Counter({a:2*v for a,v in power(D,4).items()})
        C4.update({a:12*v for a,v in multiply(power(D,2),r2).items()})
        C4.update({a:2*v for a,v in power(r2,2).items()})
        C6=Counter({a:2*v for a,v in power(D,6).items()})
        C6.update({a:30*v for a,v in multiply(power(D,4),r2).items()})
        C6.update({a:30*v for a,v in multiply(power(D,2),power(r2,2)).items()})
        C6.update({a:2*v for a,v in power(r2,3).items()})
        fourth=multiply(power(s,11),C4)
        sixth=multiply(power(s,9),C6)
        gap4=Counter(density)
        gap4.subtract(power(s,15))
        gap4.subtract({a:5*v for a,v in fourth.items()})
        assert all(v>=0 for v in gap4.values())
        best=min((Fraction(gap4.get(a,0),v),a)
                 for a,v in sixth.items() if v>0)
        assert best[0]==Fraction(265,18)
        final=Counter({a:18*v for a,v in gap4.items()})
        final.subtract({a:265*v for a,v in sixth.items()})
        assert all(v>=0 for v in final.values())
        results[cone]={
            'row_sum_polynomial':encode(s),
            'C4_excess':encode(C4),'C6_excess':encode(C6),
            'integer_scaled_surplus_coefficients':encode(final),
            'integer_scaled_surplus_nonzero_terms':sum(bool(v) for v in final.values()),
            'integer_scaled_surplus_negative_terms':sum(v<0 for v in final.values()),
            'largest_coefficientwise_sixth_cycle_constant':str(best[0]),
            'limiting_monomial':best[1],
        }

    # A strictly positive three-state example obstructs sixth constant15.
    # P=W/3, Wdiag=49/50, Woff=101/100. In the second cone:
    # A=49/300, B=C=0, D=1/100, s=1, centered eigenvalues=-1/100.
    vals=[Fraction(49,300),Fraction(0),Fraction(0),Fraction(1,100)]
    density=original['results']['T']['density']
    F=sum(v*math.prod(vals[i]**a for i,a in enumerate(
        map(int,k.split(',')))) for k,v in density.items())
    eps=Fraction(1,100)
    target15=1+10*eps**4+30*eps**6
    difference=F-target15
    assert difference<0
    out={
        'status':'exact full-regular-three-state cycle-surplus certificate PASS',
        'fourth_cycle_constant':'5','sixth_cycle_constant':'265/18',
        'input_full_vertex_assignment_count':original['assignment_count'],
        'results':results,
        'coefficient15_failure':{
            'W_diagonal':'49/50','W_off_diagonal':'101/100',
            'density':str(F),'difference_from_coefficient15_threshold':str(difference),
        },
    }
    Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2))
    print(json.dumps({
        'status':out['status'],
        'coefficient_counts':{c:results[c]['integer_scaled_surplus_nonzero_terms']
                              for c in results},
        'sixth_cycle_constant':out['sixth_cycle_constant'],
        'coefficient15_failure':out['coefficient15_failure'],
    },indent=2))


if __name__=='__main__':
    main()

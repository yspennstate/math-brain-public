#!/usr/bin/env python3
"""
Exact finite self-check for NM13-02 / P0037.

Claim checked:
For the *uniform* spanning-tree law on every connected simple graph with at
most four vertices, the BK inequality
    P(A square B) <= P(A) P(B)
holds for all increasing events A,B.

No floating point arithmetic is used.

Reduction for rank r<=3 support:
If neither event is the whole space and A square B occurs on an r-edge
spanning tree, there are nonempty disjoint witnesses W_A,W_B contained in
that tree. Hence |W_A|,|W_B| <= r-1. Replacing each event by the increasing
event generated by its minimal witnesses of size <= r-1 leaves A square B
unchanged on the spanning-tree support, while it can only decrease each
marginal probability. Thus it suffices to enumerate those reduced events.

For n=4 (rank 3), every reduced event is uniquely represented by an
antichain of singleton and pair witnesses: after choosing the singleton
witnesses, any subset of pairs avoiding them may be chosen.
For n=3 (rank 2), only singleton witnesses matter.
"""
from itertools import combinations, permutations
from fractions import Fraction


def connected(n, edge_list):
    adj = [[] for _ in range(n)]
    for u, v in edge_list:
        adj[u].append(v)
        adj[v].append(u)
    seen = {0}
    stack = [0]
    while stack:
        u = stack.pop()
        for v in adj[u]:
            if v not in seen:
                seen.add(v)
                stack.append(v)
    return len(seen) == n


def canonical_graph_code(n, edge_list):
    E = {tuple(sorted(e)) for e in edge_list}
    best = None
    pairs = list(combinations(range(n), 2))
    for p in permutations(range(n)):
        bits = 0
        for i, (u, v) in enumerate(pairs):
            if tuple(sorted((p[u], p[v]))) in E:
                bits |= 1 << i
        if best is None or bits < best:
            best = bits
    return best


def graph_from_mask(n, mask):
    pairs = list(combinations(range(n), 2))
    return [pairs[i] for i in range(len(pairs)) if (mask >> i) & 1]


def spanning_trees(n, edges):
    ans = []
    for comb in combinations(range(len(edges)), n - 1):
        parent = list(range(n))

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        ok = True
        for i in comb:
            u, v = edges[i]
            ru, rv = find(u), find(v)
            if ru == rv:
                ok = False
                break
            parent[ru] = rv
        if ok and len({find(i) for i in range(n)}) == 1:
            ans.append(sum(1 << i for i in comb))
    return ans


def reduced_events(n, edges, trees):
    m = len(edges)
    r = n - 1
    max_w = r - 1
    contain = {}
    witnesses = []
    for k in range(1, max_w + 1):
        for comb in combinations(range(m), k):
            w = sum(1 << i for i in comb)
            cm = 0
            for ti, t in enumerate(trees):
                if (w & t) == w:
                    cm |= 1 << ti
            if cm:
                witnesses.append(w)
                contain[w] = cm

    if max_w == 1:
        events = []
        for s in range(1, 1 << m):
            ws = tuple(1 << i for i in range(m) if (s >> i) & 1)
            occ = 0
            for w in ws:
                occ |= contain[w]
            if occ:
                events.append((ws, occ))
        return events, contain

    assert max_w == 2
    pairs = [w for w in witnesses if w.bit_count() == 2]
    events = []
    for singles_mask in range(1 << m):
        singles = [1 << i for i in range(m) if (singles_mask >> i) & 1]
        allowed_pairs = [w for w in pairs if (w & singles_mask) == 0]
        for pair_choice in range(1 << len(allowed_pairs)):
            ws = singles + [
                allowed_pairs[j]
                for j in range(len(allowed_pairs))
                if (pair_choice >> j) & 1
            ]
            if not ws:
                continue
            occ = 0
            for w in ws:
                occ |= contain[w]
            if occ:
                events.append((tuple(ws), occ))
    return events, contain


def check_graph(n, edges):
    trees = spanning_trees(n, edges)
    Z = len(trees)
    if n == 2:
        return dict(trees=Z, events=0, compressed_checks=0, max_ratio=Fraction(1, 1))

    events, contain = reduced_events(n, edges, trees)
    N = len(events)
    m = len(edges)
    occ = [x[1] for x in events]
    count = [x.bit_count() for x in occ]

    singleton_mask = []
    q_without_edge = []
    for ws, _ in events:
        s = 0
        for w in ws:
            if w.bit_count() == 1:
                s |= w
        singleton_mask.append(s)
        q = []
        for e in range(m):
            bit = 1 << e
            qm = 0
            for w in ws:
                if (w & bit) == 0:
                    qm |= contain[w]
            q.append(qm)
        q_without_edge.append(q)

    # L[s][j] is the set of spanning trees on which event j has a witness
    # disjoint from at least one singleton edge named by s, with that edge
    # itself present. For rank <=3:
    # square(A,B)=L[S_A][B] union L[S_B][A].
    L = [[0] * N for _ in range(1 << m)]
    for s in range(1 << m):
        es = [e for e in range(m) if (s >> e) & 1]
        for j in range(N):
            v = 0
            for e in es:
                v |= contain[1 << e] & q_without_edge[j][e]
            L[s][j] = v

    groups = [[] for _ in range(1 << m)]
    for j, s in enumerate(singleton_mask):
        groups[s].append(j)

    # For a fixed singleton mask of A and group of B, only
    # (L[S_A][B], |B| on UST support) matters. Compress identical cases.
    patterns = {}
    for sa in range(1 << m):
        for sb in range(1 << m):
            patterns[(sa, sb)] = tuple(
                set((L[sa][j], count[j]) for j in groups[sb])
            )

    best = Fraction(0, 1)
    checks = 0
    for ai in range(N):
        sa = singleton_mask[ai]
        ca = count[ai]
        for sb in range(1 << m):
            base = L[sb][ai]
            for x, cb in patterns[(sa, sb)]:
                cs = (base | x).bit_count()
                checks += 1
                if ca and cb:
                    ratio = Fraction(Z * cs, ca * cb)
                    if ratio > best:
                        best = ratio
                    if ratio > 1:
                        raise AssertionError(
                            f"BK violation: n={n} edges={edges} "
                            f"A_index={ai} SA={sa} SB={sb} "
                            f"counts=({ca},{cb},{cs}) ratio={ratio}"
                        )
    return dict(trees=Z, events=N, compressed_checks=checks, max_ratio=best)


def main():
    # Independently enumerate graph isomorphism classes, then test one
    # representative of every connected simple class for n<=4.
    total_checks = 0
    for n in (2, 3, 4):
        M = len(list(combinations(range(n), 2)))
        reps = {}
        labeled_connected = 0
        for mask in range(1 << M):
            edges = graph_from_mask(n, mask)
            if connected(n, edges):
                labeled_connected += 1
                code = canonical_graph_code(n, edges)
                reps.setdefault(code, edges)
        expected_classes = {2: 1, 3: 2, 4: 6}[n]
        expected_labeled = {2: 1, 3: 4, 4: 38}[n]
        assert len(reps) == expected_classes
        assert labeled_connected == expected_labeled
        print(
            f"n={n} connected_labeled={labeled_connected} "
            f"isomorphism_classes={len(reps)}"
        )
        for code, edges in sorted(reps.items()):
            out = check_graph(n, edges)
            total_checks += out["compressed_checks"]
            print(
                "  "
                f"code={code} m={len(edges)} trees={out['trees']} "
                f"reduced_events={out['events']} "
                f"compressed_exact_checks={out['compressed_checks']} "
                f"max_ratio={out['max_ratio']}"
            )
    print(f"TOTAL_COMPRESSED_EXACT_CHECKS={total_checks}")
    print("ALL_EXACT_CHECKS_PASS")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Exact binary minimum-slice exclusion for Luo Conjecture 1 at |p|=9.

We do NOT decide pattern-language inclusion. We use only the necessary condition
    L(p) subseteq L(q) => (L(p) cap {0,1}^9) subseteq (L(q) cap {0,1}^9).
For |p|=9 the left slice is the full set of one-letter substitutions of p.
For |q|<9 the right slice is enumerated exactly over all positive image lengths
and all binary images having total output length 9.

If mu(p)<=mu(q), q of length <=4 is arithmetically impossible. Thus only
|q|=5,6,7,8 need finite checking. Equal-length pairs |q|=9 are handled by
an analytic lemma in the report (minimum-slice inclusion makes the inclusion
morphic; strict inclusion then forces mu(p)>mu(q)).
"""
from collections import Counter, defaultdict
from math import comb

N = 9


def patterns(n):
    """Canonical patterns over terminals 0,1 and variables 0,1,... by first occurrence."""
    pat = []

    def rec(pos, maxvar):
        if pos == n:
            yield tuple(pat)
            return
        for terminal in (-1, -2):  # -1=0, -2=1
            pat.append(terminal)
            yield from rec(pos + 1, maxvar)
            pat.pop()
        for v in range(maxvar + 2):  # old variables plus the next new variable
            pat.append(v)
            yield from rec(pos + 1, max(maxvar, v))
            pat.pop()

    yield from rec(0, -1)


def var_count(p):
    return len({x for x in p if x >= 0})


def min_words(p):
    """All length-|p| words generated by p; variables necessarily map to one bit."""
    vs = sorted({x for x in p if x >= 0})
    out = []
    for mask in range(1 << len(vs)):
        assignment = {x: (mask >> j) & 1 for j, x in enumerate(vs)}
        word = 0
        for s in p:
            bit = 0 if s == -1 else 1 if s == -2 else assignment[s]
            word = (word << 1) | bit
        out.append(word)
    return out


def slice_bits(q, out_len=N):
    """Exact bitset for L(q) intersect {0,1}^out_len."""
    m = len(q)
    excess = out_len - m
    if excess < 0:
        return 0
    vs = sorted({x for x in q if x >= 0})
    occ = Counter(x for x in q if x >= 0)

    extras = [0] * len(vs)
    length_vectors = []

    def rec(i, rem):
        if i == len(vs):
            if rem == 0:
                length_vectors.append(tuple(1 + e for e in extras))
            return
        k = occ[vs[i]]
        for e in range(rem // k + 1):
            extras[i] = e
            rec(i + 1, rem - k * e)
        extras[i] = 0

    rec(0, excess)

    bits = 0
    for lens in length_vectors:
        content_bits = sum(lens)
        for mask in range(1 << content_bits):
            assignment = {}
            shift = 0
            for x, L in zip(vs, lens):
                assignment[x] = tuple((mask >> (shift + j)) & 1 for j in range(L))
                shift += L
            word_bits = []
            for s in q:
                if s == -1:
                    word_bits.append(0)
                elif s == -2:
                    word_bits.append(1)
                else:
                    word_bits.extend(assignment[s])
            assert len(word_bits) == out_len
            word = 0
            for b in word_bits:
                word = (word << 1) | b
            bits |= 1 << word
    return bits


def bell_numbers(n):
    B = [1]
    for r in range(1, n + 1):
        B.append(sum(comb(r - 1, k) * B[k] for k in range(r)))
    return B


def canonical_count_formula(n, B):
    return sum(comb(n, k) * (2 ** (n - k)) * B[k] for k in range(n + 1))


# Generator sanity: exact canonical counts, including the published <=8 counts.
B = bell_numbers(N)
expected_counts = {n: canonical_count_formula(n, B) for n in range(1, N + 1)}
actual_counts = {n: sum(1 for _ in patterns(n)) for n in range(1, N + 1)}
assert actual_counts == expected_counts
print("CANONICAL_COUNTS", " ".join(f"{n}:{actual_counts[n]}" for n in range(1, N + 1)))
assert [actual_counts[n] for n in range(1, 9)] == [3, 10, 37, 151, 674, 3263, 17007, 94828]
assert actual_counts[9] == 562595

p9 = list(patterns(9))
p_by_v = defaultdict(list)
for p in p9:
    p_by_v[var_count(p)].append(p)

# q with |q|<=4 cannot satisfy mu(p)<=mu(q) when |p|=9:
# v(p)-v(q) >= 2(9-|q|) >= 10, but v(p)<=9.
# Build exact length-9 slices for the only arithmetically relevant q lengths.
qmeta = []
for m in (5, 6, 7, 8):
    d = N - m
    for q in patterns(m):
        vq = var_count(q)
        # Some vp<=9 can meet vp-vq >= 2d only if vq<=9-2d.
        if vq > N - 2 * d:
            continue
        bits = slice_bits(q, N)
        if bits:
            qmeta.append((q, m, vq, bits, bits.bit_count()))

print("QMETA_COUNT", len(qmeta))

# For each possible v(p), retain only q that could violate mu and whose slice
# is large enough even to contain the 2^v(p) minimum words of p. Build an
# inverted exact index word -> candidate-q bitset and intersect over M(p).
summary = []
for vp in range(0, N + 1):
    qarr = []
    need = 1 << vp
    for item in qmeta:
        q, m, vq, bits, card = item
        if vp - vq >= 2 * (N - m) and card >= need:
            qarr.append(item)

    pcount = len(p_by_v.get(vp, []))
    if not qarr:
        summary.append((vp, pcount, 0, 0))
        continue

    index = [0] * (1 << N)
    for j, item in enumerate(qarr):
        bits = item[3]
        x = bits
        while x:
            lsb = x & -x
            w = lsb.bit_length() - 1
            index[w] |= 1 << j
            x -= lsb
    all_q = (1 << len(qarr)) - 1

    survivors = 0
    for p in p_by_v[vp]:
        cand = all_q
        ws = min_words(p)
        # Rarest first is only an optimization; all words are checked exactly.
        ws.sort(key=lambda w: index[w].bit_count())
        for w in ws:
            cand &= index[w]
            if not cand:
                break
        if cand:
            survivors += cand.bit_count()
            # Fail loudly and print a concrete necessary-condition survivor.
            j = (cand & -cand).bit_length() - 1
            q, m, vq, bits, card = qarr[j]
            raise AssertionError(
                f"bad minimum-slice survivor: p={p}, vp={vp}, q={q}, |q|={m}, vq={vq}"
            )
    summary.append((vp, pcount, len(qarr), survivors))

for vp, pcount, qcount, survivors in summary:
    if pcount or qcount:
        print(f"VP {vp}: P9={pcount} Q_CANDIDATES={qcount} SURVIVORS={survivors}")

print("NO_BAD_MINIMUM_SLICE_PAIR_WITH_|p|=9_AND_|q|<=8")
print("EQUAL_LENGTH_|p|=|q|=9_IS_ANALYTIC_IN_REPORT")
print("ALL_EXACT_CHECKS_PASS")

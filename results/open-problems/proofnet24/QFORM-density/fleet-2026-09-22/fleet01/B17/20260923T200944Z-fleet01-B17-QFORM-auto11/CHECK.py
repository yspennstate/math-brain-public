import sympy as sp

sqrt=sp.sqrt
J=sp.diag(1,1,-1)
a=sp.Rational(57,32)
b=sp.Rational(15,4)
c=sp.Rational(3,4)

# Universal periodic-frame coefficient.
Cstar=sp.simplify((2*sqrt(a)+sqrt(c))**2)
cstar=sp.simplify(Cstar/20)
assert sp.simplify(Cstar-(63+2*sqrt(342))/8)==0
assert sp.simplify(b**2-4*a*c)>0

# Near-sharp four-row Parseval pattern: three equal rows in the positive plane,
# one row on the negative axis.
V=sp.Matrix([
    [sqrt(sp.Rational(2,3)),0,0],
    [-1/sqrt(6),1/sqrt(2),0],
    [-1/sqrt(6),-1/sqrt(2),0],
    [0,0,1]
])
assert sp.simplify(V.T*V-sp.eye(3))==sp.zeros(3)

def Esum(M):
    out=0
    for i in range(M.rows):
        s=sp.simplify(M[i,0]**2+M[i,1]**2)
        t=sp.simplify(M[i,2]**2)
        out += a*s**2+b*s*t+c*t**2
    return sp.factor(sp.simplify(out))

S0=Esum(V)
assert S0==sp.Rational(25,8)
base_n_coeff=sp.simplify(4*S0/20)
assert base_n_coeff==sp.Rational(5,8)
assert sp.N(base_n_coeff-cstar,30)>0

# Exact rational rotation, generated by the rational unit-quaternion formula
# from (100,1,2,3); it is close to I but genuinely mixes all spectral axes.
O=sp.Matrix([
    [4994,-298,203],
    [302,4997,-94],
    [-197,106,5002]
])/5007
assert sp.simplify(O.T*O-sp.eye(3))==sp.zeros(3)
W=sp.simplify(V*O.T)
assert sp.simplify(W.T*W-sp.eye(3))==sp.zeros(3)
A4=sp.simplify(W*J*W.T)
assert sp.simplify(A4**3-A4)==sp.zeros(4)
assert sp.simplify(sp.trace(A4)-1)==0
assert sp.simplify(sp.trace(A4**2)-3)==0
for z in A4:
    assert z != 0

Sd=Esum(W)
cd=sp.factor(Sd/5) # because n=4m and correction is Sd/(20m)=cd/n
assert Sd==sp.Rational(1554220767867635,496598405422144)
assert cd==sp.Rational(310844153573527,496598405422144)
assert cd>cstar

# Latest fleet02/B17 global separated-bank constant.
K=2*sqrt(2)*sp.asin(sp.Rational(4,5))+sqrt(5)*(sp.pi/2-sp.asin(sp.Rational(4,5)))
assert sp.N(K,50) < sp.N(3*sqrt(2),50)

print('QFORM_B17_SHARP_PERIODIC_FRAME_CHECK_PASS')
print('Cstar =', sp.N(Cstar,30))
print('cstar =', sp.N(cstar,30))
print('base r=4 coefficient =', sp.N(base_n_coeff,30))
print('base gap to cstar =', sp.N(base_n_coeff-cstar,30))
print('dense Esum =', Sd)
print('dense n^{-1} coefficient =', sp.N(cd,30))
print('dense gap to cstar =', sp.N(cd-cstar,30))
print('min |A4_ij| =', min(abs(sp.N(z,30)) for z in A4))
print('K_partner =', sp.N(K,30))
print('3sqrt2-K_partner =', sp.N(3*sqrt(2)-K,30))

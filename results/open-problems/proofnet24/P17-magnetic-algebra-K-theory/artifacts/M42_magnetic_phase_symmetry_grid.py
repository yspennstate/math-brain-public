from math import exp

Q1 = P1 = 153
Q2 = P2 = 148
r = 0.4
A = exp(-(1 - 2*r))

HULL_NUMERATOR = 4.0 * 3.141592653589793 * r * A * (1.0/Q1 + 1.0/Q2)
BLOCH_NUMERATOR = 2.0 * 3.141592653589793 * A * (1.0/P1 + 1.0/P2)
TOTAL_NUMERATOR = HULL_NUMERATOR + BLOCH_NUMERATOR


def burnside_orbit_count(N: int) -> int:
    assert N > 0 and N % 2 == 0
    if N % 4 == 0:
        return N**4 // 8 + 3 * N**2 // 2 + 4
    return N**4 // 8 + N**2 + 2


def enumerate_orbits(N: int):
    assert N > 0 and N % 2 == 0

    def s1(x):
        a1, a2, b1, b2 = x
        return ((-a1) % N, a2, b1, (-b2) % N)

    def s2(x):
        a1, a2, b1, b2 = x
        return (a1, (-a2) % N, (-b1) % N, b2)

    def chiral(x):
        a1, a2, b1, b2 = x
        return (a1, a2, (b1 + N//2) % N, b2)

    unseen = {
        (a1, a2, b1, b2)
        for a1 in range(N)
        for a2 in range(N)
        for b1 in range(N)
        for b2 in range(N)
    }
    sizes = {}
    count = 0
    while unseen:
        seed = next(iter(unseen))
        orbit = {seed}
        changed = True
        while changed:
            changed = False
            for x in tuple(orbit):
                for f in (s1, s2, chiral):
                    y = f(x)
                    if y not in orbit:
                        orbit.add(y)
                        changed = True
        unseen.difference_update(orbit)
        count += 1
        sizes[len(orbit)] = sizes.get(len(orbit), 0) + 1
    return count, sizes


def m41_equal_grid_budget(N: int) -> float:
    return TOTAL_NUMERATOR / N



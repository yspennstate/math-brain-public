import sympy as s
x,r,L,T=s.symbols('x r L T',positive=True)
a=x/(1+x);c=x*r/(1+x*r)
v=s.factor(2*a*(1-a)+c*(1-c));p=(1-a)**2*(1-c);mu=s.factor(2*a+c)
W=s.factor((1-p)*v-p*mu**2)
print('W',W,flush=True)
F11=s.factor(4*((1-p)-2*p*mu/(1-a)+p*v/(1-a)**2)/W)
F12=s.factor(2*((1-p)-p*mu*(1/(1-a)+1/(1-c))+p*v/((1-a)*(1-c)))/W)
F22=s.factor(((1-p)-2*p*mu/(1-c)+p*v/(1-c)**2)/W)
print('F11',F11,'F12',F12,'F22',F22,flush=True)
detF=s.factor(4*p*(c-a)**2/((1-a)**2*(1-c)**2*W))
m=(L+x*r*T)/(1+x*r);t=(L+x*T)/(1+x)
detG=s.factor(detF-2*m*F22+4*t*F12-4*t**2)
num,den=s.fraction(detG)
print('den',s.factor(den),flush=True)
P=s.Poly(num,x)
print('degree',P.degree(),flush=True)
for (k,),coeff in reversed(P.terms()):print('coefficient',k,s.factor(coeff),flush=True)

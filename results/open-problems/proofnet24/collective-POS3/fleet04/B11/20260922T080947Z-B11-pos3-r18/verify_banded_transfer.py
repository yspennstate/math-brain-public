"""Exact finite regression for the bounded-incomparability band lemmas.

Enumerates every transitive closure generated by forward relations on [n], n<=6;
for each naturally labelled poset it checks:
  (1) every incomparable pair in the reference extension has span <= 2K-1;
  (2) every cover has span <= 2K+1;
  (3) every linear extension moves each element by at most its incomparability degree.
The arbitrary-size claims in REPORT.md are proved symbolically; this is regression only.
"""


def transitive_closure(n, relmask):
    pairs = [(i, j) for i in range(n) for j in range(i + 1, n)]
    adj = [[False] * n for _ in range(n)]
    for k, (i, j) in enumerate(pairs):
        if (relmask >> k) & 1:
            adj[i][j] = True
    for k in range(n):
        for i in range(n):
            if adj[i][k]:
                for j in range(n):
                    if adj[k][j]:
                        adj[i][j] = True
    out = 0
    for k, (i, j) in enumerate(pairs):
        if adj[i][j]:
            out |= 1 << k
    return out, adj


def all_top_sorts(n, adj):
    preds = [0] * n
    for i in range(n):
        for j in range(n):
            if adj[i][j]:
                preds[j] |= 1 << i
    full = (1 << n) - 1
    count = 0

    def rec(used, seq):
        nonlocal count
        if used == full:
            count += 1
            pos = [0] * n
            for r, v in enumerate(seq, start=1):
                pos[v] = r
            for v in range(n):
                if abs(pos[v] - (v + 1)) > inc[v]:
                    raise AssertionError(("displacement", n, v, pos[v], inc[v]))
            return
        for v in range(n):
            if not ((used >> v) & 1) and (preds[v] & ~used) == 0:
                rec(used | (1 << v), seq + [v])

    inc = []
    for i in range(n):
        inc.append(sum(1 for j in range(n)
                       if i != j and not (adj[i][j] or adj[j][i])))
    rec(0, [])
    return count


def is_cover(i, j, adj, n):
    if not adj[i][j]:
        return False
    return not any(k != i and k != j and adj[i][k] and adj[k][j]
                   for k in range(n))


def main():
    grand_posets = 0
    grand_extensions = 0
    for n in range(2, 7):
        m = n * (n - 1) // 2
        closures = {}
        for mask in range(1 << m):
            cl, adj = transitive_closure(n, mask)
            closures.setdefault(cl, adj)

        ext_count = 0
        for adj in closures.values():
            inc = []
            for i in range(n):
                inc.append(sum(1 for j in range(n)
                               if i != j and not (adj[i][j] or adj[j][i])))
            K = max(inc, default=0)

            for i in range(n):
                for j in range(i + 1, n):
                    if not (adj[i][j] or adj[j][i]):
                        if j - i > 2 * K - 1:
                            raise AssertionError(("incomparable-span", n, i, j, K))
                    if is_cover(i, j, adj, n) and j - i > 2 * K + 1:
                        raise AssertionError(("cover-span", n, i, j, K))

            ext_count += all_top_sorts(n, adj)

        grand_posets += len(closures)
        grand_extensions += ext_count
        print(f"n={n} closures={len(closures)} extensions={ext_count}")

    print("POS3_BANDED_TRANSFER_REGRESSION_PASS")
    print("closures_total", grand_posets)
    print("extensions_total", grand_extensions)


if __name__ == "__main__":
    main()

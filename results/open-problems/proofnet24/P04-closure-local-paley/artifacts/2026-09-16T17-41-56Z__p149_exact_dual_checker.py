#!/usr/bin/env python3
from fractions import Fraction
from hashlib import sha256

P = 149
X = Fraction(-643, 1000)
T = Fraction(813, 100)

def is_prime(n):
    if n < 2:
        return False
    d = 2
    while d*d <= n:
        if n % d == 0:
            return False
        d += 1
    return True

assert is_prime(P)
assert P % 4 == 1
QR = {a*a % P for a in range(1, P)}
V = sorted(v for v in QR if (v-1) % P in QR)
n = len(V)
assert n == (P-5)//4 == 36

A = [[0]*n for _ in range(n)]
edge_count = 0
for i in range(n):
    for j in range(i+1, n):
        if (V[i]-V[j]) % P in QR:
            A[i][j] = A[j][i] = 1
            edge_count += 1
assert edge_count == 300

# Exact S_3 action generated by r(v)=1-v and s(v)=1/v.
def inv(v):
    return pow(v, -1, P)
def orbit(v):
    seen = set()
    stack = [v]
    while stack:
        w = stack.pop()
        if w in seen:
            continue
        seen.add(w)
        stack.extend([(1-w) % P, inv(w)])
    return seen

Vset = set(V)
orbits = []
seen = set()
for v in V:
    if v not in seen:
        O = orbit(v)
        assert O <= Vset
        orbits.append(O)
        seen |= O
assert seen == Vset
assert len(orbits) == 6 and all(len(O) == 6 for O in orbits)

# Each generator preserves adjacency on V exactly.
for u in V:
    for v in V:
        if u == v:
            continue
        e = ((u-v) % P) in QR
        ru, rv = (1-u) % P, (1-v) % P
        su, sv = inv(u), inv(v)
        assert ((((ru-rv) % P) in QR) == e)
        assert ((((su-sv) % P) in QR) == e)

# B has B_ii=1, B_ij=1 on graph edges, and X on graph nonedges.
B = [[Fraction(0) for _ in range(n)] for __ in range(n)]
for i in range(n):
    for j in range(n):
        if i == j or A[i][j] == 1:
            B[i][j] = Fraction(1)
        else:
            B[i][j] = X

# M = T I - B.  Exact LDL^T without pivoting.
M = [[(T if i == j else Fraction(0)) - B[i][j]
      for j in range(n)] for i in range(n)]
L = [[Fraction(0) for _ in range(n)] for __ in range(n)]
D = [Fraction(0)]*n
for i in range(n):
    L[i][i] = Fraction(1)
    D[i] = M[i][i] - sum(L[i][k]*L[i][k]*D[k] for k in range(i))
    assert D[i] > 0
    for j in range(i+1, n):
        L[j][i] = (M[j][i] - sum(L[j][k]*L[i][k]*D[k] for k in range(i))) / D[i]

# Reconstruct M exactly as a self-check.
for i in range(n):
    for j in range(n):
        rec = sum(L[i][k]*D[k]*L[j][k] for k in range(min(i,j)+1))
        assert rec == M[i][j]

# Exact comparison T < (2/3)*sqrt(P), squared because T>0.
gap = Fraction(4*P, 9) - T*T
assert T > 0 and gap > 0
assert gap == Fraction(11279, 90000)

pivot_payload = "\n".join(f"{d.numerator}/{d.denominator}" for d in D).encode()
print("P04-I0101-P149-EXACT-DUAL-CERTIFICATE=PASS")
print(f"p={P}; n={n}; edges={edge_count}")
print(f"x={X.numerator}/{X.denominator}; t={T.numerator}/{T.denominator}")
print(f"threshold_square_gap={gap.numerator}/{gap.denominator}")
print(f"s3_orbits={len(orbits)}x6")
print(f"positive_ldl_pivots={len(D)}")
print(f"pivot_sha256={sha256(pivot_payload).hexdigest()}")

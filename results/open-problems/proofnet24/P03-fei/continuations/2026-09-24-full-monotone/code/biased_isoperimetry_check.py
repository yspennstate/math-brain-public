"""Check of the p-biased edge-isoperimetric inequality for increasing sets,
    p * I_p(A) >= mu_p(A) * log_p(mu_p(A)),   I_p(A) = sum_i Pr_p[x and x^i differ in membership],
(1) on every increasing subset of {0,1}^m for m <= 4 (all up-sets, by brute force over antichains of minimal sets),
    and on 20000 random increasing sets for m = 5, 6, at p in a grid of (0, 1/2];
(2) through the two-point inequality behind the usual induction on m:
    (1-p) phi(a) + p phi(b) + p (b - a) >= phi((1-p) a + p b)   for 0 <= a <= b <= 1,  phi(x) = x log_p x,
    on a grid.
"""
import itertools, math, random, functools
print = functools.partial(print, flush=True)


def phi(x, p):
    return 0.0 if x <= 0 else x * math.log(x) / math.log(p)


def upsets(m):
    pts = list(range(1 << m))
    # all up-sets: generated by antichains; brute force over subsets for m <= 4 (2^16 subsets)
    for mask in range(1 << (1 << m)):
        A = [x for x in pts if mask >> x & 1]
        S = set(A)
        ok = all((y in S) for x in A for i in range(m) for y in [x | (1 << i)])
        if ok:
            yield S


def check_set(S, m, p):
    mu = 0.0; I = 0.0
    for x in range(1 << m):
        w = 1.0
        for i in range(m):
            w *= p if x >> i & 1 else 1 - p
        if x in S:
            mu += w
        for i in range(m):
            if ((x in S) != ((x ^ (1 << i)) in S)):
                I += w
    return p * I - phi(mu, p), mu


def random_upset(m, rng):
    k = rng.randint(1, 6)
    gens = [rng.randrange(1 << m) for _ in range(k)]
    return {x for x in range(1 << m) if any((x & g) == g for g in gens)}


def main():
    ps = [0.5, 0.4, 0.3, 0.2, 0.1, 0.05, 0.01, 0.001]
    worst = (1e9, None)
    for m in range(1, 5):
        cnt = 0
        for S in upsets(m):
            cnt += 1
            for p in ps:
                d, mu = check_set(S, m, p)
                if d < worst[0]:
                    worst = (d, (m, sorted(S), p, mu))
        print(f"m={m}: {cnt} up-sets checked")
    rng = random.Random(1)
    for m in (5, 6):
        for _ in range(20000):
            S = random_upset(m, rng)
            p = rng.choice(ps)
            d, mu = check_set(S, m, p)
            if d < worst[0]:
                worst = (d, (m, 'random', p, mu))
        print(f"m={m}: 20000 random up-sets checked")
    print("smallest p*I - mu*log_p(mu):", worst[0], "at", str(worst[1])[:120])
    tw = 1e9
    for p in ps:
        for i in range(0, 401):
            a = i / 400
            for j in range(i, 401):
                b = j / 400
                lhs = (1 - p) * phi(a, p) + p * phi(b, p) + p * (b - a)
                rhs = phi((1 - p) * a + p * b, p)
                tw = min(tw, lhs - rhs)
    print("two-point inequality: smallest lhs - rhs on the grid:", tw)


if __name__ == "__main__":
    main()

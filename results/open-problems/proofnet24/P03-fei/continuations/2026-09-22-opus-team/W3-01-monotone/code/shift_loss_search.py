"""Adversarial search for the entropy lost when a monotone function is shifted to a regular one.

For monotone f put f* = the result of applying S_ij (shift j -> i) for all i < j until stable, after
relabelling the coordinates by decreasing influence (ties by index).  I(f*) = I(f) exactly.
Annealing over monotone f (toggle a point while keeping an up-set) maximises

    loss(f) = (H(f) - H(f*)) / I(f).

FEI for all monotone functions is equivalent to sup loss < infinity (given H <= 14.2142 I on regular
functions); the test bed gives loss <= 1.29.
Usage: python shift_loss_search.py N STEPS RESTARTS SEED
"""
import sys, math, time
import numpy as np
import numba as nb
from monolib import setup_process
from regular_search import wht_HI


@nb.njit(cache=True)
def influences(f, n):
    N = 1 << n
    inf = np.zeros(n)
    for i in range(n):
        c = 0
        for x in range(N):
            if (x >> i) & 1 == 0:
                if f[x] != f[x | (1 << i)]:
                    c += 1
        inf[i] = 2.0 * c / N
    return inf


@nb.njit(cache=True)
def shift_full(f, n):
    N = 1 << n
    inf = influences(f, n)
    order = np.argsort(-inf, kind='mergesort')   # order[0] = most influential
    # relabel: new coordinate p <- old coordinate order[p]
    g = np.zeros(N, dtype=np.bool_)
    for x in range(N):
        y = 0
        for p in range(n):
            if (x >> order[p]) & 1:
                y |= (1 << p)
        g[y] = f[x]
    changed = True
    while changed:
        changed = False
        for i in range(n):
            for j in range(i + 1, n):
                bi = 1 << i
                bj = 1 << j
                for x in range(N):
                    if (x & bi) == 0 and (x & bj) != 0:
                        y = x ^ (bi | bj)
                        if g[x] and not g[y]:
                            g[x] = False
                            g[y] = True
                            changed = True
    return g


@nb.njit(cache=True)
def loss(f, n):
    H, I = wht_HI(f, n)
    if I < 1e-12:
        return 0.0, 0.0, 0.0
    g = shift_full(f, n)
    Hg, Ig = wht_HI(g, n)
    return (H - Hg) / I, H / I, Ig - I


@nb.njit(cache=True)
def can_toggle(f, n, x):
    if f[x]:
        for k in range(n):
            if (x >> k) & 1 and f[x & ~(1 << k)]:
                return False
        return True
    else:
        for k in range(n):
            if not (x >> k) & 1 and not f[x | (1 << k)]:
                return False
        return True


@nb.njit(cache=True)
def anneal(n, steps, seed, T0, T1):
    np.random.seed(seed)
    N = 1 << n
    f = np.zeros(N, dtype=np.bool_)
    # start: random up-set generated by a few random sets near the middle
    for g in range(np.random.randint(2, 2 * n)):
        a = 0
        for k in range(n):
            if np.random.random() < 0.5:
                a |= (1 << k)
        for x in range(N):
            if (x & a) == a:
                f[x] = True
    cur, hi, dI = loss(f, n)
    best = cur
    bestf = f.copy()
    maxdI = abs(dI)
    for t in range(steps):
        T = T0 * (T1 / T0) ** (t / steps)
        found = False
        for _ in range(2000):
            x = np.random.randint(0, N)
            if can_toggle(f, n, x):
                found = True
                break
        if not found:
            continue
        f[x] = not f[x]
        val, hi, dI = loss(f, n)
        if abs(dI) > maxdI:
            maxdI = abs(dI)
        if val >= cur or np.random.random() < math.exp((val - cur) / T):
            cur = val
            if cur > best:
                best = cur
                bestf = f.copy()
        else:
            f[x] = not f[x]
    return best, bestf, maxdI


def main():
    setup_process()
    n = int(sys.argv[1]); steps = int(sys.argv[2]); R = int(sys.argv[3]); seed = int(sys.argv[4])
    t0 = time.time()
    overall = -1.0
    for r in range(R):
        best, bestf, maxdI = anneal(n, steps, seed + r, 0.05, 0.001)
        l, hi, dI = loss(bestf, n)
        print(f"n={n} restart {r}: max (H - H(f*))/I = {best:.6f} (H/I = {hi:.4f}, |f^-1(1)| = {int(bestf.sum())}); "
              f"max |I(f*) - I(f)| seen = {maxdI:.2e}", flush=True)
        if best > overall:
            overall = best
            np.save(f"../logs/shift_loss_best_n{n}.npy", bestf.astype(np.uint8))
    print(f"n={n}: overall max loss found = {overall:.6f} ({time.time()-t0:.0f}s)")


if __name__ == "__main__":
    main()

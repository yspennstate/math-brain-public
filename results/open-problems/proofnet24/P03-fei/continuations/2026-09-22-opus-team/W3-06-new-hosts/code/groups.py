"""Permutation groups used as symmetry hosts (degree 9..13), given by generators; normaliser elements for anti-maps."""
import itertools
import numpy as np


def close(gens, m, limit=200000):
    idp = tuple(range(m))
    G = {idp}
    frontier = [idp]
    while frontier:
        nf = []
        for g in frontier:
            for h in gens:
                k = tuple(h[g[i]] for i in range(m))
                if k not in G:
                    G.add(k); nf.append(k)
                    if len(G) > limit:
                        raise ValueError('group too large')
        frontier = nf
    return sorted(G)


def affine_line(p, mults):
    """x -> a x + b on Z_p, a in the multiplicative subgroup generated by mults."""
    gens = [tuple((x + 1) % p for x in range(p))]
    for a in mults:
        gens.append(tuple((a * x) % p for x in range(p)))
    return gens


def psl2_p_on_line(p):
    """PSL(2,p) on the projective line {0..p-1, inf=p}: x->x+1, x->a^2 x, x->-1/x."""
    inf = p
    def t(x): return inf if x == inf else (x + 1) % p
    def inv(x):
        if x == inf: return 0
        if x == 0: return inf
        return (-pow(x, p - 2, p)) % p
    sq = [(a * a) % p for a in range(1, p)]
    g = max(set(sq), key=lambda s: len({pow(s, k, p) for k in range(p)}))  # generator of squares
    def mul(x): return inf if x == inf else (g * x) % p
    return [tuple(t(x) for x in range(p + 1)), tuple(mul(x) for x in range(p + 1)), tuple(inv(x) for x in range(p + 1))]


def pgl2_p_on_line(p):
    gens = psl2_p_on_line(p)
    # add x -> n x for a non-square n
    sq = {(a * a) % p for a in range(1, p)}
    n = next(a for a in range(2, p) if a not in sq)
    gens.append(tuple(p if x == p else (n * x) % p for x in range(p + 1)))
    return gens


def grid_group(r, c, transpose=False, rowgens='S', colgens='S'):
    """S_r x S_c (or cyclic) on the r x c grid, variable r_i*c + c_j; optional transpose when r == c."""
    def P(f):
        return tuple(f(i // c, i % c) for i in range(r * c))
    gens = []
    if rowgens == 'S':
        gens += [P(lambda a, b: ((a + 1) % r) * c + b), P(lambda a, b: ((1 - a) if a < 2 else a) * c + b)]
    elif rowgens == 'C':
        gens += [P(lambda a, b: ((a + 1) % r) * c + b)]
    if colgens == 'S':
        gens += [P(lambda a, b: a * c + (b + 1) % c), P(lambda a, b: a * c + ((1 - b) if b < 2 else b))]
    elif colgens == 'C':
        gens += [P(lambda a, b: a * c + (b + 1) % c)]
    if transpose:
        assert r == c
        gens.append(P(lambda a, b: b * c + a))
    return gens


def graph_edge_group(nv, edges, vgens):
    idx = {tuple(sorted(e)): i for i, e in enumerate(edges)}
    out = []
    for g in vgens:
        out.append(tuple(idx[tuple(sorted((g[a], g[b])))] for (a, b) in edges))
    return out


def sym_gens(n):
    return [tuple((i + 1) % n for i in range(n)), tuple([1, 0] + list(range(2, n)))]


def normaliser_elements(G, m, max_perms=4_000_000, gens=None):
    """All pi in S_m with pi G pi^-1 = G (brute force; m <= 10).  pi g pi^-1 in G for every generator g of G
    implies pi G pi^-1 = G (finite group, same order), so only generators are tested."""
    Gs = set(G)
    if gens is None:
        import random
        rnd = random.Random(1)
        gens = rnd.sample(G, min(6, len(G)))
    res = []
    for pi in itertools.permutations(range(m)):
        inv = [0] * m
        for i, v in enumerate(pi):
            inv[v] = i
        ok = True
        for g in gens:
            # pi g pi^-1 : i -> pi[g[inv[i]]]
            h = tuple(pi[g[inv[i]]] for i in range(m))
            if h not in Gs:
                ok = False; break
        if ok:
            res.append(pi)
    return res


def coset_reps(N, G, m):
    """representatives of N/G (right cosets pi G)."""
    Gs = set(G)
    reps = []
    seen = set()
    for pi in N:
        if pi in seen:
            continue
        reps.append(pi)
        for g in G:
            seen.add(tuple(pi[g[i]] for i in range(m)))
    return reps

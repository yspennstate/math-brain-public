"""Signed orbits of a group acting on {0,1}^m by coordinate permutations, optionally
composed with complementation x -> ~x together with negation of the value
(anti-automorphisms).  A G-invariant partial core satisfies c0(g x) = s_g c0(x).

orbit_structure(m, gens) with gens = list of (perm, s), s = +1 plain, s = -1 dual.
Returns (rep, sgn, forced_zero): rep[x] = orbit index, sgn[x] = sign with
c0(x) = sgn[x] * v[rep[x]]; forced_zero[o] = True if the orbit is forced to 0.
"""
import numpy as np


def apply(x, perm, s, m):
    y = 0
    for i in range(m):
        if (x >> i) & 1:
            y |= 1 << perm[i]
    if s < 0:
        y ^= (1 << m) - 1
    return y


def orbit_structure(m, gens):
    N = 1 << m
    parent = list(range(N))
    rel = [1] * N  # sign of x relative to parent

    def find(x):
        # returns (root, sign of x relative to root)
        s = 1
        path = []
        while parent[x] != x:
            path.append(x)
            s *= rel[x]
            x = parent[x]
        root = x
        # path compression
        acc = 1
        for y in reversed(path):
            pass
        # recompute signs along path
        for y in path:
            # sign of y relative to root
            t = 1; z = y
            while parent[z] != z:
                t *= rel[z]; z = parent[z]
            parent[y] = root; rel[y] = t
        return root, s

    conflict = set()
    for x in range(N):
        for perm, s in gens:
            y = apply(x, perm, s, m)
            rx, sx = find(x)
            ry, sy = find(y)
            # c0(y) = s * c0(x)  ->  sy v(ry) = s sx v(rx)
            if rx == ry:
                if sy != s * sx:
                    conflict.add(rx)
            else:
                parent[ry] = rx
                rel[ry] = s * sx * sy
    roots = {}
    rep = np.zeros(N, dtype=np.int64); sgn = np.zeros(N, dtype=np.int64)
    for x in range(N):
        r, s = find(x)
        if r not in roots:
            roots[r] = len(roots)
        rep[x] = roots[r]; sgn[x] = s
    forced = np.zeros(len(roots), dtype=bool)
    for r in conflict:
        forced[roots[find(r)[0]]] = True
    return rep, sgn, forced


def orbit_sizes(rep, n_orb):
    return np.bincount(rep, minlength=n_orb)


def c0_from_values(v, rep, sgn):
    return (sgn * v[rep]).astype(np.int64)


def values_from_c0(c0, rep, sgn, n_orb):
    v = np.zeros(n_orb, dtype=np.int64)
    seen = np.zeros(n_orb, dtype=bool)
    for x in range(len(c0)):
        o = rep[x]
        val = sgn[x] * c0[x]
        if seen[o]:
            if v[o] != val:
                raise ValueError("c0 not invariant")
        else:
            v[o] = val; seen[o] = True
    return v


def group_closure(gens, m):
    """All elements (as (perm tuple, s)) of the group generated by gens."""
    ident = (tuple(range(m)), 1)
    elems = {ident}
    frontier = [ident]
    while frontier:
        new = []
        for p, s in frontier:
            for q, t in gens:
                # composition: first p then q  (x -> q(p(x)))
                r = tuple(q[p[i]] for i in range(m))
                e = (r, s * t)
                if e not in elems:
                    elems.add(e); new.append(e)
        frontier = new
    return elems

"""Core library for group W3-02 (transitive-symmetric functions).

Conventions (as in CONTEXT.md): f: {-1,1}^n -> {-1,1} stored as a +-1 numpy array of length 2^n,
entry x = f(x) where bit i of x is 1 iff x_i = -1 ("true").  Characters chi_S(x) = (-1)^{|S & x|}.
fhat(S) = 2^-n sum_x f(x) chi_S(x).  Entropy in bits.

Group machinery: a permutation group on [n] is given by generators (lists perm with perm[i] = image
of coordinate i).  The same permutation acts on inputs x and on spectral sets S (both are masks);
fhat is constant on orbits of S when f is invariant (fhat(gS) = fhat(S)).
"""
import numpy as np


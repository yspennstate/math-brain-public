def setup_process(cores=(2, 3, 10, 11, 12, 13, 14, 15)):
    try:
        import psutil
        p = psutil.Process()
        p.nice(psutil.BELOW_NORMAL_PRIORITY_CLASS)
        p.cpu_affinity(list(cores))
    except Exception as e:  # pragma: no cover
        print("setup_process warning:", e)


def popcount(a):
    return np.bitwise_count(np.asarray(a, dtype=np.uint64)).astype(np.int64)


def wht(f):
    """Normalised Walsh-Hadamard transform: returns fhat (float64 array)."""
    a = np.array(f, dtype=np.float64).copy()
    N = a.shape[0]
    n = N.bit_length() - 1
    h = 1
    while h < N:
        a = a.reshape(-1, 2, h)
        x = a[:, 0, :].copy()
        y = a[:, 1, :]
        a[:, 0, :] = x + y
        a[:, 1, :] = x - y
        a = a.reshape(N)
        h *= 2
    return a / N


def phi(t):
    """t log2(1/t) with 0 log 0 = 0 (t = squared coefficient)."""
    t = np.asarray(t, dtype=np.float64)
    out = np.zeros_like(t)
    m = t > 0
    out[m] = -t[m] * np.log2(t[m])
    return out


def spectral_stats(f):
    n = len(f).bit_length() - 1
    c = wht(f)
    p = c * c
    sizes = popcount(np.arange(len(f)))
    H = float(phi(p).sum())
    I = float((sizes * p).sum())
    return H, I, c


# ---------------------------------------------------------------- permutation groups

def perm_masks(perm, n):
    """Image of every mask 0..2^n-1 under coordinate permutation perm (i -> perm[i])."""
    x = np.arange(1 << n, dtype=np.int64)
    img = np.zeros_like(x)
    for i in range(n):
        img |= ((x >> i) & 1) << int(perm[i])
    return img


def orbit_labels(gens, n):
    """Orbit labels (0..k-1) of all masks under the group generated by gens.
    Returns labels, reps (a representative mask per orbit), sizes (orbit sizes)."""
    N = 1 << n
    imgs = [perm_masks(g, n) for g in gens]
    lab = np.arange(N, dtype=np.int64)
    while True:
        old = lab
        new = lab.copy()
        for im in imgs:
            # propagate min along x -> g(x) and back
            np.minimum(new, new[im], out=new)
            tmp = new.copy()
            np.minimum.at(tmp, im, new)
            new = tmp
        if np.array_equal(new, old):
            break
        lab = new
    uniq, inv, counts = np.unique(lab, return_inverse=True, return_counts=True)
    reps = uniq  # min mask of each orbit
    return inv.astype(np.int64), reps.astype(np.int64), counts.astype(np.int64)


def group_closure(gens, n, limit=10**6):
    """All elements of the group generated by gens (as tuples)."""
    idt = tuple(range(n))
    elems = {idt}
    frontier = [idt]
    gens = [tuple(int(v) for v in g) for g in gens]
    while frontier:
        nf = []
        for e in frontier:
            for g in gens:
                h = tuple(g[e[i]] for i in range(n))  # i -> e[i] -> g[e[i]]
                if h not in elems:
                    elems.add(h)
                    nf.append(h)
                    if len(elems) > limit:
                        raise RuntimeError("group too large")
        frontier = nf
    return elems


def is_transitive(gens, n):
    seen = {0}
    fr = [0]
    while fr:
        nf = []
        for i in fr:
            for g in gens:
                j = int(g[i])
                if j not in seen:
                    seen.add(j)
                    nf.append(j)
        fr = nf
    return len(seen) == n


class InvariantSpace:
    """Boolean functions invariant under a permutation group, evaluated through orbit sums.

    classes = orbits of inputs (= orbits of spectral sets).  For a class vector F in {+-1}^k,
    fhat on orbit o equals sum_c F[c] K[c,o] with K[c,o] = 2^-n sum_{x in c} chi_{rep_o}(x).
    """

    def __init__(self, gens, n, name=""):
        self.n = n
        self.name = name
        self.gens = [np.array(g, dtype=np.int64) for g in gens]
        self.lab, self.reps, self.osize = orbit_labels(self.gens, n)
        self.k = len(self.reps)
        self.level = popcount(self.reps)
        N = 1 << n
        masks = np.arange(N, dtype=np.int64)
        K = np.zeros((self.k, self.k))
        for o, r in enumerate(self.reps):
            sgn = 1.0 - 2.0 * (popcount(masks & r) & 1)
            K[:, o] = np.bincount(self.lab, weights=sgn, minlength=self.k) / N
        self.K = K
        self.transitive = is_transitive(gens, n)

    def truth_table(self, F):
        return np.asarray(F, dtype=np.float64)[self.lab]

    def coeffs(self, F):
        return np.asarray(F, dtype=np.float64) @ self.K

    def stats(self, F):
        c = self.coeffs(F)
        p = c * c
        H = float((self.osize * phi(p)).sum())
        I = float((self.osize * self.level * p).sum())
        mean = float(c[0]) if self.reps[0] == 0 else None
        return H, I, c

    def orbit_stats(self, F):
        """H, I, H(orbit), E log2|orbit|, H(|S|), E|S|log2(e n/|S|) restricted to S nonempty."""
        c = self.coeffs(F)
        p = c * c
        w = self.osize * p           # mass of each orbit
        H = float((self.osize * phi(p)).sum())
        I = float((self.level * w).sum())
        Horb = float(phi(w).sum())
        Elog = float((w * np.log2(self.osize)).sum())
        lev = np.bincount(self.level, weights=w, minlength=self.n + 1)
        Hlev = float(phi(lev).sum())
        ks = np.arange(self.n + 1)
        with np.errstate(divide='ignore', invalid='ignore'):
            t = np.where(ks > 0, ks * np.log2(np.e * self.n / np.maximum(ks, 1)), 0.0)
        naive = float((lev * t).sum())
        return dict(H=H, I=I, Horb=Horb, Elog=Elog, Hlev=Hlev, naive=naive, mean=float(c[0]))


# ---------------------------------------------------------------- common groups

def cyclic_gens(n):
    return [[(i + 1) % n for i in range(n)]]


def dihedral_gens(n):
    return [[(i + 1) % n for i in range(n)], [(-i) % n for i in range(n)]]


def pairs_index(m):
    idx = {}
    k = 0
    for a in range(m):
        for b in range(a + 1, m):
            idx[(a, b)] = k
            k += 1
    return idx


def graph_gens(m):
    """S_m acting on the C(m,2) edges of K_m."""
    idx = pairs_index(m)
    n = len(idx)

    def induced(sig):
        g = [0] * n
        for (a, b), e in idx.items():
            u, v = sig[a], sig[b]
            if u > v:
                u, v = v, u
            g[e] = idx[(u, v)]
        return g
    t = list(range(m)); t[0], t[1] = 1, 0
    c = [(i + 1) % m for i in range(m)]
    return [induced(t), induced(c)], n, idx


def hypergraph3_gens(m):
    """S_m acting on the C(m,3) triples."""
    from itertools import combinations
    trip = list(combinations(range(m), 3))
    idx = {t: i for i, t in enumerate(trip)}
    n = len(trip)

    def induced(sig):
        g = [0] * n
        for t, e in idx.items():
            g[e] = idx[tuple(sorted(sig[v] for v in t))]
        return g
    t = list(range(m)); t[0], t[1] = 1, 0
    c = [(i + 1) % m for i in range(m)]
    return [induced(t), induced(c)], n, idx


def bipartite_gens(a, b, transpose=True):
    """S_a x S_b acting on the a*b edges of K_{a,b} (edge (r,c) -> r*b+c); plus transpose if a==b."""
    n = a * b

    def ind(rs, cs, tr=False):
        g = [0] * n
        for r in range(a):
            for c in range(b):
                if tr:
                    g[r * b + c] = cs[c] * b + rs[r]
                else:
                    g[r * b + c] = rs[r] * b + cs[c]
        return g
    ida, idb = list(range(a)), list(range(b))
    gens = []
    if a > 1:
        t = ida[:]; t[0], t[1] = 1, 0
        gens.append(ind(t, idb))
        c = [(i + 1) % a for i in range(a)]
        gens.append(ind(c, idb))
    if b > 1:
        t = idb[:]; t[0], t[1] = 1, 0
        gens.append(ind(ida, t))
        c = [(i + 1) % b for i in range(b)]
        gens.append(ind(ida, c))
    if transpose and a == b:
        gens.append(ind(ida, idb, tr=True))
    return gens, n


def wreath_gens(w, s):
    """S_w wr S_s: blocks of size w; coordinates b*w + j."""
    n = w * s
    gens = []
    if w > 1:
        g = list(range(n)); g[0], g[1] = 1, 0
        gens.append(g)
        g = list(range(n))
        for j in range(w):
            g[j] = (j + 1) % w
        gens.append(g)
    if s > 1:
        g = list(range(n))
        for j in range(w):
            g[j], g[w + j] = w + j, j
        gens.append(g)
        g = [((i // w + 1) % s) * w + (i % w) for i in range(n)]
        gens.append(g)
    return gens, n


def affine_line_gens(p):
    """AGL(1,p) on Z_p (p prime): x -> x+1, x -> g x (g a primitive root)."""
    def primroot(p):
        for g in range(2, p):
            if all(pow(g, (p - 1) // q, p) != 1 for q in range(2, p) if (p - 1) % q == 0 and all(q % r for r in range(2, q))):
                return g
        return 1
    g = primroot(p)
    return [[(i + 1) % p for i in range(p)], [(g * i) % p for i in range(p)]]


def translations_F2(k):
    """Regular action of Z_2^k on itself."""
    n = 1 << k
    return [[i ^ (1 << j) for i in range(n)] for j in range(k)]

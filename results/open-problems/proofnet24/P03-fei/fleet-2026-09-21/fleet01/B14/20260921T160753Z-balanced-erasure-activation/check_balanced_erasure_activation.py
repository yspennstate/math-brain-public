#!/usr/bin/env python3
"""Regression checks for the balanced-composition erasure activation identity.

This is a finite checker for the analytic theorem in REPORT.md.  It does not
claim a proof of FEI.  It uses only local truth tables and NumPy.
"""

import json
import math
import random
import numpy as np


def fwht(vals):
    a = np.asarray(vals, dtype=float).copy()
    n = a.size
    h = 1
    while h < n:
        z = a.reshape(-1, 2 * h)
        x = z[:, :h].copy()
        y = z[:, h:].copy()
        z[:, :h] = x + y
        z[:, h:] = x - y
        a = z.reshape(n)
        h *= 2
    return a / n


def spectral(vals):
    a = fwht(vals)
    return a * a


def influences(p, n):
    idx = np.arange(1 << n)
    return np.array([p[(idx & (1 << i)) != 0].sum() for i in range(n)])


def erasures(p, n):
    out = np.zeros(n)
    for i in range(n):
        bit = 1 << i
        for s in range(1 << n):
            if s & bit:
                continue
            a, b = float(p[s]), float(p[s | bit])
            z = a + b
            if z == 0.0:
                continue
            if a > 0.0:
                out[i] -= a * math.log2(a / z)
            if b > 0.0:
                out[i] -= b * math.log2(b / z)
    return out


def compose(outer, m, inner, r):
    out = np.empty(1 << (m * r), dtype=np.int8)
    block_mask = (1 << r) - 1
    for x in range(out.size):
        outer_index = 0
        for j in range(m):
            y = (x >> (j * r)) & block_mask
            bit = 0 if int(inner[y]) == 1 else 1
            outer_index |= bit << j
        out[x] = outer[outer_index]
    return out


def activation(p_outer, m, i, c):
    bit = 1 << i
    ans = 0.0
    for t in range(1 << m):
        if t & bit:
            continue
        a = float(p_outer[t])
        b = float(p_outer[t | bit])
        z = a + c * b
        if z == 0.0 or a == 0.0 or c * b == 0.0:
            continue
        q = c * b / z
        ans += z * (-q * math.log2(q) - (1.0 - q) * math.log2(1.0 - q))
    return ans


def predicted_coordinate_erasures(outer, m, inner, r):
    po = spectral(outer)
    pi = spectral(inner)
    alpha = influences(po, m)
    b_inner = erasures(pi, r)
    pred = []
    for i in range(m):
        for x in range(r):
            c = float(pi[1 << x])
            pred.append(alpha[i] * b_inner[x] + activation(po, m, i, c))
    return np.asarray(pred)


def random_balanced(n, rng):
    N = 1 << n
    neg = rng.sample(range(N), N // 2)
    vals = np.ones(N, dtype=np.int8)
    vals[neg] = -1
    return vals


def seed4():
    # Balanced monotone upper set generated by {0,1}, {1,2}, {0,3}.
    vals = np.ones(16, dtype=np.int8)
    for x in range(16):
        b = [(x >> j) & 1 for j in range(4)]
        if (b[0] and b[1]) or (b[1] and b[2]) or (b[0] and b[3]):
            vals[x] = -1
    return vals


def main():
    rng = random.Random(1409)
    max_identity_error = 0.0
    min_upper_slack = float("inf")
    cases = 0

    for _ in range(200):
        m = rng.choice((2, 3))
        r = rng.choice((2, 3))
        outer = np.array([rng.choice((-1, 1)) for _ in range(1 << m)], dtype=np.int8)
        inner = random_balanced(r, rng)
        whole = compose(outer, m, inner, r)

        actual = erasures(spectral(whole), m * r)
        pred = predicted_coordinate_erasures(outer, m, inner, r)
        max_identity_error = max(max_identity_error, float(np.max(np.abs(actual - pred))))

        po, pi = spectral(outer), spectral(inner)
        bo, bi = erasures(po, m), erasures(pi, r)
        inf_o = float(influences(po, m).sum())
        w1 = sum(float(pi[1 << x]) for x in range(r))
        e1 = sum(float(pi[1 << x]) * math.log2(1.0 / float(pi[1 << x]))
                 for x in range(r) if pi[1 << x] > 0)
        upper = inf_o * float(bi.sum()) + w1 * float(bo.sum()) + inf_o * e1
        min_upper_slack = min(min_upper_slack, upper - float(actual.sum()))
        cases += 1

    g = seed4()
    pg = spectral(g)
    I = float(influences(pg, 4).sum())
    B = float(erasures(pg, 4).sum())
    W1 = sum(float(pg[1 << x]) for x in range(4))
    E1 = sum(float(pg[1 << x]) * math.log2(1.0 / float(pg[1 << x]))
             for x in range(4) if pg[1 << x] > 0)
    q = W1 / I

    # Exact activation recurrence numerically, compressed by the two singleton
    # weights 1/4 (twice) and 1/16 (twice).
    bcur = B
    depth_ratios = {1: B / I}
    for depth in range(2, 21):
        r = depth - 1
        # At depth r, singleton square c=4^{-(r+k)} occurs 2^r*C(r,k) times.
        activ = 0.0
        for i in range(4):
            for k in range(r + 1):
                c = 4.0 ** (-(r + k))
                multiplicity = (2 ** r) * math.comb(r, k)
                activ += multiplicity * activation(pg, 4, i, c)
        bcur = I * bcur + activ
        depth_ratios[depth] = bcur / (I ** depth)

    c0 = 2.0 / (math.e * math.log(2.0))
    bound_limit = (B / I) / (1.0 - q) + (E1 / I) / ((1.0 - q) ** 2)

    result = {
        "status": "PASS",
        "random_balanced_composition_cases": cases,
        "max_coordinate_identity_abs_error": max_identity_error,
        "min_summed_upper_bound_slack": min_upper_slack,
        "level1_entropy_linear_constant_2_over_e_ln2": c0,
        "seed4": {
            "I": I,
            "Bsum": B,
            "Bsum_over_I": B / I,
            "W1": W1,
            "W1_over_I": q,
            "E1": E1,
            "E1_over_I": E1 / I,
            "analytic_uniform_self_composition_upper_bound": bound_limit,
            "actual_recurrence_Bsum_over_I_depths": {
                str(k): depth_ratios[k] for k in (1, 2, 3, 4, 5, 8, 10, 15, 20)
            },
        },
        "full_FEI_proved": False,
    }
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()

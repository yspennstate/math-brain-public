coeff = {}
bank = F(0)
for lam,p,q in TERMS:
    for x,a in ((fold(p),q),(fold(q),p),(fold(p*q),-1)):
        coeff[x] = coeff.get(x,F(0)) + lam*a
    bank += lam*p*q*(1-p)*(1-q)

target = {F(3,8):-F(57,256), F(967,2048):F(1)}
coeff.pop(F(1,2), None)
coeff = {x:a for x,a in coeff.items() if a}
assert coeff == target, (coeff,target)

KAPPA = F(2900397572141,42924444221440)
assert bank == KAPPA

d0 = F(88057,5000000)          # 0.0176114
A  = F(32275607,125000000)     # 0.258204856
assert d0 - KAPPA*A == F(882852438006487413,5365555527680000000000)
assert d0 > KAPPA*A

a = F(1078193,1048576)
Emin = (d0-KAPPA*A)/(a+4*KAPPA)
assert Emin == F(882852438006487413,6967304280623000000000)

